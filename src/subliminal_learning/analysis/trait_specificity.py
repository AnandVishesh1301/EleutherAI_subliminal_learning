def summarize_pooled_receivers(df: pd.DataFrame, n_boot: int = 2000, seed: int = 0,
                               prompt_set: str = "test") -> pd.DataFrame:
    """Same-model effect per (trait, animal) with the four receivers POOLED into one series.

    Same difference of means as `summarize`, but treatment and control runs are pooled across the
    four same-model receivers (``orig``/``fs1``/``fs2``/``fs3``) instead of being reported per
    receiver: **effect = mean over the pooled treatment runs of $p_a$ $-$ mean over the pooled
    control runs of $p_a$**. The 95% CI is the same cluster bootstrap
    (`cluster_bootstrap_mean_difference`) with cluster = (receiver, teacher) -- 40 clusters, so the
    interval covers receiver-level as well as teacher-level variation -- and the controls (the four
    receivers' 30-cell control sets) resampled by row.

    Args:
        df: Output of `load_specificity_runs`.
        n_boot: Bootstrap replicates.
        seed: RNG seed.
        prompt_set: Which scored prompt set to read (``"test"`` or ``"off_topic"``).

    Returns:
        Frame with ``trait, animal, effect, lo, hi, n_treat, n_ctrl, n_clusters``, traits in
        `TRAITS` order and animals in `ANIMALS10` order.
    """
    df = _pick(df, prompt_set)
    sm = df[df.condition == SAME]
    out = []
    for trait, sub in sm.groupby("trait", sort=False):
        treat, ctrl = sub[sub.arm == "treatment"], sub[sub.arm == "control"]
        for a in ANIMALS10:
            t, c = treat[treat.animal == a], ctrl[ctrl.animal == a]
            if t.empty or c.empty:
                continue
            clusters = (t.receiver + "|" + t.teacher).to_numpy()
            effect, lo, hi = cluster_bootstrap_mean_difference(
                t.p.to_numpy(), clusters, c.p.to_numpy(), n_boot=n_boot, seed=seed)
            out.append({"trait": trait, "animal": a, "effect": effect, "lo": lo, "hi": hi,
                        "n_treat": len(t), "n_ctrl": len(c), "n_clusters": len(set(clusters))})
    res = pd.DataFrame(out)
    return (res.assign(_t=res.trait.map({t: i for i, t in enumerate(TRAITS)}),
                       _a=res.animal.map({a: i for i, a in enumerate(ANIMALS10)}))
            .sort_values(["_t", "_a"]).drop(columns=["_t", "_a"]).reset_index(drop=True))


def _draw_trait_vs_others(ax, lifts: pd.DataFrame, *,
                          ylabel: str = "p(student) $-$ p(control)",
                          legend_loc: str = "upper center",
                          legend_bbox: tuple[float, float] = (0.62, 0.99),
                          value_labels: bool = False, legend: bool = True,
                          control_label: bool = True) -> None:
    """Draw the own-trait vs. other-animal lift panel (same-model rows) on ``ax``.

    Every variant shares the y label and carries no per-point value labels; only the legend
    placement differs between the standalone figure and panel B of `plot_specificity_combined`
    (which is narrower). ``legend=False`` / ``control_label=False`` drop the key and the
    "= control" annotation, for the second panel of `plot_trait_vs_others_sets`.
    """
    import matplotlib.pyplot as plt

    sm = lifts[lifts.condition == SAME]
    models = [m for m in SAME_MODELS if m in set(sm.receiver)]
    pos = {m: i for i, m in enumerate(models)}
    traits = [t for t in TRAITS if t in set(sm.trait)]
    ylo: list[float] = []
    yhi: list[float] = []
    marks: list[tuple[float, float, str, int]] = []
    for trait in traits:
        color = TRAIT_COLORS[trait]
        for q, ls in (("trait", "-"), ("others", "--")):
            d = sm[(sm.trait == trait) & (sm.quantity == q)]
            if d.empty:
                continue
            d = d.assign(x=d.receiver.map(pos)).sort_values("x")
            ylo.append(float(d.lo.min()))
            yhi.append(float(d.hi.max()))
            ax.fill_between(d.x, d.lo, d.hi, color=color, alpha=BAND_ALPHA, lw=0, zorder=2)
            ax.plot(d.x, d.lift, ls, color=color, lw=2, zorder=3)
            ax.plot(d.x, d.lift, "o", ms=8, color=color, mec="white", mew=2, ls="none", zorder=4)
            if q == "trait":
                marks.extend((float(xx), float(vv), color, traits.index(trait))
                             for xx, vv in zip(d.x, d.lift))
    # Traits can land within a label height of each other at one receiver: nudge the value labels
    # apart vertically and put alternating traits on opposite sides of their marker.
    if value_labels:
        span = max(yhi) - min(ylo)
        for x in sorted({m[0] for m in marks}):
            prev = -np.inf
            for _, v, color, k in sorted((m for m in marks if m[0] == x), key=lambda m: m[1]):
                prev = max(v, prev + 0.05 * span)
                side = -1 if k % 2 == 0 else 1
                ax.annotate(f"{v:+.3f}", (x, prev), textcoords="offset points",
                            xytext=(10 * side, 4), ha="right" if side < 0 else "left",
                            fontsize=9.5, color=color)
    ax.set_xticks(list(pos.values()))
    ax.set_xticklabels(models, fontsize=11, color=TEXT)
    ax.set_xlim(-0.35, len(models) - 0.65)
    _style_axis(ax, ylabel)
    _set_ylim(ax, ylo, yhi)
    if control_label:
        ax.annotate("= control", (len(models) - 0.7, 0.0), xytext=(-2, 5),
                    textcoords="offset points", fontsize=9.5, color="0.45", va="bottom",
                    ha="right")
    entries = ([(plt.Line2D([], [], color=TRAIT_COLORS[t], lw=2.6), t) for t in traits]
               + [(plt.Line2D([], [], ls="none"), " "),
                  (plt.Line2D([], [], color="0.45", lw=2.2, ls="-"), "solid = trait"),
                  (plt.Line2D([], [], color="0.45", lw=2.2, ls="--"), "dashed = non-trait")])
    # Inside the axes, in whichever empty region the caller picked.
    if legend:
        ax.legend(*zip(*entries), title="teacher trait", loc=legend_loc,
                  bbox_to_anchor=legend_bbox, frameon=True, framealpha=0.9, edgecolor="none",
                  facecolor="white", fontsize=10.5, title_fontsize=10.5, labelcolor=TEXT)


def _draw_pooled_animals(ax, pooled: pd.DataFrame) -> None:
    """Draw the pooled-receiver per-animal panel (one line per teacher trait) on ``ax``.

    Linear y over the range spanned by the effects and their bands.
    """
    import matplotlib.pyplot as plt

    traits = [t for t in TRAITS if t in set(pooled.trait)]
    for trait in traits:
        d = pooled[pooled.trait == trait]
        color = TRAIT_COLORS[trait]
        xi = np.array([ANIMALS10.index(a) for a in d.animal], dtype=float)
        o = np.argsort(xi)
        xi = xi[o]
        y, lo, hi = d.effect.to_numpy()[o], d.lo.to_numpy()[o], d.hi.to_numpy()[o]
        for seg in _segments(xi):
            ax.fill_between(xi[seg], lo[seg], hi[seg], color=color, alpha=BAND_ALPHA, lw=0,
                            zorder=2)
            ax.plot(xi[seg], y[seg], "-", color=color, lw=2, zorder=3)
        ax.plot(xi, y, "o", ms=8, color=color, mec="white", mew=2, ls="none", zorder=4)
    ax.set_xticks(np.arange(len(ANIMALS10)))
    ax.set_xticklabels(ANIMALS10, rotation=45, ha="right", fontsize=10.5, color=TEXT)
    ax.set_xlim(-0.5, len(ANIMALS10) - 0.4)
    _style_axis(ax, "p(student) $-$ p(control)")
    ax.grid(axis="x", color="0.95", lw=0.8)
    ylo, yhi = float(pooled.lo.min()), float(pooled.hi.max())
    pad = 0.06 * max(yhi - ylo, 1e-3)
    ax.set_ylim(min(ylo, 0.0) - pad, max(yhi, 0.0) + pad)
    ax.annotate("= control", (len(ANIMALS10) - 0.45, 0.0), xytext=(-2, 4),
                textcoords="offset points", fontsize=9.5, color="0.45", va="bottom", ha="right")
    ax.legend([plt.Line2D([], [], color=TRAIT_COLORS[t], lw=2.6) for t in traits], traits,
              title="teacher trait", loc="upper right", frameon=True, framealpha=0.9,
              edgecolor="none", facecolor="white", fontsize=10.5, title_fontsize=10.5,
              labelcolor=TEXT)


