"""Per-receiver trait specificity of subliminal transfer, treatment vs. matched trait-free control.

One question: when a **dog** teacher's numbers are distilled into a student, does the student's
preference rise for dog only, or for animals generally? This module reads the three landed arms
that can answer it *with a matched control*, on the same 10 teachers x 30 student cells:

* **same-model** -- receiver == sender, for ``orig``/``fs1``/``fs2``/``fs3``, ten animals read off
  the endpoint row of ``eval/pref_traj.json``;
* **cross-model** -- the 12 ordered sender != receiver pairs over those four inits, four animals
  (dog/cat/lion/pig) read from ``preference_summary.json`` (dog at the run root, the others under
  ``eval/<animal>/``);
* **cross-data-order** -- receiver ``ds1``, sender ``orig``, ten animals from ``pref_traj.json``.

Every arm's control is the trait-free ``controls/base/<receiver>/teacher-<sender>/`` run: the same
student cells distilled from numbers generated by the *untuned* sender base, so "any distillation
on number data shifts animal tokens" is subtracted rather than assumed away.

The statistic is a **difference of means** (not a new metric), in probability units: mean treatment
``p_a`` minus mean control ``p_a``, with a cluster bootstrap whose treatment unit is the teacher
(same-model) or the (sender, teacher) pair (cross-model) -- see `summarize`.
"""
from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

from subliminal_learning.stats.core import (
    cluster_bootstrap_mean_difference,
    cluster_bootstrap_ratio_of_medians,
)

#: Ten animals, teacher trait first, then the nine non-target ones (figure x-axis order).
ANIMALS10 = ["dog", "cat", "lion", "pig", "rabbit", "chicken", "deer", "tiger", "cow", "elephant"]
#: The four animals the cross-model arm was re-scored on.
ANIMALS4 = ["dog", "cat", "lion", "pig"]
TARGET = "dog"
POOL = "ex10-20_prefix_n100k"
#: Display name -> model directory, in figure panel order.
MODELS = {"orig": "pythia-160m", "fs1": "pythia-160m-seed1", "fs2": "pythia-160m-seed2",
          "fs3": "pythia-160m-seed3", "ds1": "pythia-160m-data-seed1"}
SAME_MODELS = ["orig", "fs1", "fs2", "fs3"]
SAME, CROSS, XDO = "same-model", "cross-model", "cross-data-order"


def _load(path: Path):
    try:
        return json.loads(path.read_text())
    except Exception:
        return None


def _traj_p(path: Path) -> dict[str, float] | None:
    """Endpoint per-animal ``p_target`` from a ``pref_traj.json`` (the ``checkpoints`` row)."""
    d = _load(path)
    if d is None:
        return None
    end = [pt for pt in d["points"] if pt.get("checkpoint") == "checkpoints"]
    if len(end) != 1:
        return None
    test = end[0]["test"]
    out = {a: test[a]["p_target"] for a in ANIMALS10
           if a in test and test[a].get("p_target") is not None}
    return out if TARGET in out else None


def _test_summary(d: dict) -> dict:
    return next(s for s in d["summaries"] if s["prompt_set"] == "test")


def _summary_p(run_dir: Path, *, is_ctrl: bool) -> dict[str, float] | None:
    """Per-animal ``p_target_mean`` on ``test`` from a cross-model run's preference summaries.

    Treatment runs carry dog at the run root (``target_animal == "dog"``) and the other animals
    under ``eval/<animal>/``; controls carry all four under ``eval/<animal>/`` (with a legacy
    root-dog fallback). ``target_animal`` is asserted on every file read.
    """
    root = _load(run_dir / "preference_summary.json")
    if root is None:
        return None
    out: dict[str, float] = {}
    if not is_ctrl:
        if root.get("target_animal") != TARGET:
            return None
        out[TARGET] = _test_summary(root)["p_target_mean"]
    for a in ANIMALS4:
        if a == TARGET and not is_ctrl:
            continue
        q = _load(run_dir / "eval" / a / "preference_summary.json")
        if q is None:
            if a == TARGET and root.get("target_animal") == TARGET:
                out[TARGET] = _test_summary(root)["p_target_mean"]
            continue
        if q.get("target_animal") != a:
            continue
        out[a] = _test_summary(q)["p_target_mean"]
    return out if TARGET in out else None


def _jobs(output_root: Path, teachers: list[str], cells: list[str]) -> list[tuple]:
    """Enumerate ``(kind, receiver, sender, condition, teacher, cell, arm, path)`` reads."""
    jobs: list[tuple] = []
    for recv, cond, senders in ([(m, SAME, [m]) for m in SAME_MODELS]
                                + [(r, CROSS, [s for s in SAME_MODELS if s != r])
                                   for r in SAME_MODELS]
                                + [("ds1", XDO, ["orig"])]):
        kind = "summ" if cond == CROSS else "traj"
        R, tail = MODELS[recv], "" if cond == CROSS else "/ftseed1/eval/pref_traj.json"
        for send in senders:
            S = MODELS[send]
            lineage = output_root / "dog" / R / f"teacher-{S}"
            ctrl = output_root / "controls" / "base" / R / f"teacher-{S}" / POOL
            for t in teachers:
                for c in cells:
                    jobs.append((kind, recv, send, cond, t, c, "treatment",
                                 Path(f"{lineage / t / POOL / c}{tail}")))
            for c in cells:
                jobs.append((kind, recv, send, cond, "", c, "control",
                             Path(f"{ctrl / c}{tail}")))
    return jobs


def load_specificity_runs(output_root: Path, *, root: Path | None = None,
                          max_workers: int = 32) -> pd.DataFrame:
    """Read every treatment/control run of the three arms into one long frame.

    Args:
        output_root: The ``students`` output root (CephFS; reads are threaded).
        root: Repo root holding ``run_logs/`` (default: the parent of this package's repo).
        max_workers: Thread-pool width for the JSON reads.

    Returns:
        Long frame with columns ``receiver, sender, condition, teacher, cell, arm, animal, p``
        (one row per run x animal) plus ``n_missing`` / ``n_runs`` recorded in ``df.attrs``.
    """
    root = root or Path(__file__).resolve().parents[3]
    teachers = [f"{t}_tseed1" for t in
                json.loads((root / "run_logs" / "dog_top10_kband_configs.json").read_text())
                ["param_tags"]]
    cells = [c["student_tag"] for c in
             json.loads((root / "run_logs" / "core30_cells.json").read_text())["cells"]]
    jobs = _jobs(Path(output_root), teachers, cells)

    def run(job):
        kind, *_, arm, path = job
        p = _traj_p(path) if kind == "traj" else _summary_p(path, is_ctrl=arm == "control")
        return job, p

    with ThreadPoolExecutor(max_workers) as ex:
        results = list(ex.map(run, jobs))

    rows, missing = [], 0
    for (_, recv, send, cond, t, c, arm, _path), p in results:
        if p is None:
            missing += 1
            continue
        for a, v in p.items():
            rows.append({"receiver": recv, "sender": send, "condition": cond, "teacher": t,
                         "cell": c, "arm": arm, "animal": a, "p": float(v)})
    df = pd.DataFrame(rows)
    df.attrs["n_missing"] = missing
    df.attrs["n_jobs"] = len(jobs)
    return df


def coverage(df: pd.DataFrame) -> pd.DataFrame:
    """Runs read per (receiver, condition, arm): distinct runs, teachers/senders and cells."""
    key = ["receiver", "condition", "arm"]
    g = df[df.animal == TARGET].groupby(key)
    return (g.agg(n_runs=("p", "size"), n_senders=("sender", "nunique"),
                  n_teachers=("teacher", "nunique"), n_cells=("cell", "nunique"))
            .reset_index())


def summarize(df: pd.DataFrame, n_boot: int = 2000, seed: int = 0,
              stat: str = "diff") -> pd.DataFrame:
    """Treatment-minus-control effect per receiver, condition and animal, with a cluster bootstrap.

    The statistic (``stat="diff"``, the default): for each (receiver, condition, animal),
    **effect = mean over treatment runs of $p_a$ minus mean over control runs of $p_a$**, in
    probability units, treatment runs pooled over all teachers x cells (x senders for cross-model).
    ``stat="ratio"`` keeps the older median-ratio effect. The 95% interval is a cluster bootstrap --
    treatment CLUSTERS resampled with replacement (cluster = teacher for same-model, (sender,
    teacher) for cross-model / cross-data-order), keeping every cell of a resampled cluster, with
    the control runs (cells) resampled independently; 2000 reps, seed 0, percentile interval.

    Args:
        df: Output of `load_specificity_runs`.
        n_boot: Bootstrap replicates.
        seed: RNG seed (shared by every row, so the table is reproducible).
        stat: ``"diff"`` (difference of means) or ``"ratio"`` (ratio of medians).

    Returns:
        Frame with ``receiver, condition, animal, effect, lo, hi, n_treat, n_ctrl, n_clusters``;
        ``df.attrs["stat"]`` records which statistic was used.
    """
    if stat not in ("diff", "ratio"):
        raise ValueError(f"stat must be 'diff' or 'ratio', got {stat!r}")
    boot = cluster_bootstrap_mean_difference if stat == "diff" else \
        cluster_bootstrap_ratio_of_medians
    out = []
    for (recv, cond), sub in df.groupby(["receiver", "condition"], sort=False):
        treat, ctrl = sub[sub.arm == "treatment"], sub[sub.arm == "control"]
        for a in ANIMALS10:
            t, c = treat[treat.animal == a], ctrl[ctrl.animal == a]
            if t.empty or c.empty:
                continue
            clusters = (t.teacher if cond == SAME else t.sender + "|" + t.teacher).to_numpy()
            effect, lo, hi = boot(t.p.to_numpy(), clusters, c.p.to_numpy(),
                                  n_boot=n_boot, seed=seed)
            out.append({"receiver": recv, "condition": cond, "animal": a, "effect": effect,
                        "lo": lo, "hi": hi, "n_treat": len(t), "n_ctrl": len(c),
                        "n_clusters": len(set(clusters))})
    order = {m: i for i, m in enumerate(MODELS)}
    res = pd.DataFrame(out)
    res = (res.assign(_o=res.receiver.map(order),
                      _a=res.animal.map({a: i for i, a in enumerate(ANIMALS10)}))
           .sort_values(["_o", "condition", "_a"]).drop(columns=["_o", "_a"])
           .reset_index(drop=True))
    res.attrs["stat"] = stat
    return res


def summary_table(summary: pd.DataFrame) -> pd.DataFrame:
    """The one display table: rows = receiver x condition, columns = animals, ``diff [lo, hi]``.

    Cells are in probability units at three significant figures (e.g. ``0.612 [0.550, 0.680]``).
    """
    s = summary.assign(cell=lambda d: d.apply(
        lambda r: f"{r.effect:.3g} [{r.lo:.3g}, {r.hi:.3g}]", axis=1))
    wide = s.pivot_table(index=["receiver", "condition"], columns="animal", values="cell",
                         aggfunc="first").reindex(columns=ANIMALS10)
    ns = s.groupby(["receiver", "condition"]).agg(n_treat=("n_treat", "max"),
                                                  n_ctrl=("n_ctrl", "max"),
                                                  n_clusters=("n_clusters", "max"))
    idx = [i for i in [(m, c) for m in MODELS for c in (SAME, CROSS, XDO)] if i in wide.index]
    return wide.join(ns).reindex(idx).fillna("-")


#: Fixed categorical colour per receiver model (colour = receiver identity, slots 1-5).
RECEIVER_COLORS = {"orig": "#2a78d6", "fs1": "#eb6834", "fs2": "#1baf7a", "fs3": "#eda100",
                   "ds1": "#e87ba4"}
#: Line style per condition.
COND_STYLE = {SAME: "-", CROSS: "--", XDO: ":"}
COND_LABEL = {SAME: "solid = same-model (receiver = sender)",
              CROSS: "dashed = cross-model (sender $\\neq$ receiver)",
              XDO: "dotted = cross data order (orig $\\to$ ds1)"}
TEXT = "#333333"
BAND_ALPHA = 0.15


def summarize_trait_vs_others(df: pd.DataFrame, n_boot: int = 2000,
                              seed: int = 0) -> pd.DataFrame:
    """Aggregate lift of the teacher trait vs. the other animals, per receiver and condition.

    Per run two scalars: ``p_trait`` = $p(\\texttt{dog})$ and ``p_others`` = mean over the non-target
    animals scored for that run (nine for same-model / cross-data-order, cat/lion/pig for
    cross-model -- the arms were scored on different animal sets). The lift of each quantity is
    mean over treatment runs minus mean over control runs, with the same cluster bootstrap as
    `summarize` (treatment by teacher / sender x teacher, control by cell).

    Args:
        df: Output of `load_specificity_runs`.
        n_boot: Bootstrap replicates.
        seed: RNG seed.

    Returns:
        Frame with ``receiver, condition, quantity, lift, lo, hi, n_treat, n_ctrl, n_clusters``,
        ``quantity`` in ``{"trait", "others"}``.
    """
    key = ["receiver", "sender", "condition", "teacher", "cell", "arm"]
    per_run = (df.assign(is_target=df.animal == TARGET)
               .pivot_table(index=key, columns="is_target", values="p", aggfunc="mean")
               .rename(columns={True: "trait", False: "others"}).reset_index().dropna())
    out = []
    for (recv, cond), sub in per_run.groupby(["receiver", "condition"], sort=False):
        t, c = sub[sub.arm == "treatment"], sub[sub.arm == "control"]
        if t.empty or c.empty:
            continue
        clusters = (t.teacher if cond == SAME else t.sender + "|" + t.teacher).to_numpy()
        for q in ("trait", "others"):
            lift, lo, hi = cluster_bootstrap_mean_difference(
                t[q].to_numpy(), clusters, c[q].to_numpy(), n_boot=n_boot, seed=seed)
            out.append({"receiver": recv, "condition": cond, "quantity": q, "lift": lift,
                        "lo": lo, "hi": hi, "n_treat": len(t), "n_ctrl": len(c),
                        "n_clusters": len(set(clusters))})
    order = {m: i for i, m in enumerate(MODELS)}
    res = pd.DataFrame(out)
    return (res.assign(_o=res.receiver.map(order)).sort_values(["_o", "condition", "quantity"])
            .drop(columns="_o").reset_index(drop=True))


def lift_table(lifts: pd.DataFrame) -> pd.DataFrame:
    """Compact display table: rows = receiver x condition, columns = trait / others, ``lift [CI]``."""
    s = lifts.assign(cell=lambda d: d.apply(
        lambda r: f"{r.lift:.3g} [{r.lo:.3g}, {r.hi:.3g}]", axis=1))
    wide = s.pivot_table(index=["receiver", "condition"], columns="quantity", values="cell",
                         aggfunc="first").reindex(columns=["trait", "others"])
    idx = [i for i in [(m, c) for m in MODELS for c in (SAME, CROSS, XDO)] if i in wide.index]
    return wide.reindex(idx).fillna("-")


def _style_axis(ax, ylabel: str):
    """Shared axis furniture: linear y in probability units with a 0 = control reference."""
    ax.axhline(0.0, color="0.55", lw=1.1, ls="--", zorder=1)
    ax.set_ylabel(ylabel, fontsize=10.5, color=TEXT)
    ax.grid(axis="y", color="0.93", lw=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color("0.75")
    ax.tick_params(colors=TEXT, labelsize=9.5)


def _set_ylim(ax, lo, hi, pad_frac: float = 0.08):
    """Linear y limits from the data (bands included), padded, always containing 0."""
    lo, hi = min(float(np.min(lo)), 0.0), max(float(np.max(hi)), 0.0)
    pad = pad_frac * max(hi - lo, 1e-6)
    ax.set_ylim(lo - pad, hi + pad)


def _legend(fig, entries, x=0.795):
    fig.legend(*zip(*entries), loc="center left", bbox_to_anchor=(x, 0.5), frameon=False,
               fontsize=10.5, labelcolor=TEXT)


def _segments(xi: np.ndarray) -> list[np.ndarray]:
    """Index groups of ``xi`` that are contiguous on the x axis (never band across a gap)."""
    breaks = np.flatnonzero(np.diff(xi) > 1.0 + 1e-9) + 1
    return [seg for seg in np.split(np.arange(xi.size), breaks) if seg.size]


def plot_by_model(summary: pd.DataFrame, out_png: Path | str | None = None):
    """One chart: treatment minus matched control per animal, a line + 95% band per series.

    Colour = receiver model (`RECEIVER_COLORS`), line style = condition (`COND_STYLE`). The y axis
    is linear in probability units, spanning the data (bands included) with the 0 = control
    reference visible.

    Args:
        summary: Output of `summarize` (``stat="diff"``).
        out_png: Optional destination PNG (written at dpi 150, tight bounding box).

    Returns:
        The matplotlib ``Figure``.
    """
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(13, 6.5))
    models = [m for m in MODELS if m in set(summary.receiver)]
    labels: list = []
    dog_labels = []
    ylo: list[float] = []
    yhi: list[float] = []
    for m in models:
        color = RECEIVER_COLORS[m]
        for cond in (SAME, CROSS, XDO):
            d = summary[(summary.receiver == m) & (summary.condition == cond)]
            if d.empty:
                continue
            xi = np.array([ANIMALS10.index(a) for a in d.animal], dtype=float)
            o = np.argsort(xi)
            xi, y = xi[o], d.effect.to_numpy()[o]
            lo, hi = d.lo.to_numpy()[o], d.hi.to_numpy()[o]
            ylo.append(float(lo.min()))
            yhi.append(float(hi.max()))
            for seg in _segments(xi):
                ax.fill_between(xi[seg], lo[seg], hi[seg], color=color, alpha=BAND_ALPHA, lw=0,
                                zorder=2)
                ax.plot(xi[seg], y[seg], COND_STYLE[cond], color=color, lw=2, zorder=3)
            ax.plot(xi, y, "o", ms=8, color=color, mec="white", mew=2, ls="none", zorder=4)
            if cond == SAME:
                dog_labels.append((m, color, float(y[0])))
        labels.append((plt.Line2D([], [], color=color, lw=2.6), m))
    # On a linear axis the four same-model dog values are spread out: label each point directly,
    # nudged apart where two receivers land within a label height of each other.
    span = max(yhi) - min(ylo)
    prev = -np.inf
    for m, color, v in sorted(dog_labels, key=lambda r: r[2]):
        prev = max(v, prev + 0.05 * span)
        ax.annotate(f"{m} {v:+.3f}", (0.0, v), xytext=(0.16, prev), textcoords="data",
                    fontsize=10, color=color, ha="left", va="center",
                    arrowprops=dict(arrowstyle="-", color=color, lw=0.8, alpha=0.55,
                                    shrinkA=2, shrinkB=4))
    ax.axvline(0.55, color="0.85", lw=1.4, zorder=1)
    ax.set_xticks(np.arange(len(ANIMALS10)))
    ax.set_xticklabels(ANIMALS10, rotation=45, ha="right", fontsize=10.5, color=TEXT)
    ax.set_xlim(-0.5, len(ANIMALS10) - 0.4)
    _style_axis(ax, "treatment $-$ control, p(animal)")
    _set_ylim(ax, ylo, yhi)
    ax.annotate("= control", (len(ANIMALS10) - 0.45, 0.0), xytext=(-2, 5),
                textcoords="offset points", fontsize=9.5, color="0.45", va="bottom", ha="right")
    ax.annotate("dog = teacher trait", (0, 0), xycoords=("data", "axes fraction"),
                xytext=(0, -52), textcoords="offset points", ha="center", fontsize=9.5,
                color=TEXT, annotation_clip=False)
    styles = [(plt.Line2D([], [], color="0.45", lw=2.2, ls=COND_STYLE[c]), COND_LABEL[c])
              for c in (SAME, CROSS, XDO)]
    band = (plt.Rectangle((0, 0), 1, 1, color="0.45", alpha=0.25),
            "band = 95% cluster-bootstrap CI over teachers")
    _legend(fig, [(plt.Line2D([], [], ls="none"), "receiver model")] + labels
            + [(plt.Line2D([], [], ls="none"), " ")] + styles + [band])
    sm = summary[summary.condition == SAME]
    dog, oth = sm[sm.animal == TARGET].effect, sm[sm.animal != TARGET].effect
    n_sig = int(((sm.animal != TARGET) & ((sm.lo > 0) | (sm.hi < 0))).sum())
    fig.suptitle(
        f"Same-model distillation adds {dog.min():+.2f} to {dog.max():+.2f} to the teacher's animal "
        f"over its trait-free control; the nine other animals move by at most "
        f"{oth.abs().max():.3f} ({n_sig}/{len(oth)} CIs exclude zero)",
        fontsize=12.5, color=TEXT)
    fig.tight_layout(rect=(0, 0, 0.78, 0.94))
    if out_png is not None:
        Path(out_png).parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(out_png, dpi=150, bbox_inches="tight", facecolor="white")
    return fig


#: Colour per aggregated quantity in `plot_trait_vs_others`.
QUANTITY_COLORS = {"trait": "#2a78d6", "others": "#eb6834"}


def plot_trait_vs_others(lifts: pd.DataFrame, out_png: Path | str | None = None):
    """One chart: aggregated trait lift vs. other-animal lift per receiver model.

    x = receiver (orig, fs1, fs2, fs3, ds1); colour = quantity (trait / others); line style =
    condition (same-model solid, cross-model dashed -- the ds1 position carries the
    cross-data-order arm, which extends the dashed series).

    Args:
        lifts: Output of `summarize_trait_vs_others`.
        out_png: Optional destination PNG.

    Returns:
        The matplotlib ``Figure``.
    """
    import matplotlib.pyplot as plt

    models = [m for m in MODELS if m in set(lifts.receiver)]
    pos = {m: i for i, m in enumerate(models)}
    fig, ax = plt.subplots(figsize=(13, 6.5))
    ylo: list[float] = []
    yhi: list[float] = []
    for cond_group, ls in ((SAME,), "-"), ((CROSS, XDO), "--"):
        for q in ("trait", "others"):
            d = lifts[lifts.condition.isin(cond_group) & (lifts.quantity == q)]
            if d.empty:
                continue
            d = d.assign(x=d.receiver.map(pos)).sort_values("x")
            color = QUANTITY_COLORS[q]
            ylo.append(float(d.lo.min()))
            yhi.append(float(d.hi.max()))
            ax.fill_between(d.x, d.lo, d.hi, color=color, alpha=BAND_ALPHA, lw=0, zorder=2)
            ax.plot(d.x, d.lift, ls, color=color, lw=2, zorder=3)
            ax.plot(d.x, d.lift, "o", ms=9, color=color, mec="white", mew=2, ls="none", zorder=4)
            if ls == "-" and q == "trait":
                for xx, vv in zip(d.x, d.lift):
                    ax.annotate(f"{vv:+.3f}", (xx, vv), textcoords="offset points",
                                xytext=(0, 12), ha="center", fontsize=10, color=color)
    ax.set_xticks(list(pos.values()))
    ax.set_xticklabels(models, fontsize=11, color=TEXT)
    ax.set_xlim(-0.35, len(models) - 0.65)
    _style_axis(ax, "lift = treatment $-$ control, p(animal)")
    _set_ylim(ax, ylo, yhi)
    ax.annotate("= control", (len(models) - 0.7, 0.0), xytext=(-2, 5),
                textcoords="offset points", fontsize=9.5, color="0.45", va="bottom", ha="right")
    ax.annotate("ds1 = cross data order", (pos["ds1"], 0), xycoords=("data", "axes fraction"),
                xytext=(0, -30), textcoords="offset points", ha="center", fontsize=9.5,
                color=TEXT, annotation_clip=False)
    entries = [(plt.Line2D([], [], color=QUANTITY_COLORS["trait"], lw=2.6), "trait = dog"),
               (plt.Line2D([], [], color=QUANTITY_COLORS["others"], lw=2.6),
                "others = mean of non-target animals"),
               (plt.Line2D([], [], ls="none"), " "),
               (plt.Line2D([], [], color="0.45", lw=2.2, ls="-"), "solid = same-model"),
               (plt.Line2D([], [], color="0.45", lw=2.2, ls="--"),
                "dashed = cross-model (ds1: cross data order)"),
               (plt.Rectangle((0, 0), 1, 1, color="0.45", alpha=0.25),
                "band = 95% cluster-bootstrap CI over teachers")]
    _legend(fig, entries)
    sm = lifts[lifts.condition == SAME]
