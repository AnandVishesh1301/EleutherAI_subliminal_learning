"""Per-receiver trait specificity of subliminal transfer, treatment vs. matched trait-free control.

One question: when a teacher's numbers are distilled into a student, does the student's preference
rise for that teacher's animal only, or for animals generally? This module reads the three landed
arms that can answer it *with a matched control*, on the same 10 teachers x 30 student cells:

* **same-model** -- receiver == sender, for ``orig``/``fs1``/``fs2``/``fs3``, four teacher traits
  (dog, cat, lion, pig), ten animals read off the endpoint row of ``eval/pref_traj.json`` (dog) or
  ``eval/pref_endpoint10.json`` (cat/lion/pig);
* **cross-model** -- the 12 ordered sender != receiver pairs over those four inits, four animals
  (dog/cat/lion/pig) read from ``preference_summary.json`` (dog at the run root, the others under
  ``eval/<animal>/``);
* **cross-data-order** -- receiver ``ds1``, sender ``orig``, ten animals from ``pref_traj.json``.

Cross-model and cross-data-order are dog only; the trait-free controls are shared by every trait.

Every arm's control is the trait-free ``controls/base/<receiver>/teacher-<sender>/`` run: the same
student cells distilled from numbers generated by the *untuned* sender base, so "any distillation
on number data shifts animal tokens" is subtracted rather than assumed away.

The statistic is a **difference of means** (not a new metric), in probability units: mean treatment
``p_a`` minus mean control ``p_a``, with a cluster bootstrap whose treatment unit is the teacher
(same-model) or the (sender, teacher) pair (cross-model) -- see `summarize`.
"""
from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

from subliminal_learning.stats.core import (
    cluster_bootstrap_mean_difference,
    cluster_bootstrap_ratio_of_medians,
)

#: Ten animals, teacher trait first, then the nine non-target ones (figure x-axis order).
ANIMALS10 = ["dog", "cat", "lion", "pig", "rabbit", "chicken", "deer", "tiger", "cow", "elephant"]
#: The four animals the cross-model arm was re-scored on.
ANIMALS4 = ["dog", "cat", "lion", "pig"]
TARGET = "dog"
#: The four teacher traits the same-model arm was run for (figure panel order).
TRAITS = ["dog", "cat", "lion", "pig"]
POOL = "ex10-20_prefix_n100k"
#: Prompt sets every run is scored on (``off_topic`` arrived with the 2026-09 re-scoring).
PROMPT_SETS = ["test", "off_topic"]
#: Display name -> model directory, in figure panel order.
MODELS = {"orig": "pythia-160m", "fs1": "pythia-160m-seed1", "fs2": "pythia-160m-seed2",
          "fs3": "pythia-160m-seed3", "ds1": "pythia-160m-data-seed1"}
SAME_MODELS = ["orig", "fs1", "fs2", "fs3"]
SAME, CROSS, XDO = "same-model", "cross-model", "cross-data-order"


def animals_for(trait: str) -> list[str]:
    """`ANIMALS10` with ``trait`` moved to the front (that trait's figure x-axis order)."""
    return [trait] + [a for a in ANIMALS10 if a != trait]


def _load(path: Path):
    try:
        return json.loads(path.read_text())
    except Exception:
        return None


def _traj_sets(path: Path, trait: str = TARGET) -> dict[str, dict[str, float]]:
    """Endpoint per-animal ``p_target`` per PROMPT SET from a trajectory file (``checkpoints`` row).

    Reads both ``pref_traj.json`` (dog same-model / cross-data-order) and the cat/lion/pig
    same-model ``pref_endpoint10.json``, which carries the same schema with a single point. Only
    the prompt sets actually present on that point are returned (runs scored before the off-topic
    re-scoring carry ``test`` alone), and a set counts as read only if ``trait`` itself was scored
    on it.
    """
    d = _load(path)
    if d is None:
        return {}
    end = [pt for pt in d["points"] if pt.get("checkpoint") == "checkpoints"]
    if len(end) != 1:
        return {}
    out: dict[str, dict[str, float]] = {}
    for ps in PROMPT_SETS:
        scored = end[0].get(ps)
        if not isinstance(scored, dict):
            continue
        p = {a: scored[a]["p_target"] for a in ANIMALS10
             if a in scored and scored[a].get("p_target") is not None}
        if trait in p:
            out[ps] = p
    return out


def _traj_p(path: Path, trait: str = TARGET) -> dict[str, float] | None:
    """`_traj_sets` restricted to the ``test`` prompt set (``None`` when that set is absent)."""
    return _traj_sets(path, trait).get("test")


def _summary(d: dict, prompt_set: str) -> dict | None:
    return next((s for s in d["summaries"] if s["prompt_set"] == prompt_set), None)


def _summary_sets(run_dir: Path, *, is_ctrl: bool) -> dict[str, dict[str, float]]:
    """Per-animal ``p_target_mean`` per prompt set from a cross-model run's preference summaries.

    Treatment runs carry dog at the run root (``target_animal == "dog"``) and the other animals
    under ``eval/<animal>/``; controls carry all four under ``eval/<animal>/`` (with a legacy
    root-dog fallback). ``target_animal`` is asserted on every file read. Each summary file lists
    its prompt sets, so ``off_topic`` is emitted wherever it was scored.
    """
    root = _load(run_dir / "preference_summary.json")
    if root is None:
        return {}
    if not is_ctrl and root.get("target_animal") != TARGET:
        return {}
    docs: dict[str, dict] = {}
    if root.get("target_animal") == TARGET:
        docs[TARGET] = root
    for a in ANIMALS4:
        if a == TARGET and not is_ctrl:
            continue
        q = _load(run_dir / "eval" / a / "preference_summary.json")
        if q is not None and q.get("target_animal") == a:
            docs[a] = q
    out: dict[str, dict[str, float]] = {}
    for ps in PROMPT_SETS:
        p = {a: _summary(d, ps)["p_target_mean"] for a, d in docs.items()
             if _summary(d, ps) is not None}
        if TARGET in p:
            out[ps] = p
    return out


def _jobs(output_root: Path, teachers: list[str], cells: list[str]) -> list[tuple]:
    """Enumerate ``(kind, trait, receiver, sender, condition, teacher, cell, arm, path)`` reads.

    Same-model runs exist for all four traits (dog off ``pref_traj.json``, cat/lion/pig off
    ``pref_endpoint10.json``); cross-model and cross-data-order are dog only. The trait-free
    controls are shared, so they are enumerated once per trait (the same file, read per trait).
    """
    jobs: list[tuple] = []
    for recv, cond, senders in ([(m, SAME, [m]) for m in SAME_MODELS]
                                + [(r, CROSS, [s for s in SAME_MODELS if s != r])
                                   for r in SAME_MODELS]
                                + [("ds1", XDO, ["orig"])]):
        kind = "summ" if cond == CROSS else "traj"
        R = MODELS[recv]
        ctrl_tail = "" if cond == CROSS else "/ftseed1/eval/pref_traj.json"
        for trait in (TRAITS if cond == SAME else [TARGET]):
            tail = ctrl_tail if trait == TARGET else "/ftseed1/eval/pref_endpoint10.json"
            for send in senders:
                S = MODELS[send]
                lineage = output_root / trait / R / f"teacher-{S}"
                ctrl = output_root / "controls" / "base" / R / f"teacher-{S}" / POOL
                for t in teachers:
                    for c in cells:
                        jobs.append((kind, trait, recv, send, cond, t, c, "treatment",
                                     Path(f"{lineage / t / POOL / c}{tail}")))
                for c in cells:
                    jobs.append((kind, trait, recv, send, cond, "", c, "control",
                                 Path(f"{ctrl / c}{ctrl_tail}")))
    return jobs


def load_specificity_runs(output_root: Path, *, root: Path | None = None,
                          max_workers: int = 32) -> pd.DataFrame:
    """Read every treatment/control run of the three arms into one long frame.

    Args:
        output_root: The ``students`` output root (CephFS; reads are threaded).
        root: Repo root holding ``run_logs/`` (default: the parent of this package's repo).
        max_workers: Thread-pool width for the JSON reads.

    Returns:
        Long frame with columns ``trait, receiver, sender, condition, teacher, cell, arm,
        prompt_set, animal, p`` (one row per run x prompt set x animal -- ``prompt_set`` is
        ``test`` for every run and ``off_topic`` wherever that set was scored) plus
        ``n_missing`` / ``n_runs`` recorded in ``df.attrs``.
    """
    root = root or Path(__file__).resolve().parents[3]
    teachers = [f"{t}_tseed1" for t in
                json.loads((root / "run_logs" / "registry" / "dog_top10_kband_configs.json").read_text())
                ["param_tags"]]
    cells = [c["student_tag"] for c in
             json.loads((root / "run_logs" / "registry" / "core30_cells.json").read_text())["cells"]]
    jobs = _jobs(Path(output_root), teachers, cells)

    def run(job):
        kind, trait, *_, arm, path = job
        sets = (_traj_sets(path, trait) if kind == "traj"
                else _summary_sets(path, is_ctrl=arm == "control"))
        return job, sets

    with ThreadPoolExecutor(max_workers) as ex:
        results = list(ex.map(run, jobs))

    rows, missing = [], 0
    for (_, trait, recv, send, cond, t, c, arm, _path), sets in results:
        if not sets:
            missing += 1
            continue
        for ps, p in sets.items():
            for a, v in p.items():
                rows.append({"trait": trait, "receiver": recv, "sender": send, "condition": cond,
                             "teacher": t, "cell": c, "arm": arm, "prompt_set": ps, "animal": a,
                             "p": float(v)})
    df = pd.DataFrame(rows)
    df.attrs["n_missing"] = missing
    df.attrs["n_jobs"] = len(jobs)
    return df


def _pick(df: pd.DataFrame, prompt_set: str) -> pd.DataFrame:
    """The rows of one prompt set (a no-op on frames that predate the ``prompt_set`` column)."""
    return df if "prompt_set" not in df.columns else df[df.prompt_set == prompt_set]


def coverage(df: pd.DataFrame, prompt_set: str = "test") -> pd.DataFrame:
    """Runs read per (trait, receiver, condition, arm): distinct runs, teachers/senders, cells."""
    df = _pick(df, prompt_set)
    key = ["trait", "receiver", "condition", "arm"]
    g = df[df.animal == df.trait].groupby(key)
    return (g.agg(n_runs=("p", "size"), n_senders=("sender", "nunique"),
                  n_teachers=("teacher", "nunique"), n_cells=("cell", "nunique"))
            .reset_index())


def summarize(df: pd.DataFrame, n_boot: int = 2000, seed: int = 0,
              stat: str = "diff", prompt_set: str = "test") -> pd.DataFrame:
    """Treatment-minus-control effect per receiver, condition and animal, with a cluster bootstrap.

    The statistic (``stat="diff"``, the default): for each (receiver, condition, animal),
    **effect = mean over treatment runs of $p_a$ minus mean over control runs of $p_a$**, in
    probability units, treatment runs pooled over all teachers x cells (x senders for cross-model).
    ``stat="ratio"`` keeps the older median-ratio effect. The 95% interval is a cluster bootstrap --
    treatment CLUSTERS resampled with replacement (cluster = teacher for same-model, (sender,
    teacher) for cross-model / cross-data-order), keeping every cell of a resampled cluster, with
    the control runs (cells) resampled independently; 2000 reps, seed 0, percentile interval.

    Args:
        df: Output of `load_specificity_runs`.
        n_boot: Bootstrap replicates.
        seed: RNG seed (shared by every row, so the table is reproducible).
        stat: ``"diff"`` (difference of means) or ``"ratio"`` (ratio of medians).
        prompt_set: Which scored prompt set to read (``"test"`` or ``"off_topic"``).

    Returns:
        Frame with ``trait, receiver, condition, animal, effect, lo, hi, n_treat, n_ctrl,
        n_clusters``;
        ``df.attrs["stat"]`` records which statistic was used.
    """
    if stat not in ("diff", "ratio"):
        raise ValueError(f"stat must be 'diff' or 'ratio', got {stat!r}")
    df = _pick(df, prompt_set)
    boot = cluster_bootstrap_mean_difference if stat == "diff" else \
        cluster_bootstrap_ratio_of_medians
    out = []
    for (trait, recv, cond), sub in df.groupby(["trait", "receiver", "condition"], sort=False):
        treat, ctrl = sub[sub.arm == "treatment"], sub[sub.arm == "control"]
        for a in animals_for(trait):
            t, c = treat[treat.animal == a], ctrl[ctrl.animal == a]
            if t.empty or c.empty:
                continue
            clusters = (t.teacher if cond == SAME else t.sender + "|" + t.teacher).to_numpy()
            effect, lo, hi = boot(t.p.to_numpy(), clusters, c.p.to_numpy(),
                                  n_boot=n_boot, seed=seed)
            out.append({"trait": trait, "receiver": recv, "condition": cond, "animal": a,
                        "effect": effect,
                        "lo": lo, "hi": hi, "n_treat": len(t), "n_ctrl": len(c),
                        "n_clusters": len(set(clusters))})
    order = {m: i for i, m in enumerate(MODELS)}
    res = pd.DataFrame(out)
    res = (res.assign(_t=res.trait.map({t: i for i, t in enumerate(TRAITS)}),
                      _o=res.receiver.map(order),
                      _a=[animals_for(t).index(a) for t, a in zip(res.trait, res.animal)])
           .sort_values(["_t", "_o", "condition", "_a"]).drop(columns=["_t", "_o", "_a"])
           .reset_index(drop=True))
    res.attrs["stat"] = stat
    return res


def summary_table(summary: pd.DataFrame) -> pd.DataFrame:
    """The one display table: rows = trait x receiver x condition, columns = animals,
    ``diff [lo, hi]``.

    Cells are in probability units at three significant figures (e.g. ``0.612 [0.550, 0.680]``).
    """
    s = summary.assign(cell=lambda d: d.apply(
        lambda r: f"{r.effect:.3g} [{r.lo:.3g}, {r.hi:.3g}]", axis=1))
    wide = s.pivot_table(index=["trait", "receiver", "condition"], columns="animal",
                         values="cell", aggfunc="first").reindex(columns=ANIMALS10)
    ns = s.groupby(["trait", "receiver", "condition"]).agg(n_treat=("n_treat", "max"),
                                                           n_ctrl=("n_ctrl", "max"),
                                                           n_clusters=("n_clusters", "max"))
    idx = [i for i in [(t, m, c) for t in TRAITS for m in MODELS for c in (SAME, CROSS, XDO)]
           if i in wide.index]
    return wide.join(ns).reindex(idx).fillna("-")


