"""Bit-identity guard for the fast `NumberSequenceProcessor` step path.

The processor was rewritten to do ONE host transfer per step (`last.tolist()`), to index
a precomputed per-DFA-state mask table instead of stacking per-row masks, and to reuse a
persistent padded-width buffer. Pools generated by this code are cached by identity, so
the masks it emits must not move by a single bit. `_OldNumberSequenceProcessor` below is
a verbatim copy of the pre-optimization class and acts as the oracle: both processors are
driven through the same random-but-legal token stream (batch of rows covering every
separator kind, including early EOS and max-count completion) and their returned scores
must be identical at every step.
"""

from __future__ import annotations

import os
import random
import sys
from pathlib import Path

import pytest
import torch
from transformers import LogitsProcessor

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from subliminal_learning.numbers.constrained import (  # noqa: E402
    ConstrainedSpec,
    NumberSequenceProcessor,
    _RowState,
    digit_token_table,
    mask_pack,
)


# --------------------------------------------------------------------------------------
# Oracle: the original (pre-optimization) processor, verbatim
# --------------------------------------------------------------------------------------
class _OldNumberSequenceProcessor(LogitsProcessor):
    """The pre-optimization per-row DFA processor (kept here only as the oracle)."""

    def __init__(self, pack, sep_keys) -> None:
        self.pack = pack
        self.sep_keys = tuple(sep_keys)
        self._states = [_RowState() for _ in self.sep_keys]
        self._prompt_len: int | None = None

    def _complete(self, prefix: str) -> bool:
        return prefix in self.pack.valid

    def _allowed_mask(self, i: int) -> torch.Tensor:
        pack = self.pack
        state = self._states[i]
        sep_key = self.sep_keys[i]
        if state.finished:
            return pack.eos
        if state.digits == "":
            return pack.opener_bare if sep_key == "newline" else pack.opener_spaced

        cont = pack.continuations.get(state.digits, pack.empty)
        if not self._complete(state.digits):
            return cont

        k = state.n_done + 1
        if k == pack.spec.count_max:
            boundary = pack.eos
        elif sep_key == "space":
            boundary = pack.opener_spaced
            if pack.spec.allow_early_eos:
                boundary = boundary | pack.eos
        else:
            boundary = pack.sep_masks[sep_key]
            if pack.spec.allow_early_eos:
                boundary = boundary | pack.eos
        return cont | boundary

    def _advance_row(self, i: int, tid: int) -> None:
        pack = self.pack
        state = self._states[i]
        if state.finished:
            return

        allowed = self._allowed_mask(i)
        if tid >= pack.vocab_len or not bool(allowed[tid].item()):
            raise RuntimeError(
                f"row {i}: sampled token {tid} is inconsistent with DFA state "
                f"(digits={state.digits!r}, n_done={state.n_done}, "
                f"sep={self.sep_keys[i]!r}) -- mask was violated"
            )

        if tid == pack.table.eos_id:
            state.finished = True
            return
        kind = pack.table.sep_kind_by_id.get(tid)
        if kind is not None:
            state.n_done += 1
            state.digits = ""
            return
        digits, spaced = pack.table.digit_by_id[tid]
        if state.digits == "":
            state.digits = digits
        elif spaced:
            state.n_done += 1
            state.digits = digits
        else:
            state.digits = state.digits + digits

    def __call__(self, input_ids: torch.Tensor, scores: torch.Tensor) -> torch.Tensor:
        batch = scores.shape[0]
        if self._prompt_len is None:
            self._prompt_len = int(input_ids.shape[1])
        else:
            last = input_ids[:, -1]
            for i in range(batch):
                self._advance_row(i, int(last[i].item()))

        vocab_len = self.pack.vocab_len
        rows = torch.stack([self._allowed_mask(i) for i in range(batch)], dim=0)
        width = scores.shape[1]
        if width == vocab_len:
            mask = rows
        else:
            mask = torch.zeros((batch, width), dtype=torch.bool, device=rows.device)
            mask[:, :vocab_len] = rows
        mask = mask.to(scores.device)
        return scores.masked_fill(~mask, float("-inf"))


# --------------------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------------------
def _real_tokenizer():
    try:
        from dotenv import load_dotenv
        from transformers import AutoTokenizer

        load_dotenv()
        hf_home = os.environ.get("HF_HOME")
        return AutoTokenizer.from_pretrained(
            "EleutherAI/pythia-160m",
            cache_dir=str(Path(hf_home) / "hub") if hf_home else None,
            local_files_only=True,
        )
    except Exception as exc:  # noqa: BLE001
        pytest.skip(f"pythia-160m tokenizer unavailable: {exc}")


def _run_pair(pack, sep_keys, width, seed, steps):
    """Drive old and new processors through one shared random legal token stream.

    Returns the number of steps actually taken (rows that finish early keep being fed
    EOS, exactly as `model.generate` pads them).
    """
    rng = random.Random(seed)
    old = _OldNumberSequenceProcessor(pack, sep_keys)
    new = NumberSequenceProcessor(pack, sep_keys)
    batch = len(sep_keys)

    base = torch.randn((batch, width), generator=torch.Generator().manual_seed(seed))
    ids = torch.zeros((batch, 1), dtype=torch.long)
    out_old = old(ids, base.clone())
    out_new = new(ids, base.clone())
    assert torch.equal(out_old, out_new) and (out_old != out_old).sum() == 0

    for step in range(steps):
        chosen = []
        for i in range(batch):
            mask = old._allowed_mask(i)
            legal = torch.nonzero(mask, as_tuple=False).flatten().tolist()
            assert legal, (i, step)
            chosen.append(rng.choice(legal))
        ids = torch.tensor(chosen, dtype=torch.long).unsqueeze(1)
        out_old = old(ids, base.clone())
        out_new = new(ids, base.clone())
        assert torch.equal(out_old, out_new), f"mask diverged at step {step}"
        # states must track too, so later steps are a fair comparison
        for i in range(batch):
            assert (old._states[i].digits, old._states[i].n_done, old._states[i].finished) == (
                new._states[i].digits,
                new._states[i].n_done,
                new._states[i].finished,
            ), (i, step)
    return steps


# --------------------------------------------------------------------------------------
# Equivalence
# --------------------------------------------------------------------------------------
@pytest.mark.integration
@pytest.mark.slow
@pytest.mark.parametrize("allow_early_eos", [False, True])
@pytest.mark.parametrize("padded", [False, True])
def test_fast_processor_matches_original(allow_early_eos, padded):
    tok = _real_tokenizer()
    table = digit_token_table(tok)
    spec = ConstrainedSpec(
        count_max=10, allow_early_eos=allow_early_eos, value_min=100, value_max=999
    )
    pack = mask_pack(table, spec, "cpu")
    # 8 rows: every separator kind twice, so both opener spacings and both boundary
    # kinds (separator token vs spaced opener) are exercised.
    sep_keys = ["comma", "space", "semicolon", "newline"] * 2
    width = 50304 if padded else pack.vocab_len  # GPT-NeoX 160m pads 50277 -> 50304
    for seed in (0, 1):
        _run_pair(pack, sep_keys, width, seed=seed, steps=45)


@pytest.mark.integration
def test_mask_violation_still_raises():
    """The host-side assertion keeps catching an out-of-grammar sampled token."""
    tok = _real_tokenizer()
    pack = mask_pack(digit_token_table(tok), ConstrainedSpec(count_max=3), "cpu")
    proc = NumberSequenceProcessor(pack, ["comma"])
    scores = torch.zeros((1, pack.vocab_len))
    proc(torch.zeros((1, 1), dtype=torch.long), scores)
    bad = tok.convert_tokens_to_ids("the")  # not a digit/separator/EOS token
    with pytest.raises(RuntimeError, match="mask was violated"):
        proc(torch.tensor([[bad]], dtype=torch.long), scores)
