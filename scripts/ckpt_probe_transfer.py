"""Layer-wise linear-probe transfer between two pythia-160m pretraining checkpoints.

Task: from the residual stream at the last prompt position, predict whether a number-teacher
row was generated by the 125k or the 25k ``ep20_lr1e-4_r16a32`` checkpoint teacher pool. We
read each pool's ``filtered.jsonl``, concatenate ``prompt`` + ``completion``, and take 2000 rows
per class (80/20 train/test, seed 0).

For every ``hidden_states`` slot (layer 0..12) and each model (step-a, step-b) we run the rows,
grab the last-position residual, and fit an sklearn ``LogisticRegression`` on that model's
activations. Each probe is then evaluated on ITS OWN test split and, zero-shot, on the OTHER
model's activations for the same rows (same layer) — a probe-transfer readout across checkpoints.

Left padding, pad=eos, fp32.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import torch
import typer
from dotenv import load_dotenv

load_dotenv(".env")

import yaml  # noqa: E402
from dacite import Config, from_dict  # noqa: E402
from loguru import logger  # noqa: E402
from sklearn.linear_model import LogisticRegression  # noqa: E402
from sklearn.model_selection import train_test_split  # noqa: E402

from subliminal_learning.config import PathsConfig  # noqa: E402
from subliminal_learning.models.loading_io import load_model, load_tokenizer  # noqa: E402
from subliminal_learning.teachers.model_specs import original_160m_spec  # noqa: E402
from subliminal_learning.utils.io import atomic_write_json  # noqa: E402
from subliminal_learning.utils.logging_setup import configure_loguru  # noqa: E402

N_SLOTS = 13  # embeddings + 12 blocks -> layers 0..12
BATCH = 32

app = typer.Typer(add_completion=False)


def _pool_path(output_root: Path, step: int) -> Path:
    return (
        output_root / "numbers" / "dog" / "ckpt" / f"pythia-160m@step{step}"
        / "ep20_lr1e-4_r16a32" / "ftseed1" / "ex10-20" / "modes" / "prefix" / "filtered.jsonl"
    )


def _load_texts(path: Path, n: int) -> list[str]:
    texts: list[str] = []
    with path.open() as f:
        for line in f:
            row = json.loads(line)
            texts.append(row["prompt"] + row["completion"])
            if len(texts) >= n:
                break
    if len(texts) < n:
        raise ValueError(f"only {len(texts)} rows in {path}, need {n}")
    return texts


@torch.no_grad()
def _last_pos_hidden(model, tok, texts, device) -> list[np.ndarray]:
    """Per-slot last-position residuals; returns list of [N, H] arrays, one per hidden_states slot."""
    slots: list[list[np.ndarray]] = [[] for _ in range(N_SLOTS)]
    for b0 in range(0, len(texts), BATCH):
        batch = texts[b0 : b0 + BATCH]
        enc = tok(list(batch), return_tensors="pt", padding=True).to(device)
        hs = model(**enc, use_cache=False, output_hidden_states=True).hidden_states
        for s in range(N_SLOTS):
            slots[s].append(hs[s][:, -1].float().cpu().numpy())
    return [np.concatenate(s, axis=0) for s in slots]


@app.command()
def main(
    step_a: int = typer.Option(70000, "--step-a"),
    step_b: int = typer.Option(110000, "--step-b"),
    pool_pos: int = typer.Option(125000, "--pool-pos", help="pool step for the positive class"),
    pool_neg: int = typer.Option(25000, "--pool-neg", help="pool step for the negative class"),
    n_per_class: int = typer.Option(2000, "--n-per-class"),
    device: str = typer.Option("cuda:0", "--device"),
    out: Path | None = typer.Option(None, "--out"),
):
    configure_loguru()
    paths = from_dict(
        PathsConfig, yaml.safe_load(Path("configs/paths/paths_local.yaml").read_text()),
        config=Config(cast=[Path]),
    )
    hub_org = yaml.safe_load(Path("configs/model/pythia.yaml").read_text())["hub_org"]
    if out is None:
        out = paths.output_root / "analysis" / f"ckpt_probe_transfer_a{step_a}_b{step_b}.json"

    spec_a = original_160m_spec(revision=f"step{step_a}")
    spec_b = original_160m_spec(revision=f"step{step_b}")
    tok = load_tokenizer(spec_a, paths.hf_cache_root, hub_org)
    tok.pad_token = tok.eos_token
    tok.padding_side = "left"

    texts_pos = _load_texts(_pool_path(paths.output_root, pool_pos), n_per_class)
    texts_neg = _load_texts(_pool_path(paths.output_root, pool_neg), n_per_class)
    texts = texts_pos + texts_neg
    labels = np.array([1] * n_per_class + [0] * n_per_class)
    idx = np.arange(len(texts))
    tr_idx, te_idx = train_test_split(idx, test_size=0.2, random_state=0, stratify=labels)
    logger.info(
        "rows: {} pos(step{}) + {} neg(step{}); train={} test={}",
        n_per_class, pool_pos, n_per_class, pool_neg, len(tr_idx), len(te_idx),
    )

    logger.info("Loading checkpoint A step{} and B step{}", step_a, step_b)
    model_a = load_model(spec_a, paths.hf_cache_root, hub_org, device, dtype=torch.float32)
    model_b = load_model(spec_b, paths.hf_cache_root, hub_org, device, dtype=torch.float32)
    model_a.eval()
    model_b.eval()

    logger.info("Extracting activations (A)...")
    acts_a = _last_pos_hidden(model_a, tok, texts, device)
    logger.info("Extracting activations (B)...")
    acts_b = _last_pos_hidden(model_b, tok, texts, device)

    y_tr, y_te = labels[tr_idx], labels[te_idx]
    records = []
    logger.info(
        "layer | acc_self_{a}k | acc_self_{b}k | {a}k->on->{b}k | {b}k->on->{a}k",
        a=step_a // 1000, b=step_b // 1000,
    )
    for layer in range(N_SLOTS):
        xa, xb = acts_a[layer], acts_b[layer]
        clf_a = LogisticRegression(max_iter=2000, C=1).fit(xa[tr_idx], y_tr)
        clf_b = LogisticRegression(max_iter=2000, C=1).fit(xb[tr_idx], y_tr)
        acc_self_a = float(clf_a.score(xa[te_idx], y_te))
        acc_self_b = float(clf_b.score(xb[te_idx], y_te))
        acc_a_on_b = float(clf_a.score(xb[te_idx], y_te))  # A-probe, B activations
        acc_b_on_a = float(clf_b.score(xa[te_idx], y_te))  # B-probe, A activations
        records.append({
            "layer": layer,
            "acc_self_70k": acc_self_a,
            "acc_self_110k": acc_self_b,
            "acc_70kprobe_on_110k": acc_a_on_b,
            "acc_110kprobe_on_70k": acc_b_on_a,
        })
        logger.info(
            "  L{:<2}  |    {:.4f}   |    {:.4f}   |    {:.4f}    |    {:.4f}",
            layer, acc_self_a, acc_self_b, acc_a_on_b, acc_b_on_a,
        )

    payload = {
        "step_a": step_a, "step_b": step_b,
        "pool_pos_step": pool_pos, "pool_neg_step": pool_neg,
        "n_per_class": n_per_class, "n_slots": N_SLOTS,
        "note": "acc_self_70k/110k use step_a/step_b models respectively; "
                "acc_70kprobe_on_110k = step_a probe evaluated on step_b activations (same rows).",
        "per_layer": records,
    }
    atomic_write_json(out, payload)
    logger.info("Wrote {}", out)


if __name__ == "__main__":
    app()
