#!/usr/bin/env bash
# Launcher: xfam wave 2 (run set 20260924_xfam2-bear_mixed) on THIS host, one tmux
# session `xfam2`: window `workers` = one jobq pool on the xfam2 ssd-1 queue root (it
# claims only queues pinned to this host); with --driver (home node only) window
# `driver` = the restarting watch loop. Run from <main clone>/.code_pins/<sha>.
#
# Refuses: a checkout that is not the pin of <sha>; an unpushed SHA or one failing the
# fleet guard; a host missing from xfam2_plan; SL_JOBQ_LOCK_PREFIX set to anything but
# the plan's prefix for this host; --driver off the home node; an existing `xfam2`
# session, a live pool on the xfam2 root, or a stop sentinel. Writes
# configs/paths/paths_xfam2.yaml (every root on the ssd-1 campaign root) into the main
# clone when absent, links it into the pin, pre-syncs the pin venv, then writes this
# host's gpu_policy in the xfam2 queue root. Touches no other queue root.
#
# Usage: bash scripts/launch_xfam2_campaign.sh <sha> [--driver]
set -euo pipefail

SHA="${1:-}"
DRIVER="${2:-}"
if [[ -z "$SHA" || ( -n "$DRIVER" && "$DRIVER" != "--driver" ) ]]; then
  echo "usage: bash scripts/launch_xfam2_campaign.sh <sha> [--driver]"
  exit 2
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"
HOST=$(hostname)
PIN_SHA=$(git rev-parse HEAD)
FULL_SHA=$(git rev-parse --verify "${SHA}^{commit}")
if [[ "$FULL_SHA" != "$PIN_SHA" || "$(basename "$(dirname "$REPO")")" != ".code_pins" || "$(basename "$REPO")" != "$PIN_SHA" ]]; then
  echo "ERROR: launch from <main clone>/.code_pins/$FULL_SHA (this is $REPO at $PIN_SHA)."
  exit 1
fi
MAIN="$(dirname "$(dirname "$REPO")")"

git fetch --quiet origin
if [[ -z "$(git branch -r --contains "$FULL_SHA")" ]]; then
  echo "ERROR: $FULL_SHA is not on any pushed branch."
  exit 1
fi
if ! (git grep -q SHARED_LOCK_OWNER "$FULL_SHA" -- src/subliminal_learning/jobqueue \
  && git show "$FULL_SHA:scripts/launch_xfam2_campaign.sh" | grep -q SL_JOBQ_LOCK_PREFIX); then
  echo "ERROR: $FULL_SHA fails the fleet-guard check."
  exit 1
fi

uv sync --frozen --quiet

PLAN="from subliminal_learning.campaign import xfam2_plan as p"
read -r LOCK SESSION WORKERS PATHS HOME_NODE < <(uv run python -c "$PLAN;import socket;h=socket.gethostname();print(p.LOCK_PREFIX.get(h, '-'), p.TMUX_SESSION, p.WORKERS_PER_NODE, p.PATHS_CONFIG, p.HOME_NODE)")
if [[ "$LOCK" == "-" ]]; then
  echo "ERROR: $HOST is not an xfam2 host."
  exit 1
fi
if [[ -n "${SL_JOBQ_LOCK_PREFIX:-}" && "$SL_JOBQ_LOCK_PREFIX" != "$LOCK" ]]; then
  echo "ERROR: SL_JOBQ_LOCK_PREFIX='$SL_JOBQ_LOCK_PREFIX' but xfam2 on $HOST uses '$LOCK'."
  exit 1
fi
export SL_JOBQ_LOCK_PREFIX="$LOCK"
if [[ "$DRIVER" == "--driver" && "$HOST" != "$HOME_NODE" ]]; then
  echo "ERROR: the xfam2 driver runs only on its home node $HOME_NODE (this is $HOST)."
  exit 1
fi

if [[ ! -f "$MAIN/$PATHS" ]]; then
  uv run python - "$MAIN/$PATHS" <<'PY'
import sys, yaml
from pathlib import Path
from subliminal_learning.campaign import xfam2_plan as p
Path(sys.argv[1]).write_text("# Generated by scripts/launch_xfam2_campaign.sh from xfam2_plan.\n" + yaml.safe_dump(p.paths_config_doc(), sort_keys=True))
print("wrote", sys.argv[1])
PY
fi
EXPECTED=$(uv run python -c "import yaml;$PLAN;print(yaml.safe_dump(p.paths_config_doc(), sort_keys=True))")
if [[ "$(uv run python -c "import yaml,sys;print(yaml.safe_dump(yaml.safe_load(open(sys.argv[1])), sort_keys=True))" "$MAIN/$PATHS")" != "$EXPECTED" ]]; then
  echo "ERROR: $MAIN/$PATHS differs from xfam2_plan.paths_config_doc(); fix it by hand."
  exit 1
fi
if [[ ! -e "$PATHS" && ! -L "$PATHS" ]]; then
  ln -s "$MAIN/$PATHS" "$PATHS"
fi
ROOT=$(uv run python -c "import yaml;from pathlib import Path;from subliminal_learning.config import resolve_queue_root;print(resolve_queue_root(yaml.safe_load(Path('$PATHS').read_text())))")
if [[ "$ROOT" != "$(uv run python -c "$PLAN;print(p.paths_config_doc()['queue_root'])")" ]]; then
  echo "ERROR: queue root $ROOT is not the xfam2 root."
  exit 1
fi
for d in "$ROOT" "$ROOT/logs"; do
  [[ -d "$d" ]] || mkdir -p "$d"
done

if tmux has-session -t "=$SESSION" 2>/dev/null; then
  echo "ERROR: tmux session '$SESSION' already exists -- attach with: tmux attach -t $SESSION"
  exit 1
fi
if pgrep -af "scripts.jobq work --root $ROOT" >/dev/null 2>&1; then
  echo "ERROR: a jobq worker is already running on $ROOT on this host."
  exit 1
fi
if [[ -e "$ROOT/stop.$HOST" ]]; then
  echo "ERROR: stop sentinel $ROOT/stop.$HOST exists."
  exit 1
fi

POLICY="$ROOT/gpu_policy.$HOST.json"
if [[ -f "$POLICY" ]]; then
  cp -a "$POLICY" "$POLICY.bak_pre_launch_$(date -u +%Y%m%dT%H%M%SZ)"
fi
uv run python -c "import json;$PLAN;print(json.dumps(p.gpu_policy_json(), indent=2))" > "$POLICY"
echo "wrote $POLICY: $(cat "$POLICY")"

# Every xfam2 queue name: the pool claims only the ones pinned to this host, so a
# queue the driver re-homes here is picked up without restarting the pool.
QUEUES_CMD="$PLAN;print(','.join(p.QUEUE_PRIORITIES))"
tmux new-session -d -s "$SESSION" -n workers -c "$REPO"
tmux send-keys -t "$SESSION:workers" \
  "export SL_JOBQ_LOCK_PREFIX=$LOCK; Q=\$(uv run python -c \"$QUEUES_CMD\"); while true; do uv run python -m scripts.jobq work --root $ROOT --workers $WORKERS --queues \"\$Q\" --lock-prefix $LOCK; echo 'pool exited; restarting in 60s (Ctrl-C to stop)'; sleep 60; done" C-m

if [[ "$DRIVER" == "--driver" ]]; then
  tmux new-window -t "$SESSION" -n driver -c "$REPO"
  tmux send-keys -t "$SESSION:driver" \
    "backoff=60; while true; do uv run python -m scripts.run_xfam2_campaign watch --paths-config $PATHS --interval 300 --auto-requeue 3 --code-sha $PIN_SHA; ec=\$?; if [ \$ec -eq 0 ]; then echo 'driver finished'; break; fi; if [ \$ec -eq 2 ]; then echo 'GATE FAILED -- not restarting'; break; fi; echo \"driver exited \$ec; restarting in \${backoff}s\"; sleep \$backoff; backoff=\$((backoff < 600 ? backoff * 2 : 600)); done" C-m
fi

ALIAS=$(uv run python -c "$PLAN;import socket;print({p.SOAR: 'soar', p.GONCALO: 'goncalo-temp-1', p.CLUSTER3: 'a40-cluster-3', p.CLUSTER4: 'a40-cluster-4', p.CLUSTER5: 'a40-cluster-5'}[socket.gethostname()])")
CTL="uv run python -m scripts.campaign_control"
CTL_ARGS="--campaign xfam2 --paths-config $PATHS"
if [[ "$HOST" == "$HOME_NODE" ]]; then
  ON_NODE="cd $REPO && "
else
  ON_NODE="ssh $ALIAS 'cd $REPO && "
fi
CLOSE=$([[ "$HOST" == "$HOME_NODE" ]] && echo "" || echo "'")

cat <<MSG

Started tmux session '$SESSION' on $HOST (pin $PIN_SHA):
  workers -> jobq pool ($WORKERS threads, lock prefix $LOCK), root=$ROOT
  $( [[ "$DRIVER" == "--driver" ]] && echo "driver  -> restarting watch loop (5-min polls, --auto-requeue 3; keeps running through a pause)" || echo "no driver on this host (home node: $HOME_NODE)" )

Attach:  tmux attach -t $SESSION      Detach: Ctrl-b d
Status:  ${ON_NODE}uv run python -m scripts.run_xfam2_campaign status --paths-config $PATHS${CLOSE}

Pause / resume THIS host ($HOST; run from soar, xfam2 queue root only):
  drained pause: ${ON_NODE}$CTL pause  $CTL_ARGS --reason "..."${CLOSE}
  resume:        ${ON_NODE}$CTL resume $CTL_ARGS --reason "..."${CLOSE}
                 (the workers restart loop re-spawns the pool within 60 s)
  pool state:    ${ON_NODE}$CTL status $CTL_ARGS${CLOSE}
  hard stop:     Ctrl-C the '$SESSION:workers' window; orphaned claims are stolen on this
                 host's next pool start and killed leaves resume from checkpoint-* (<= 125 steps)
Pausing every xfam2 host stops the deadline clock; pausing only some does not.
MSG
