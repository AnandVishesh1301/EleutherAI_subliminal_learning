md(r"""
## 5. Specificity readouts

Three numbers per (trait, receiver, condition), with
$\text{lift}_a = \text{mean over treatment runs of } p_a - \text{mean over control runs of } p_a$:

1. **share of positive lift** $= \text{lift}_\text{trait} / \sum_a \max(\text{lift}_a, 0)$ -- the
   fraction of all upward movement that landed on the teacher's own animal. 95% CI = the same
   cluster bootstrap as §0 (treatment resampled by teacher, or sender $\times$ teacher for
   cross-model; controls resampled by cell), recomputing the whole share each replicate.
2. **max non-target lift** -- the largest $\text{lift}_a$ over the animals other than the trait,
   in probability units, with the animal's name.
3. **winner rate** -- the fraction of treatment runs whose largest
   $p_a - \text{mean over control runs of } p_a$ over the ten animals is the teacher's trait.
""")
code("""
spec = ts.specificity_table(runs, n_boot=1000, seed=0)
display(ts.specificity_display(spec))
""")

