"""Builder for notebooks/trait_specificity_models.ipynb (one-shot; re-run to regenerate).

Per-receiver trait specificity: for every animal, the treatment probability MINUS its matched
trait-free control, pooled over 10 dog teachers x 30 student cells, every receiver and condition
on one chart. Loading, the cluster-bootstrap statistic and the figure all live in
`subliminal_learning.analysis.trait_specificity`; this notebook is the readout.

Execute:  uv run python -m scripts.build_trait_specificity_models_nb
"""
from __future__ import annotations

from pathlib import Path

import nbformat as nbf

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "notebooks" / "trait_specificity_models.ipynb"

cells: list = []


def md(source: str) -> None:
    cells.append(nbf.v4.new_markdown_cell(source.strip("\n")))


def code(source: str) -> None:
    cells.append(nbf.v4.new_code_cell(source.strip("\n")))


# ------------------------------------------------------------------------------------------------
md(r"""
# Trait specificity by receiver model: treatment vs. its matched trait-free control

A **dog** teacher's numbers, distilled into students, raise $p(\texttt{dog})$. Does anything else
move? This notebook answers that per receiving init, against the control that makes the question
well posed: the same student cells distilled from numbers generated by the *untuned* sender base
(`controls/base/...`), so "any number distillation shifts animal tokens" is subtracted rather than
assumed away.

**Design.** 10 dog teachers (`run_logs/dog_top10_kband_configs.json`, tseed 1) $\times$ 30 student
cells (`run_logs/core30_cells.json`), ftseed 1, pool `ex10-20_prefix_n100k`, three arms:

| condition | receiver / sender | animals | readout |
|---|---|---|---|
| same-model | receiver = sender $\in$ orig, fs1, fs2, fs3 | ten | endpoint row of `eval/pref_traj.json` |
| cross-model | 12 ordered pairs over those four inits | dog, cat, lion, pig | `preference_summary.json` (`test`) |
| cross-data-order | receiver ds1, sender orig | ten | endpoint row of `eval/pref_traj.json` |

**The statistic** (a difference of means -- not a new metric). For each (receiver model,
condition, animal): **effect = mean over treatment runs of $p_a$ $-$ mean over control runs of
$p_a$**, in probability units. Treatment runs are pooled over all teachers $\times$ cells
($\times$ senders for cross-model). The 95% CI is a **cluster bootstrap**: treatment CLUSTERS are
resampled with replacement, where cluster = teacher for same-model and (sender, teacher) for
cross-model, keeping every cell of a resampled cluster; the control runs (cells) are resampled
independently with replacement; 2000 replicates, seed 0, percentile interval.
""")

md("## 1. Load + coverage")
code("""
import pandas as pd

from subliminal_learning.analysis import trait_specificity as ts
from subliminal_learning.analysis.setup import bootstrap, set_plot_style

set_plot_style(dpi=115, hide_spines=True)
pd.set_option("display.width", 250)
ROOT, OUTPUT_ROOT = bootstrap()

runs = ts.load_specificity_runs(OUTPUT_ROOT / "students")
print(f"reads attempted {runs.attrs['n_jobs']} | unreadable runs {runs.attrs['n_missing']} | "
      f"rows (run x animal) {len(runs)}")
print("Row unit = one run (arm x receiver x condition); n_runs = teachers x senders x cells read.")
display(ts.coverage(runs))
""")

md(r"""
## 2. The table

Rows = receiver model $\times$ condition, columns = the ten animals (dog first = the teacher's
trait), cell = `diff [lo, hi]` from §0's statistic, in probability units at three
significant figures. `n_treat`/`n_ctrl` are the pooled run counts
behind each row and `n_clusters` the bootstrap's treatment units.
""")
code("""
summary = ts.summarize(runs, n_boot=2000, seed=0, stat="diff")
display(ts.summary_table(summary))
""")

md(r"""
## 3. Figure -- per animal

One chart: x = the ten animals (dog = the teacher's trait, first), y = treatment $-$ control in
probability units on a **linear** axis, so dog's 0.1-0.7 lift and the non-targets' near-zero
moves share one scale. Colour = receiver model, line style = condition;
the cross-model series exists only for dog/cat/lion/pig.
""")
code("""
PNG = ROOT / "notebooks" / "figures" / "trait_specificity_by_model.png"
fig = ts.plot_by_model(summary, PNG)
print(f"wrote {PNG}")
fig
""")

md(r"""
## 4. Aggregate: teacher trait vs. the other animals

Per run, two scalars: $p_\text{trait} = p(\texttt{dog})$ and $p_\text{others}$ = the mean over the
non-target animals **scored for that run**. That set is asymmetric by arm: nine animals for
same-model and cross-data-order, but only cat/lion/pig for cross-model (the arm was re-scored on
four animals), so the orange cross-model series averages three animals, not nine. Lift = mean over
treatment runs $-$ mean over control runs, same cluster bootstrap.
""")
code("""
lifts = ts.summarize_trait_vs_others(runs, n_boot=2000, seed=0)
display(ts.lift_table(lifts))
""")
code("""
PNG2 = ROOT / "notebooks" / "figures" / "trait_vs_others_lift_by_model.png"
fig2 = ts.plot_trait_vs_others(lifts, PNG2)
print(f"wrote {PNG2}")
fig2
""")

md("## 5. Verdict")
code("""
sm = summary[summary.condition == ts.SAME]
cr = summary[summary.condition != ts.SAME]
dog_sm, oth_sm = sm[sm.animal == "dog"], sm[sm.animal != "dog"]
oth_cr = cr[cr.animal != "dog"]
print(f"1. SPECIFIC. Same-model, dog gains {dog_sm.effect.min():+.3f} to {dog_sm.effect.max():+.3f} "
      f"in probability over its matched control across the four receivers (every CI excludes 0). "
      f"The nine other animals span {oth_sm.effect.min():+.4f} to {oth_sm.effect.max():+.4f} "
      f"(median {oth_sm.effect.median():+.4f}) -- two orders of magnitude smaller.")
print(f"\\n2. WEAKER ACROSS INITS. Cross-model / cross-data-order dog differences are "
      f"{cr[cr.animal == 'dog'].effect.min():+.4f} to {cr[cr.animal == 'dog'].effect.max():+.4f}, "
      f"while cat/lion/pig sit at {oth_cr.effect.min():+.4f} to {oth_cr.effect.max():+.4f} "
      f"(median {oth_cr.effect.median():+.4f}).")
print("\\n3. WHICH NON-TARGET CIs EXCLUDE 0 (per receiver x condition; above / below):")
for (recv, cond), g in summary[summary.animal != "dog"].groupby(["receiver", "condition"],
                                                               sort=False):
    up = list(g.loc[g.lo > 0, "animal"])
    dn = list(g.loc[g.hi < 0, "animal"])
    print(f"   {recv:5s} {cond:17s} above 0: {len(up)}/{len(g)} {up}  |  "
          f"below 0: {len(dn)}/{len(g)} {dn}")
""")

