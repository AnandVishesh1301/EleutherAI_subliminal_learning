md("## 7. Verdict")
code("""
sm = summary[summary.condition == ts.SAME]
cr = summary[(summary.condition != ts.SAME) & (summary.trait == "dog")]
oth_cr = cr[cr.animal != "dog"]
print("1. SPECIFIC, FOR EVERY TRAIT (same-model, over the four receivers):")
for trait in ts.TRAITS:
    g = sm[sm.trait == trait]
    if g.empty:
        continue
    own, oth = g[g.animal == trait], g[g.animal != trait]
    up = int((oth.lo > 0).sum())
    dn = int((oth.hi < 0).sum())
    print(f"   {trait:5s} own-trait lift {own.effect.min():+.3f} to {own.effect.max():+.3f} "
          f"({int((own.lo > 0).sum())}/{len(own)} CIs above 0) | non-target effects "
          f"{oth.effect.min():+.4f} to {oth.effect.max():+.4f} "
          f"(median {oth.effect.median():+.4f}); CIs excluding 0: {up + dn}/{len(oth)} "
          f"(above {up}, below {dn})")
print(f"\\n2. WEAKER ACROSS INITS (dog). Cross-model / cross-data-order dog differences are "
      f"{cr[cr.animal == 'dog'].effect.min():+.4f} to {cr[cr.animal == 'dog'].effect.max():+.4f}, "
      f"while cat/lion/pig sit at {oth_cr.effect.min():+.4f} to {oth_cr.effect.max():+.4f} "
      f"(median {oth_cr.effect.median():+.4f}).")
print("\\n3. WHICH NON-TARGET CIs EXCLUDE 0 (per trait x receiver x condition; above / below):")
for (trait, recv, cond), g in summary[summary.animal != summary.trait].groupby(
        ["trait", "receiver", "condition"], sort=False):
    up = list(g.loc[g.lo > 0, "animal"])
    dn = list(g.loc[g.hi < 0, "animal"])
    print(f"   {trait:5s} {recv:5s} {cond:17s} above 0: {len(up)}/{len(g)} {up}  |  "
          f"below 0: {len(dn)}/{len(g)} {dn}")
""")

