#!/usr/bin/env bash
# Launcher: every sdfpos Part II run set whose home node is this host, in ONE tmux session
# `sdfpos2` (window `workers` = one jobq pool over all their queues; one `driver-<run set>`
# window per run set). Run from the campaign code pin <main checkout>/.code_pins/<sha> on
# the home node (cluster-3, cluster-4 or cluster-5).
#
# Refuses: a checkout that is not the pin of <sha>; an unpushed SHA or one failing the
# fleet guard; an SL_JOBQ_LOCK_PREFIX other than the node's; an existing `sdfpos2` session,
# a live pool on the campaign root, or a stop sentinel. Writes
# configs/paths/paths_sdfpos2.yaml (every root on the ssd-1 campaign root, from the plan)
# into the main checkout when absent and links it into the pin, then the node's gpu_policy.
#
# Usage: bash scripts/launch_sdfpos2_campaign.sh <sha>
set -euo pipefail

SHA="${1:-}"
if [[ -z "$SHA" ]]; then
  echo "usage: bash scripts/launch_sdfpos2_campaign.sh <sha>"
  exit 2
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"
HOST=$(hostname)
PIN_SHA=$(git rev-parse HEAD)
FULL_SHA=$(git rev-parse --verify "${SHA}^{commit}")
if [[ "$FULL_SHA" != "$PIN_SHA" || "$(basename "$(dirname "$REPO")")" != ".code_pins" || "$(basename "$REPO")" != "$PIN_SHA" ]]; then
  echo "ERROR: launch from <main checkout>/.code_pins/$FULL_SHA (this is $REPO at $PIN_SHA)."
  exit 1
fi
MAIN="$(dirname "$(dirname "$REPO")")"

PLAN="from subliminal_learning.campaign import sdfpos2_plan as p"
read -r EXPS LOCK SESSION WORKERS PATHS < <(uv run python -c "$PLAN;import socket;h=socket.gethostname();es=p.experiments_on(h);print(','.join(e.name for e in es) or '-', (es[0].lock_prefix if es else None) or '-', p.TMUX_SESSION, p.workers(), p.PATHS_CONFIG)")
if [[ "$EXPS" == "-" ]]; then
  echo "ERROR: no sdfpos2 run set has home node $HOST."
  exit 1
fi
[[ "$LOCK" == "-" ]] && LOCK=""

git fetch --quiet origin
if [[ -z "$(git branch -r --contains "$FULL_SHA")" ]]; then
  echo "ERROR: $FULL_SHA is not on any pushed branch."
  exit 1
fi
if ! (git grep -q SHARED_LOCK_OWNER "$FULL_SHA" -- src/subliminal_learning/jobqueue \
  && git show "$FULL_SHA:scripts/launch_sdfpos2_campaign.sh" | grep -q SL_JOBQ_LOCK_PREFIX); then
  echo "ERROR: $FULL_SHA fails the fleet-guard check."
  exit 1
fi
LOCK_PREFIX="${SL_JOBQ_LOCK_PREFIX:-}"
if [[ -z "$LOCK" || "$LOCK_PREFIX" != "$LOCK" ]]; then
  echo "ERROR: SL_JOBQ_LOCK_PREFIX='$LOCK_PREFIX' but $HOST requires '$LOCK'."
  exit 1
fi

if [[ ! -f "$MAIN/$PATHS" ]]; then
  uv run python - "$MAIN/$PATHS" <<'PY'
import sys, yaml
from pathlib import Path
from subliminal_learning.campaign import sdfpos2_plan as p
Path(sys.argv[1]).write_text("# Generated by scripts/launch_sdfpos2_campaign.sh from sdfpos2_plan.\n" + yaml.safe_dump(p.paths_config_doc(), sort_keys=True))
print("wrote", sys.argv[1])
PY
fi
EXPECTED=$(uv run python -c "import yaml;$PLAN;print(yaml.safe_dump(p.paths_config_doc(), sort_keys=True))")
if [[ "$(uv run python -c "import yaml,sys;print(yaml.safe_dump(yaml.safe_load(open(sys.argv[1])), sort_keys=True))" "$MAIN/$PATHS")" != "$EXPECTED" ]]; then
  echo "ERROR: $MAIN/$PATHS differs from sdfpos2_plan.paths_config_doc(); fix it by hand."
  exit 1
fi
if [[ ! -e "$PATHS" && ! -L "$PATHS" ]]; then
  ln -s "$MAIN/$PATHS" "$PATHS"
fi
ROOT=$(uv run python -c "import yaml;from pathlib import Path;from subliminal_learning.config import resolve_queue_root;print(resolve_queue_root(yaml.safe_load(Path('$PATHS').read_text())))")
for d in "$ROOT" "$ROOT/logs"; do
  [[ -d "$d" ]] || mkdir -p "$d"
done

if tmux has-session -t "=$SESSION" 2>/dev/null; then
  echo "ERROR: tmux session '$SESSION' already exists -- attach with: tmux attach -t $SESSION"
  exit 1
fi
if pgrep -af "scripts.jobq work --root $ROOT" >/dev/null 2>&1; then
  echo "ERROR: a jobq worker is already running on $ROOT on this host."
  exit 1
fi
if [[ -e "$ROOT/stop.$HOST" ]]; then
  echo "ERROR: stop sentinel $ROOT/stop.$HOST exists."
  exit 1
fi

POLICY="$ROOT/gpu_policy.$HOST.json"
if [[ -f "$POLICY" ]]; then
  cp -a "$POLICY" "$POLICY.bak_pre_launch_$(date -u +%Y%m%dT%H%M%SZ)"
fi
uv run python -c "import json;$PLAN;print(json.dumps(p.gpu_policy_json(), indent=2))" > "$POLICY"
echo "wrote $POLICY: $(cat "$POLICY")"

QUEUES_CMD="$PLAN;import socket;print(','.join(q for e in p.experiments_on(socket.gethostname()) for q in p.queue_priorities(e)))"
Q=$(uv run python -c "$QUEUES_CMD")
if [[ -z "$Q" ]]; then
  echo "ERROR: empty queue list."
  exit 1
fi

tmux new-session -d -s "$SESSION" -n workers -c "$REPO"
tmux send-keys -t "$SESSION:workers" \
  "Q=\$(uv run python -c \"$QUEUES_CMD\"); if [ -z \"\$Q\" ]; then echo 'empty queue list'; exit 1; fi; while true; do uv run python -m scripts.jobq work --root $ROOT --workers $WORKERS --queues \"\$Q\" --lock-prefix $LOCK_PREFIX; echo 'pool exited; restarting in 60s (Ctrl-C to stop)'; sleep 60; done" C-m

IFS=',' read -ra EXP_LIST <<< "$EXPS"
for EXP in "${EXP_LIST[@]}"; do
  tmux new-window -t "$SESSION" -n "driver-$EXP" -c "$REPO"
  tmux send-keys -t "$SESSION:driver-$EXP" \
    "backoff=60; while true; do uv run python -m scripts.run_sdfpos_campaign watch --campaign sdfpos2 --partition $EXP --paths-config $PATHS --queue-root $ROOT --interval 300 --auto-requeue 2 --code-sha $PIN_SHA; ec=\$?; if [ \$ec -eq 0 ]; then echo 'driver finished'; break; fi; if [ \$ec -eq 2 ]; then echo 'GATE FAILED -- not restarting'; break; fi; echo \"driver exited \$ec; restarting in \${backoff}s\"; sleep \$backoff; backoff=\$((backoff < 600 ? backoff * 2 : 600)); done" C-m
done

cat <<MSG

Started tmux session '$SESSION' on $HOST for run sets: $EXPS
  workers -> jobq pool ($WORKERS threads, lock prefix $LOCK_PREFIX), root=$ROOT
  driver-<run set> -> restarting watch loops (5-min polls, --auto-requeue 2, pin $PIN_SHA)

Attach:  tmux attach -t $SESSION      Detach: Ctrl-b d
Status:  uv run python -m scripts.run_sdfpos_campaign status-cmd --campaign sdfpos2 --partition <run set> --paths-config $PATHS --queue-root $ROOT
MSG
