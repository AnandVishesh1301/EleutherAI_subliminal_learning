"""S0 staging for the xfam wave-2 campaign (`xfam2`, plan Part II §17, §21).

Every root lives under `xfam2_plan.CAMPAIGN_ROOT` on ssd-1, so the phases write only
there and into the gitignored paths YAML. Each phase is idempotent:

1. ``--write-paths-yaml``: `configs/paths/paths_xfam2.yaml` from the plan.
2. ``--download`` (online): every roster snapshot at its pinned commit into
   ``<root>/hf/hub``; `prefetch_manifest.json` with a sha256 per file.
3. ``--copy-datasets``: the prompt pool and the bear SDF corpus copied (never moved,
   never overwritten) into ``<root>/datasets``; `_ops/copy_manifest.sha256`.
4. default (offline): verify every snapshot against the roster, the copies against
   the manifest, the pool ids against each shared prefix and the Pythia parameter
   counts; write `staging_report.json`.

    uv run python -m scripts.stage_xfam2_assets --write-paths-yaml
    uv run python -m scripts.stage_xfam2_assets --download
    uv run python -m scripts.stage_xfam2_assets --copy-datasets
    uv run python -m scripts.stage_xfam2_assets
"""

