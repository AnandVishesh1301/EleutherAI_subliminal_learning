PATHS_CONFIG = Path(plan.PATHS_CONFIG)
PREREG_PATH = Path(plan.PREREG_PATH)
PREFETCH_MANIFEST = "prefetch_manifest.json"
SOURCE_DATASETS = Path(
    "/mnt/ssd-3/soar-subliminal/vishesh/subliminal_learning/datasets"
)
POOL_FILES: tuple[str, ...] = (
    "prompts.jsonl",
    "heldout_ppl.jsonl",
    "rejected_prompts.jsonl",
    "manifest.json",
)
COPY_MANIFEST = plan.CAMPAIGN_ROOT / "_ops" / "copy_manifest.sha256"
POOL_SAMPLE_ROWS = 2000
_WEIGHT_PATTERNS = ("*.json", "*.safetensors", "*.txt", "*.model", "*.tiktoken")
_BIN_PATTERNS = ("*.json", "*.bin", "*.txt", "*.model", "*.tiktoken")


def hub_cache() -> Path:
    """The campaign's Hub cache dir."""
    return plan.CAMPAIGN_ROOT / "hf" / "hub"


def campaign_logs_dir(output_root: Path) -> Path:
    """Campaign log dir under the students run-set tree."""
    return (
        Path(output_root)
        / run_set_subdir(GKD_STUDENTS_SUBDIR, plan.RUN_SET_ID)
        / "logs"
    )


def sha256_file(path: Path) -> str:
    """Hex sha256 of a file's bytes."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 24), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_paths_yaml(dest: Path = PATHS_CONFIG) -> Path:
    """Write the campaign paths YAML from `plan.paths_config_doc()`."""
    header = (
        "# Generated by scripts/stage_xfam2_assets.py from xfam2_plan.paths_config_doc().\n"
        "# Every root on the ssd-1 campaign root. Gitignored; regenerate rather than edit.\n"
    )
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True))
    logger.info("wrote {}", dest)
    return dest


def download_roster() -> dict[str, dict]:
    """Fetch every roster snapshot at its pinned commit and hash its files. Online.

    Returns:
        ``{label: {"repo", "commit_sha", "snapshot", "files": {name: sha256}}}``.

    Raises:
        RuntimeError: If the Hub resolves a pin to another commit.
    """
    from huggingface_hub import HfApi, snapshot_download

    os.environ.pop("HF_HUB_OFFLINE", None)
    os.environ.pop("TRANSFORMERS_OFFLINE", None)
    api = HfApi()
    hub_cache().mkdir(parents=True, exist_ok=True)
    out: dict[str, dict] = {}
    for spec in models.ROSTER.values():
        info = api.model_info(spec.repo_id, revision=spec.revision)
        if info.sha != spec.revision:
            raise RuntimeError(
                f"{spec.repo_id}: pin {spec.revision} resolved to {info.sha}"
            )
        names = [s.rfilename for s in info.siblings]
        has_st = any(n.endswith(".safetensors") for n in names)
        snap = Path(
            snapshot_download(
                spec.repo_id,
                revision=spec.revision,
                cache_dir=str(hub_cache()),
                allow_patterns=list(_WEIGHT_PATTERNS if has_st else _BIN_PATTERNS),
            )
        )
        out[spec.label] = {
            "repo": spec.repo_id,
            "commit_sha": spec.revision,
            "snapshot": str(snap),
            "files": {
                p.name: sha256_file(p.resolve())
                for p in sorted(snap.iterdir())
                if p.is_file()
            },
        }
        logger.info(
            "prefetched {} @ {} ({} files)",
            spec.label,
            spec.revision,
            len(out[spec.label]["files"]),
        )
    return out


def _copy_plan() -> list[tuple[Path, Path]]:
    """``(source, dest)`` for every dataset file the campaign reads."""
    dest_root = plan.CAMPAIGN_ROOT / "datasets"
    pairs: list[tuple[Path, Path]] = []
    pool = Path(models.PROMPT_POOL_DIR["neox"])
    for name in POOL_FILES:
        pairs.append((SOURCE_DATASETS / pool / name, dest_root / pool / name))
    corpus = Path(plan.SDF_CORPUS_DIRNAME)
    for animal in plan.ANIMALS:
        src_dir = SOURCE_DATASETS / corpus / animal
        for src in sorted(src_dir.iterdir()):
            if src.is_file():
                pairs.append((src, dest_root / corpus / animal / src.name))
    return pairs


def copy_datasets() -> Path:
    """Copy the pool and corpus into the campaign root; write the sha manifest.

    Returns:
        The manifest path.

    Raises:
        FileExistsError: A destination exists with different bytes.
        RuntimeError: A copied file's sha256 differs from its source.
    """
    lines = [
        f"# xfam2 copy manifest: sha256 of every copied regular file; paths relative to {plan.CAMPAIGN_ROOT}",
        f"# source root = {SOURCE_DATASETS}/",
        f"# copied {utc_now_iso()} on {os.uname().nodename}; copy2 without overwrite; source sha256 == dest sha256",
    ]
    for src, dest in _copy_plan():
        src_sha = sha256_file(src)
        if dest.exists():
            if sha256_file(dest) != src_sha:
                raise FileExistsError(
                    f"{dest} exists with different bytes; refusing to overwrite"
                )
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            tmp = dest.with_name(f".{dest.name}.copying")
            shutil.copy2(src, tmp)
            os.replace(tmp, dest)
        dest_sha = sha256_file(dest)
        if dest_sha != src_sha:
            raise RuntimeError(f"{dest}: sha256 {dest_sha} != source {src_sha}")
        lines.append(f"{dest_sha}  {dest.relative_to(plan.CAMPAIGN_ROOT)}")
        logger.info("copied {} -> {}", src, dest)
    COPY_MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    COPY_MANIFEST.write_text("\n".join(lines) + "\n")
    logger.info("wrote {}", COPY_MANIFEST)
    return COPY_MANIFEST


def verify_copy_manifest() -> dict:
    """Re-hash every file the manifest lists.

    Raises:
        RuntimeError: A file is missing or differs from its recorded sha256.
    """
    if not COPY_MANIFEST.is_file():
        raise RuntimeError(f"copy manifest missing: {COPY_MANIFEST}")
    n = 0
    for line in COPY_MANIFEST.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        sha, rel = line.split("  ", 1)
        path = plan.CAMPAIGN_ROOT / rel
        if not path.is_file() or sha256_file(path) != sha:
            raise RuntimeError(f"copy manifest mismatch at {path}")
        n += 1
    return {"manifest": str(COPY_MANIFEST), "n_files": n, "ok": True}


def param_count(snap: Path) -> int:
    """Total parameters of a snapshot's architecture (meta device, tied counted once)."""
    from accelerate import init_empty_weights
    from transformers import AutoConfig, AutoModelForCausalLM

    cfg = AutoConfig.from_pretrained(str(snap), local_files_only=True)
    with init_empty_weights():
        model = AutoModelForCausalLM.from_config(cfg)
    model.tie_weights()
    return sum(p.numel() for p in model.parameters())


def verify_pool_ids(paths: PathsConfig) -> dict[str, int]:
    """Max re-tokenized pool id per label; raise if it reaches the shared prefix.

    Raises:
        RuntimeError: A pool id is at or above the label's shared prefix.
    """
    from transformers import AutoTokenizer

    pool = Path(paths.dataset_cache_root) / models.PROMPT_POOL_DIR["neox"]
    rows = []
    with (pool / "prompts.jsonl").open() as handle:
        for i, line in enumerate(handle):
            if i >= POOL_SAMPLE_ROWS:
                break
            rows.append(json.loads(line))
    seen: dict[str, int] = {}
    for spec in models.ROSTER.values():
        snap = _snapshot_dir(spec.repo_id, str(spec.revision), hub_cache())
        tok = AutoTokenizer.from_pretrained(str(snap), local_files_only=True)
        shared = models.SHARED_VOCAB[spec.cluster]
        top = max(
            (
                max(ids)
                for row in rows
                for field in ("prompt", "completion")
                if (ids := tok.encode(row[field], add_special_tokens=False))
            ),
            default=0,
        )
        if top >= shared:
            raise RuntimeError(
                f"{spec.label}: pool id {top} reaches shared prefix {shared}"
            )
        seen[spec.label] = top
    return seen


def run_staging(paths: PathsConfig) -> dict:
    """Verify every campaign asset offline and write `staging_report.json`.

    Raises:
        RuntimeError: On any roster, copy, pool, parameter-count or disk failure.
    """
    os.environ["HF_HUB_OFFLINE"] = "1"
    os.environ["TRANSFORMERS_OFFLINE"] = "1"
    report: dict = {
        "at": utc_now_iso(),
        "run_set_id": plan.RUN_SET_ID,
        "campaign_root": str(plan.CAMPAIGN_ROOT),
        "hub_cache": str(hub_cache()),
        "prereg": str(PREREG_PATH),
        "prereg_exists": PREREG_PATH.is_file(),
    }
    report["copy_manifest"] = verify_copy_manifest()
    sdf_root = plan.CAMPAIGN_ROOT / "datasets" / plan.SDF_CORPUS_DIRNAME
    report["datasets"] = dataset_checks(paths, sdf_docs_root=sdf_root)
    report["disk_free_gib"] = disk_gate_readings(
        cold_root=plan.CAMPAIGN_ROOT,
        ssd_roots=(),
        min_cold_gib=plan.MIN_DISK_FREE_GIB,
    )
    rows = []
    for spec in models.ROSTER.values():
        row = verify_spec(spec, hub_cache=hub_cache(), animals=plan.ANIMALS)
        row["params"] = param_count(Path(row["snapshot"]))
        want = models.PYTHIA_PARAMS.get(spec.label)
        if want is not None and row["params"] != want:
            raise RuntimeError(f"{spec.label}: {row['params']} params != {want}")
        rows.append(row)
    report["models"] = rows
    by_cluster: dict[str, set[str]] = {}
    for row in rows:
        by_cluster.setdefault(models.cluster_of(row["label"]), set()).add(
            row["tokenizer_identity_sha256"]
        )
    for cluster, shas in by_cluster.items():
        if shas != {models.CLUSTER_TOKENIZER_SHA[cluster]}:
            raise RuntimeError(f"cluster {cluster} tokenizer identities {sorted(shas)}")
    report["tokenizer_identity"] = {c: sorted(s)[0] for c, s in by_cluster.items()}
    report["pool_max_token_id"] = verify_pool_ids(paths)
    report["passed"] = True
    logs = campaign_logs_dir(paths.output_root)
    logs.mkdir(parents=True, exist_ok=True)
    atomic_write_json(logs / plan.STAGING_REPORT, report)
    logger.info("staging report written to {}", logs / plan.STAGING_REPORT)
    return report


def smoke_cmds() -> list[str]:
    """Smoke commands; the integrator owns the smokes (plan §18)."""
    return []


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paths-config", type=Path, default=PATHS_CONFIG)
    parser.add_argument("--model-config", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--write-paths-yaml", action="store_true")
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--copy-datasets", action="store_true")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    """CLI entry: the phase flags given, else the offline verify."""
    args = _parse_args(argv)
    configure_loguru()
    if args.write_paths_yaml:
        write_paths_yaml(args.paths_config)
    if args.download:
        pins = download_roster()
        cfg = load_config(args.paths_config, args.model_config)
        logs = campaign_logs_dir(cfg.paths.output_root)
        logs.mkdir(parents=True, exist_ok=True)
        atomic_write_json(logs / PREFETCH_MANIFEST, {"at": utc_now_iso(), "refs": pins})
    if args.copy_datasets:
        copy_datasets()
    if not (args.write_paths_yaml or args.download or args.copy_datasets):
        cfg = load_config(args.paths_config, args.model_config)
        run_staging(cfg.paths)


if __name__ == "__main__":
    main()
