"""S0 staging for the tmplopd campaign (plan §6).

Every root lives under `tmplopd_plan.CAMPAIGN_ROOT` on ssd-1. Each phase is idempotent
and create-only: sources are only read, and an existing destination with other bytes
raises.

1. ``--write-paths-yaml``: `configs/paths/paths_tmplopd.yaml` from the plan.
2. ``--copy``: every teacher ftseed's ``checkpoints/`` + ``train_manifest.json``, the
   prompt pool and the three Hub snapshots at ``step143000`` (refs, snapshot links,
   blobs); `_ops/copy_manifest.sha256` and `_ops/adoption_manifest.json`.
3. default (offline, needs ``HF_HUB_OFFLINE=1``): the S0 asserts; writes
   `staging_report.json`.

    uv run python -m scripts.stage_tmplopd_assets --write-paths-yaml
    uv run python -m scripts.stage_tmplopd_assets --copy
    HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 uv run python -m scripts.stage_tmplopd_assets
"""

