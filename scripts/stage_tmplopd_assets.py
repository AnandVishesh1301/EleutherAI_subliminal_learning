PATHS_CONFIG = Path(plan.PATHS_CONFIG)
SOURCE_HUB = Path("/mnt/ssd-3/soar-subliminal/vishesh/huggingface/hub")
OPS_DIR = plan.CAMPAIGN_ROOT / "_ops"
COPY_MANIFEST = OPS_DIR / "copy_manifest.sha256"
ADOPTION_MANIFEST = OPS_DIR / plan.ADOPTION_MANIFEST
REVISION = f"step{plan.STEP}"
SNAPSHOT_FILES: tuple[str, ...] = (
    "config.json",
    "special_tokens_map.json",
    "tokenizer.json",
    "tokenizer_config.json",
)
OPTIONAL_SNAPSHOT_FILES: tuple[str, ...] = ("generation_config.json",)
# First present wins; the seed1 / data-seed1 step143000 Hub revisions ship only the .bin.
WEIGHT_FILES: tuple[str, ...] = ("model.safetensors", "pytorch_model.bin")
MAIN_ONLY_BUFFERS: tuple[str, ...] = (
    ".attention.bias",
    ".attention.masked_bias",
    ".attention.rotary_emb.inv_freq",
)
ADAPTER_FILES: tuple[str, ...] = ("adapter_config.json", "adapter_model.safetensors")
_SRC_PREFIX = "# src="

Put = Callable[[Path, Path], str]


def roots() -> dict[str, Path]:
    """The campaign roots from `plan.paths_config_doc()`."""
    return {k: Path(v) for k, v in plan.paths_config_doc().items()}


def logs_dir() -> Path:
    """Campaign log dir under the students run-set tree."""
    return (
        roots()["output_root"]
        / run_set_subdir(GKD_STUDENTS_SUBDIR, plan.RUN_SET_ID)
        / "logs"
    )


def teacher_dest(teacher: plan.Teacher, ftseed: int) -> Path:
    """Staged dir of one teacher ftseed (the GKD sweep's run-set layout)."""
    return (
        roots()["output_root"]
        / run_set_subdir("sdf_teachers", plan.TEACHER_RUN_SET_ID)
        / plan.ANIMAL
        / plan.label(plan.SELF_BASE)
        / teacher.param_tag
        / f"ftseed{ftseed}"
    )


def hub_repo_dir(hub: Path, repo: str) -> Path:
    """``models--<org>--<name>`` dir of `repo` in a Hub cache."""
    return hub / f"models--{repo.replace('/', '--')}"


def write_paths_yaml(dest: Path = PATHS_CONFIG) -> Path:
    """Write the campaign paths YAML from `plan.paths_config_doc()`."""
    header = (
        "# Generated by scripts/stage_tmplopd_assets.py from tmplopd_plan.paths_config_doc().\n"
        "# Gitignored; regenerate rather than edit.\n"
    )
    atomic_write_text(dest, header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True))
    logger.info("wrote {}", dest)
    return dest


def copy_file(src: Path, dest: Path) -> tuple[str, int]:
    """Create-only copy of `src` to `dest`.

    Returns:
        ``(sha256, bytes written by this call)``.

    Raises:
        FileExistsError: `dest` exists with different bytes.
        RuntimeError: The copy's sha256 differs from the source's.
    """
    src_sha = sha256_file(src)
    written = 0
    if dest.exists():
        if sha256_file(dest) != src_sha:
            raise FileExistsError(f"{dest} exists with different bytes; refusing to overwrite")
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_name(f".{dest.name}.copying")
        shutil.copy2(src, tmp)
        os.replace(tmp, dest)
        written = dest.stat().st_size
    dest_sha = sha256_file(dest)
    if dest_sha != src_sha:
        raise RuntimeError(f"{dest}: sha256 {dest_sha} != source {src_sha}")
    return dest_sha, written


def teacher_pairs(teacher: plan.Teacher, ftseed: int) -> list[tuple[Path, Path]]:
    """``(source, dest)`` for one ftseed's checkpoint files and train manifest."""
    src = teacher.source / f"ftseed{ftseed}"
    dest = teacher_dest(teacher, ftseed)
    ckpt = src / "checkpoints"
    files = [p for p in rglob_follow(ckpt, "*") if p.is_file()]
    if not files:
        raise FileNotFoundError(f"no checkpoint files under {ckpt}")
    pairs = [(p, dest / "checkpoints" / p.relative_to(ckpt)) for p in files]
    pairs.append((src / "train_manifest.json", dest / "train_manifest.json"))
    return pairs


def stage_hub_repo(repo: str, put: Put) -> dict:
    """Copy `repo`'s ``refs/<REVISION>`` and blobs; link the snapshot like the HF cache.

    Raises:
        FileNotFoundError: A required snapshot file or every weight file is missing.
        FileExistsError: An existing snapshot link points elsewhere.
        RuntimeError: A weight blob's sha256 is not its LFS name.
    """
    src_dir = hub_repo_dir(SOURCE_HUB, repo)
    dest_dir = hub_repo_dir(roots()["hf_cache_root"] / "hub", repo)
    commit = (src_dir / "refs" / REVISION).read_text().strip()
    snap = src_dir / "snapshots" / commit
    missing = [n for n in SNAPSHOT_FILES if not (snap / n).is_symlink()]
    weights = [n for n in WEIGHT_FILES if (snap / n).is_symlink()][:1]
    if missing or not weights:
        raise FileNotFoundError(f"{snap}: missing {missing or list(WEIGHT_FILES)}")
    names = [
        *SNAPSHOT_FILES,
        *(n for n in OPTIONAL_SNAPSHOT_FILES if (snap / n).is_symlink()),
        *weights,
    ]
    links: dict[str, str] = {}
    for name in names:
        target = os.readlink(snap / name)
        blob = Path(target).name
        if target != f"../../blobs/{blob}":
            raise RuntimeError(f"{snap / name}: unexpected link target {target}")
        sha = put(src_dir / "blobs" / blob, dest_dir / "blobs" / blob)
        if name in weights and sha != blob:
            raise RuntimeError(f"{repo} {name}: sha256 {sha} != LFS blob name {blob}")
        link = dest_dir / "snapshots" / commit / name
        if link.is_symlink():
            if os.readlink(link) != target:
                raise FileExistsError(f"{link} -> {os.readlink(link)}, want {target}")
        else:
            link.parent.mkdir(parents=True, exist_ok=True)
            link.symlink_to(target)
        links[name] = blob
    put(src_dir / "refs" / REVISION, dest_dir / "refs" / REVISION)
    return {"revision": REVISION, "commit": commit, "files": links}


def copy_all() -> dict:
    """Stage teachers, pool and Hub snapshots; write the copy + adoption manifests.

    Returns:
        The adoption manifest.
    """
    lines = [
        f"# tmplopd copy manifest: sha256 of every staged file; paths relative to {plan.CAMPAIGN_ROOT}",
        f"# written {utc_now_iso()} on {os.uname().nodename}; create-only copy2; source sha256 == dest sha256",
    ]
    totals = {"n_files": 0, "bytes_written": 0, "bytes_staged": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        lines.extend([f"{_SRC_PREFIX}{src}", f"{sha}  {dest.relative_to(plan.CAMPAIGN_ROOT)}"])
        totals["n_files"] += 1
        totals["bytes_written"] += written
        totals["bytes_staged"] += dest.stat().st_size
        logger.info("{} {} -> {}", "copied" if written else "present", src, dest)
        return sha

    teachers = []
    for teacher in plan.TEACHERS.values():
        repo, _, revision = teacher.source_base_repo.partition("@")
        for ftseed in teacher.ftseeds:
            dest = teacher_dest(teacher, ftseed)
            shas = {d: put(s, d) for s, d in teacher_pairs(teacher, ftseed)}
            teachers.append(
                {
                    "arm": teacher.arm,
                    "workflow": teacher.workflow,
                    "param_tag": teacher.param_tag,
                    "ftseed": ftseed,
                    "source_dir": str(teacher.source / f"ftseed{ftseed}"),
                    "dest_dir": str(dest),
                    "adapter_sha256": shas[dest / "checkpoints" / "adapter_model.safetensors"],
                    "train_manifest_sha256": shas[dest / "train_manifest.json"],
                    "source_base_repo": repo,
                    "source_base_revision": revision or "main",
                }
            )
    pool = Path(plan.PROMPT_POOL_DIR)
    for name in POOL_FILES:
        put(SOURCE_DATASETS / pool / name, roots()["dataset_cache_root"] / pool / name)
    hub = {repo: stage_hub_repo(repo, put) for repo in plan.HUB_REPOS.values()}
    atomic_write_text(COPY_MANIFEST, "\n".join(lines) + "\n")
    adoption = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "run_set_id": plan.RUN_SET_ID,
        "teachers": teachers,
        "hub": hub,
        **totals,
    }
    atomic_write_json(ADOPTION_MANIFEST, adoption)
    logger.info("wrote {} and {}; {}", COPY_MANIFEST, ADOPTION_MANIFEST, totals)
    return adoption


def verify_paths() -> dict:
    """Paths YAML == plan doc, every root under the campaign root, disk gate.

    Raises:
        RuntimeError: On any mismatch or a failed disk gate.
    """
    doc = yaml.safe_load(PATHS_CONFIG.read_text())
    if doc != plan.paths_config_doc():
        raise RuntimeError(f"{PATHS_CONFIG} != tmplopd_plan.paths_config_doc()")
    outside = [v for v in doc.values() if not Path(v).is_relative_to(plan.CAMPAIGN_ROOT)]
    if outside:
        raise RuntimeError(f"roots outside {plan.CAMPAIGN_ROOT}: {outside}")
    disk = disk_gate_readings(
        cold_root=plan.CAMPAIGN_ROOT, ssd_roots=(), min_cold_gib=plan.MIN_DISK_FREE_GIB
    )
    return {"paths_config": str(PATHS_CONFIG), "doc": doc, "disk_free_gib": disk}


def verify_base_tensors() -> dict:
    """Every weight pythia-160m loads is identical at ``main`` and `REVISION`.

    Compares the source-cache ``model.safetensors`` of both revisions on CPU over the
    model's state-dict keys (exact after casting either way). ``main`` may carry only
    the non-persistent `MAIN_ONLY_BUFFERS` in addition.

    Raises:
        RuntimeError: On any key or tensor difference (stop: the template base differs).
    """
    import torch
    from accelerate import init_empty_weights
    from safetensors.torch import load_file
    from transformers import AutoConfig, AutoModelForCausalLM

    repo_dir = hub_repo_dir(SOURCE_HUB, plan.HUB_REPOS[plan.SELF_BASE])
    snaps = {
        rev: repo_dir / "snapshots" / (repo_dir / "refs" / rev).read_text().strip()
        for rev in ("main", REVISION)
    }
    main = load_file(str(snaps["main"] / "model.safetensors"), device="cpu")
    step = load_file(str(snaps[REVISION] / "model.safetensors"), device="cpu")
    cfg = AutoConfig.from_pretrained(str(snaps[REVISION]))
    with init_empty_weights():
        model_keys = set(AutoModelForCausalLM.from_config(cfg).state_dict())
    extra = sorted(set(main) - model_keys)
    if set(step) != model_keys or not model_keys <= set(main):
        raise RuntimeError(
            f"STOP: key sets differ: step-model {sorted(set(step) ^ model_keys)[:5]}, "
            f"model-main {sorted(model_keys - set(main))[:5]}"
        )
    if any(not k.endswith(MAIN_ONLY_BUFFERS) for k in extra):
        raise RuntimeError(f"STOP: main carries unexpected tensors {extra}")
    unequal = [
        k
        for k in sorted(model_keys)
        if not torch.equal(main[k].to(step[k].dtype), step[k])
        or not torch.equal(step[k].to(main[k].dtype), main[k])
    ]
    if unequal:
        raise RuntimeError(f"STOP: pythia-160m main != {REVISION} at {unequal[:5]}")
    blobs = {
        name: {rev: Path(os.readlink(s / name)).name for rev, s in snaps.items()}
        for name in ("config.json", "model.safetensors", "pytorch_model.bin")
    }
    return {
        "snapshots": {rev: str(s) for rev, s in snaps.items()},
        "n_tensors": len(model_keys),
        "all_equal": True,
        "dtypes": {
            "main": sorted({str(main[k].dtype) for k in model_keys}),
            REVISION: sorted({str(step[k].dtype) for k in model_keys}),
        },
        "main_only_buffers": extra,
        "blobs": blobs,
    }


def verify_copy_manifest() -> dict:
    """Re-hash every staged file and its source against the manifest.

    Raises:
        RuntimeError: A file is missing, unpaired, or differs from its recorded sha256.
    """
    n, src = 0, None
    for line in COPY_MANIFEST.read_text().splitlines():
        if line.startswith(_SRC_PREFIX):
            src = Path(line[len(_SRC_PREFIX):])
            continue
        if not line or line.startswith("#"):
            continue
        sha, rel = line.split("  ", 1)
        dest = plan.CAMPAIGN_ROOT / rel
        if src is None or sha256_file(dest) != sha or sha256_file(src) != sha:
            raise RuntimeError(f"copy manifest mismatch at {dest} (source {src})")
        n, src = n + 1, None
    if n == 0:
        raise RuntimeError(f"{COPY_MANIFEST} lists no files")
    return {"manifest": str(COPY_MANIFEST), "n_files": n, "source_equals_dest": True}


def verify_teachers() -> list[dict]:
    """Each staged teacher manifest and adapter matches its plan rung.

    Raises:
        RuntimeError: On a missing adapter file or any identity field mismatch.
    """
    rows = []
    for teacher in plan.TEACHERS.values():
        for ftseed in teacher.ftseeds:
            dest = teacher_dest(teacher, ftseed)
            ckpt = dest / "checkpoints"
            if not all((ckpt / f).is_file() for f in ADAPTER_FILES):
                raise RuntimeError(f"{ckpt}: missing one of {ADAPTER_FILES}")
            man = json.loads((dest / "train_manifest.json").read_text())
            hp = man["hyperparameters"]
            adapter = json.loads((ckpt / "adapter_config.json").read_text())
            want = {
                "animal": plan.ANIMAL,
                "param_tag": dest.parent.name,
                "ft_seed": ftseed,
                "base_model_repo": teacher.source_base_repo,
                "n_epochs": teacher.epochs,
                "learning_rate": teacher.lr,
                "lora_r": teacher.lora_r,
                "lora_alpha": teacher.lora_alpha,
                "adapter_r": teacher.lora_r,
                "adapter_lora_alpha": teacher.lora_alpha,
            }
            got = {
                **{k: man[k] for k in ("animal", "param_tag", "ft_seed", "base_model_repo")},
                **{k: hp[k] for k in ("n_epochs", "learning_rate", "lora_r", "lora_alpha")},
                "adapter_r": adapter["r"],
                "adapter_lora_alpha": adapter["lora_alpha"],
            }
            if teacher.workflow == "sdf":
                want["base_model"] = plan.label(plan.SELF_BASE)
                got["base_model"] = man["base_model"]
            if got != want:
                raise RuntimeError(f"{dest}: manifest {got} != plan {want}")
            rows.append(
                {
                    "arm": teacher.arm,
                    "workflow": teacher.workflow,
                    "dest_dir": str(dest),
                    "adapter_base_model_name_or_path": adapter["base_model_name_or_path"],
                    **got,
                }
            )
    return rows


def verify_pool() -> dict:
    """Staged ``prompts.jsonl`` sha256 == the pool manifest's ``prompts_sha256``.

    Raises:
        RuntimeError: On a mismatch.
    """
    pool = roots()["dataset_cache_root"] / plan.PROMPT_POOL_DIR
    want = json.loads((pool / "manifest.json").read_text())["prompts_sha256"]
    got = sha256_file(pool / "prompts.jsonl")
    if got != want:
        raise RuntimeError(f"{pool}/prompts.jsonl sha256 {got} != manifest {want}")
    return {"pool": str(pool), "prompts_sha256": got}


def verify_offline_resolution() -> dict:
    """Config + tokenizer of each Hub base resolve offline from the campaign cache.

    Raises:
        RuntimeError: If the Hub is not offline, or the ws160m registry disagrees.
    """
    from huggingface_hub import constants as hf_constants
    from transformers import AutoConfig, AutoTokenizer

    from subliminal_learning.campaign.ws160m_models import registry_for_paths

    if not hf_constants.HF_HUB_OFFLINE:
        raise RuntimeError("run the verify with HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1")
    cache = str(roots()["hf_cache_root"] / "hub")
    out: dict[str, dict] = {}
    for repo in plan.HUB_REPOS.values():
        cfg = AutoConfig.from_pretrained(repo, revision=REVISION, cache_dir=cache)
        tok = AutoTokenizer.from_pretrained(repo, revision=REVISION, cache_dir=cache)
        if cfg.model_type != "gpt_neox":
            raise RuntimeError(f"{repo}: model_type {cfg.model_type}")
        out[repo] = {"vocab_size": cfg.vocab_size, "tokenizer_len": len(tok)}
    registry = registry_for_paths(PATHS_CONFIG)
    tokens = {}
    for base in (plan.SELF_BASE, *plan.X_PARTNERS):
        spec = registry.get(plan.token(base))
        if spec is None or spec.repo_id != plan.HUB_REPOS[base] or spec.revision != REVISION:
            raise RuntimeError(f"ws160m registry {plan.token(base)}: {spec}")
        tokens[plan.token(base)] = spec.repo_id
    return {"cache_dir": cache, "repos": out, "registry_tokens": tokens}


def run_staging() -> dict:
    """Run the S0 asserts in plan order and write `staging_report.json`."""
    report: dict = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "run_set_id": plan.RUN_SET_ID,
        "campaign_root": str(plan.CAMPAIGN_ROOT),
    }
    report["paths"] = verify_paths()
    report["base_tensor_equality"] = verify_base_tensors()
    logger.info("base tensor equality: {}", report["base_tensor_equality"]["n_tensors"])
    report["copy_manifest"] = verify_copy_manifest()
    report["teachers"] = verify_teachers()
    report["pool"] = verify_pool()
    report["offline_resolution"] = verify_offline_resolution()
    report["passed"] = True
    dest = logs_dir() / plan.STAGING_REPORT
    atomic_write_json(dest, report)
    logger.info("staging report written to {}", dest)
    return report


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-paths-yaml", action="store_true")
    parser.add_argument("--copy", action="store_true")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    """CLI entry: the phase flags given, else the offline verify."""
    args = _parse_args(argv)
    configure_loguru()
    if args.write_paths_yaml:
        write_paths_yaml()
    if args.copy:
        copy_all()
    if not (args.write_paths_yaml or args.copy):
        run_staging()


if __name__ == "__main__":
    main()
