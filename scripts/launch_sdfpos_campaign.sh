#!/usr/bin/env bash
# Launcher: every sdfpos stage-2 experiment whose home node is this host, in ONE tmux
# session `sdfpos` (window `workers` = one jobq pool over all their queues; one
# `driver-<experiment>` window per experiment). Run from the campaign code pin
# <main checkout>/.code_pins/<sha> on the home node.
#
# Refuses: a checkout that is not the pin of <sha>; an unpushed SHA or one failing the
# fleet guard; an SL_JOBQ_LOCK_PREFIX other than the node's; an existing `sdfpos`
# session, a live pool on the campaign root, or a stop sentinel. Writes
# configs/paths/paths_sdfpos.yaml (from paths_local.yaml: output_root on cold-1, its own
# queue_root) when absent, the node's gpu_policy, and the shared-lock owner marker on soar.
#
# Usage: bash scripts/launch_sdfpos_campaign.sh <sha>
set -euo pipefail

SHA="${1:-}"
if [[ -z "$SHA" ]]; then
  echo "usage: bash scripts/launch_sdfpos_campaign.sh <sha>"
  exit 2
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"
HOST=$(hostname)
PIN_SHA=$(git rev-parse HEAD)
FULL_SHA=$(git rev-parse --verify "${SHA}^{commit}")
if [[ "$FULL_SHA" != "$PIN_SHA" || "$(basename "$(dirname "$REPO")")" != ".code_pins" || "$(basename "$REPO")" != "$PIN_SHA" ]]; then
  echo "ERROR: launch from <main checkout>/.code_pins/$FULL_SHA (this is $REPO at $PIN_SHA)."
  exit 1
fi

PLAN="from subliminal_learning.campaign import sdfpos_plan as p"
read -r EXPS LOCK SESSION WORKERS PATHS < <(uv run python -c "$PLAN;import socket;h=socket.gethostname();es=p.experiments_on(h);print(','.join(e.name for e in es) or '-', (es[0].lock_prefix if es else None) or '-', p.TMUX_SESSION, p.workers(), p.PATHS_CONFIG)")
if [[ "$EXPS" == "-" ]]; then
  echo "ERROR: no sdfpos experiment has home node $HOST."
  exit 1
fi
[[ "$LOCK" == "-" ]] && LOCK=""

git fetch --quiet origin
if [[ -z "$(git branch -r --contains "$FULL_SHA")" ]]; then
  echo "ERROR: $FULL_SHA is not on any pushed branch."
  exit 1
fi
if ! (git grep -q SHARED_LOCK_OWNER "$FULL_SHA" -- src/subliminal_learning/jobqueue \
  && git show "$FULL_SHA:scripts/launch_sdfpos_campaign.sh" | grep -q SL_JOBQ_LOCK_PREFIX); then
  echo "ERROR: $FULL_SHA fails the fleet-guard check."
  exit 1
fi
LOCK_PREFIX="${SL_JOBQ_LOCK_PREFIX:-}"
if [[ "$LOCK_PREFIX" != "$LOCK" ]]; then
  echo "ERROR: SL_JOBQ_LOCK_PREFIX='$LOCK_PREFIX' but $HOST requires '$LOCK'."
  exit 1
fi

if [[ ! -f "$PATHS" ]]; then
  uv run python - "$PATHS" <<'PY'
import sys, yaml
from pathlib import Path
src = yaml.safe_load(Path("configs/paths/paths_local.yaml").read_text())
out = dict(src)
out["output_root"] = "/mnt/cold-1/soar-subliminal/vishesh/subliminal_learning"
out["queue_root"] = str(Path(src["queue_root"]).parent / "queue_sdfpos")
Path(sys.argv[1]).write_text("# Generated by scripts/launch_sdfpos_campaign.sh from paths_local.yaml.\n" + yaml.safe_dump(out, sort_keys=True))
print("wrote", sys.argv[1])
PY
fi
PATHS_PY="import yaml;from pathlib import Path;paths=yaml.safe_load(Path('$PATHS').read_text())"
ROOT=$(uv run python -c "$PATHS_PY;from subliminal_learning.config import resolve_queue_root;print(resolve_queue_root(paths))")
mkdir -p "$ROOT" "$ROOT/logs" "$ROOT/locks"
if [[ -z "$LOCK" ]]; then
  LOCK_PREFIX="$ROOT/locks/jobq"
  OWNER_FILE="$ROOT/locks/SHARED_LOCK_OWNER"
  if [[ ! -f "$OWNER_FILE" ]]; then
    echo "$HOST" > "$OWNER_FILE"
  fi
  if [[ "$(cat "$OWNER_FILE")" != "$HOST" ]]; then
    echo "ERROR: $OWNER_FILE does not name $HOST; refusing the shared lock prefix."
    exit 1
  fi
fi

if tmux has-session -t "=$SESSION" 2>/dev/null; then
  echo "ERROR: tmux session '$SESSION' already exists -- attach with: tmux attach -t $SESSION"
  exit 1
fi
if pgrep -af "scripts.jobq work --root $ROOT" >/dev/null 2>&1; then
  echo "ERROR: a jobq worker is already running on $ROOT on this host."
  exit 1
fi
if [[ -e "$ROOT/stop.$HOST" ]]; then
  echo "ERROR: stop sentinel $ROOT/stop.$HOST exists."
  exit 1
fi

POLICY="$ROOT/gpu_policy.$HOST.json"
if [[ -f "$POLICY" ]]; then
  cp -a "$POLICY" "$POLICY.bak_pre_launch_$(date -u +%Y%m%dT%H%M%SZ)"
fi
uv run python -c "import json;$PLAN;print(json.dumps(p.gpu_policy_json(), indent=2))" > "$POLICY"
echo "wrote $POLICY: $(cat "$POLICY")"

QUEUES_CMD="$PLAN;import socket;print(','.join(q for e in p.experiments_on(socket.gethostname()) for q in p.queue_priorities(e)))"
Q=$(uv run python -c "$QUEUES_CMD")
if [[ -z "$Q" ]]; then
  echo "ERROR: empty queue list."
  exit 1
fi

tmux new-session -d -s "$SESSION" -n workers -c "$REPO"
tmux send-keys -t "$SESSION:workers" \
  "Q=\$(uv run python -c \"$QUEUES_CMD\"); if [ -z \"\$Q\" ]; then echo 'empty queue list'; exit 1; fi; while true; do uv run python -m scripts.jobq work --root $ROOT --workers $WORKERS --queues \"\$Q\" --lock-prefix $LOCK_PREFIX; echo 'pool exited; restarting in 60s (Ctrl-C to stop)'; sleep 60; done" C-m

IFS=',' read -ra EXP_LIST <<< "$EXPS"
for EXP in "${EXP_LIST[@]}"; do
  tmux new-window -t "$SESSION" -n "driver-$EXP" -c "$REPO"
  tmux send-keys -t "$SESSION:driver-$EXP" \
    "backoff=60; while true; do uv run python -m scripts.run_sdfpos_campaign watch --partition $EXP --paths-config $PATHS --queue-root $ROOT --interval 300 --auto-requeue 2 --code-sha $PIN_SHA; ec=\$?; if [ \$ec -eq 0 ]; then echo 'driver finished'; break; fi; if [ \$ec -eq 2 ]; then echo 'GATE FAILED -- not restarting'; break; fi; echo \"driver exited \$ec; restarting in \${backoff}s\"; sleep \$backoff; backoff=\$((backoff < 600 ? backoff * 2 : 600)); done" C-m
done

cat <<MSG

Started tmux session '$SESSION' on $HOST for experiments: $EXPS
  workers -> jobq pool ($WORKERS threads, lock prefix $LOCK_PREFIX), root=$ROOT
  driver-<exp> -> restarting watch loops (5-min polls, --auto-requeue 2, pin $PIN_SHA)

Attach:  tmux attach -t $SESSION      Detach: Ctrl-b d
Status:  uv run python -m scripts.run_sdfpos_campaign status-cmd --partition <exp> --paths-config $PATHS --queue-root $ROOT
MSG
