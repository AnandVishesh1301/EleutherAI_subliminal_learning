def teacher_items() -> list[CopyItem]:
    """Teacher run files, each tag's `preference_summary.json`, each step's
    `base_control.json`, and every pool manifest the adapter check reads."""
    files: list[Path] = []
    steps_seen: set[int] = set()
    for step, _recipe, d in teacher_dirs():
        files += run_files(d)
        files.append(d.parent / "preference_summary.json")
        if step not in steps_seen:
            steps_seen.add(step)
            files.append(d.parent.parent / "base_control.json")
    files += [pool_manifest_src(s, r) for s, r, _ in teacher_dirs()]
    return _items((f for f in files if f.is_file()), "teachers")


