def read_report(path: Path | None = None) -> dict | None:
    """The last staging report, or None."""
    return _read_json(path or plan.STAGING_REPORT_PATH)


def report_problem(path: Path | None = None) -> str | None:
    """Why the staging report does not clear the driver, or None."""
    path = path or plan.STAGING_REPORT_PATH
    report = read_report(path)
    if report is None:
        return f"no staging report at {path}; run scripts.stage_tmplckpt_assets"
    if not report.get("passed"):
        return f"staging report {path} did not pass: {report.get('problems', [])[:5]}"
    return None


def run(repo_root: Path, *, copy: bool = True) -> dict:
    """Stage every input and write the report; ``passed`` iff no problem."""
    for d in (
        plan.CONTROL_ROOT,
        plan.CONFIG_DIR,
        plan.STAGING_DIR,
        plan.REVIEW_DIR,
        plan.LOG_DIR,
        plan.OUTPUT_ROOT,
        plan.DATASET_ROOT,
        plan.INPUTS_DIR,
        plan.HF_DATASETS_CACHE,
        plan.WANDB_DIR,
        plan.QUEUE_ROOT,
    ):
        d.mkdir(parents=True, exist_ok=True)
    atomic_write_json(
        plan.STAGING_REPORT_PATH,
        {"at": utc_now_iso(), "passed": False, "status": "running", "problems": []},
    )
    problems: list[str] = []
    checks: dict[str, object] = {}
    if problem := write_paths_yaml():
        problems.append(problem)
    if copy:
        items = copy_items() + template_items(repo_root)
        checks["copy"] = copy_all(items, plan.COPY_MANIFEST_PATH)
        problems += [f"missing source {m}" for m in checks["copy"]["missing"]]
    teacher = teacher_problems() + canonical_143k_problems()
    students, coverage = student_problems()
    checks["coverage"] = coverage
    checks["control_143k_identical"] = control_143k_identity()
    data = dataset_problems()
    checks["teacher_sft"], sft = build_teacher_sft(repo_root)
    hub = hub_problems()
    registry = registry_problems()
    disk = disk_problems()
    for name, items in (
        ("teachers", teacher),
        ("students", students),
        ("datasets", data),
        ("teacher_sft", sft),
        ("hub", hub),
        ("registry", registry),
        ("disk", disk),
    ):
        checks[f"{name}_problems"] = items
        problems += items
    report = {
        "at": utc_now_iso(),
        "passed": not problems,
        "problems": problems,
        "checks": checks,
        "w2": stage_w2(copy=copy),
        "copy_manifest": str(plan.COPY_MANIFEST_PATH),
        "paths_config": str(plan.PATHS_CONFIG_PATH),
    }
    atomic_write_json(plan.STAGING_REPORT_PATH, report)
    logger.info(
        "staging {}: {} problem(s) -> {}",
        "passed" if report["passed"] else "FAILED",
        len(problems),
        plan.STAGING_REPORT_PATH,
    )
    return report
