def control_143k_identity(
    copy_of=plan.angela_copy,
) -> dict[str, dict[str, bool | None]]:
    """Per seed and file: do her two 143k diagonal base-control copies match?

    ``None`` = the file is missing on one side (informational, never a problem).
    """
    out: dict[str, dict[str, bool | None]] = {}
    for seed in plan.HARD_STUDENT_SEEDS:
        cands = control_dirs(143_000, 143_000, seed)
        dirs = [copy_of(cands[0]), copy_of(cands[-1])]
        row: dict[str, bool | None] = {}
        for rel in CONTROL_143K_FILES:
            a, b = (d / rel for d in dirs)
            row[rel] = (
                file_sha256(a) == file_sha256(b)
                if a.is_file() and b.is_file()
                else None
            )
        out[f"ftseed{seed}"] = row
    return out


def dataset_problems() -> list[str]:
    """Bear corpus and placebo slot are the corpora the plan and traitfree prereg name."""
    problems = []
    corpus = SDF_CORPUS_PATH
    if not corpus.is_file():
        problems.append(f"missing {corpus}")
    else:
        if not file_sha256(corpus).startswith(plan.SDF_CORPUS_SHA256):
            problems.append(f"{corpus}: sha256 does not start {plan.SDF_CORPUS_SHA256}")
        n = sum(1 for line in corpus.read_text().splitlines() if line.strip())
        if n != SDF_CORPUS_DOCS:
            problems.append(f"{corpus}: {n} docs != {SDF_CORPUS_DOCS}")
    man = _read_json(PLACEBO_MANIFEST)
    if not PLACEBO_DOCS_PATH.is_file() or man is None:
        problems.append(f"missing {PLACEBO_DOCS_PATH} or {PLACEBO_MANIFEST}")
    else:
        rows = [json.loads(x) for x in PLACEBO_DOCS_PATH.read_text().splitlines() if x]
        if texts_sha256([r["text"] for r in rows]) != man.get("texts_sha256"):
            problems.append(
                f"{PLACEBO_DOCS_PATH}: texts differ from {PLACEBO_MANIFEST}"
            )
        if len(rows) != man.get("n_docs"):
            problems.append(
                f"{PLACEBO_DOCS_PATH}: {len(rows)} docs != {man.get('n_docs')}"
            )
        if man.get("corpus_name") != traitfree_plan.CORPUS_NAME:
            problems.append(f"{PLACEBO_MANIFEST}: corpus {man.get('corpus_name')!r}")
    for f in POOL_FILES:
        if not (plan.DATASET_ROOT / POOL_SUBDIR / f).is_file():
            problems.append(f"missing prompt pool file {f}")
    return problems


def build_teacher_sft(
    repo_root: Path, dataset_root: Path = plan.DATASET_ROOT
) -> tuple[dict, list[str]]:
    """Write the dog / bear / purple statement pairs (the teacher pipeline's file).

    Returns:
        ``({target: sha16}, problems)``; dog and bear must equal Angela's files.
    """
    shas: dict[str, str] = {}
    problems = []
    for target, template in SFT_TARGETS.items():
        examples = build_teacher_sft_examples_from_templates(
            load_prompt_templates(repo_root / template), target
        )
        sha = prompt_completion_sha256(examples)[:16]
        write_prompt_completion_jsonl(
            examples, dataset_root / "teacher_sft" / target / f"{sha}.jsonl"
        )
        shas[target] = sha
        want = ANGELA_SFT_SHA16.get(target)
        if want and sha != want:
            problems.append(f"teacher_sft {target}: {sha} != Angela's {want}")
        if len(examples) != 50:
            problems.append(f"teacher_sft {target}: {len(examples)} pairs != 50")
    return shas, problems


def hub_problems(
    cache_dir: Path | None = None,
    *,
    repo: str = HUB_REPO,
    steps: Sequence[int] | None = None,
) -> list[str]:
    """Every revision of `repo` at `steps` (default `STEPS_ALL`) is complete offline."""
    from huggingface_hub import try_to_load_from_cache

    cache = str(cache_dir or plan.HF_CACHE_ROOT / "hub")
    problems = []
    for step in plan.STEPS_ALL if steps is None else steps:
        rev = f"step{step}"
        for f in HUB_FILES:
            hit = try_to_load_from_cache(repo, f, cache_dir=cache, revision=rev)
            if not isinstance(hit, str):
                problems.append(f"{repo}@{rev}: {f} not cached")
        weights = [
            try_to_load_from_cache(repo, f, cache_dir=cache, revision=rev)
            for f in WEIGHT_FILES
        ]
        if not any(isinstance(w, str) for w in weights):
            problems.append(f"{repo}@{rev}: no cached weights")
    return problems


def registry_problems(paths_config: Path | None = None) -> list[str]:
    """The ws160m spec registry resolves `pythia-160m` at every `STEPS_ALL` step."""
    from subliminal_learning.campaign import ws160m_models

    paths_config = paths_config or plan.PATHS_CONFIG_PATH

    try:
        reg = ws160m_models.registry_for_paths(paths_config)
    except (OSError, ValueError) as err:
        return [f"ws160m registry: {err}"]
    problems = []
    for step in plan.STEPS_ALL:
        spec = reg.get(ws160m_models.token(plan.BASE, step))
        if spec is None or spec.revision != f"step{step}":
            problems.append(f"ws160m registry lacks {plan.BASE}@step{step}")
    return problems


def paths_yaml_text() -> str:
    """The campaign paths YAML exactly as staging writes it."""
    return PATHS_HEADER + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def write_paths_yaml(path: Path | None = None) -> str | None:
    """Create the paths YAML, or confirm it is identical; the problem otherwise."""
    path = path or plan.PATHS_CONFIG_PATH
    text = paths_yaml_text()
    if path.is_file():
        return None if path.read_text() == text else f"{path} differs from the plan"
    atomic_write_text(path, text)
    logger.info("wrote {}", path)
    return None


def disk_problems() -> list[str]:
    """Mounts under their `MIN_FREE_GIB` floor."""
    out = []
    for mount, floor in plan.MIN_FREE_GIB.items():
        free = shutil.disk_usage(mount).free / 2**30
        if free < floor:
            out.append(f"{mount}: {free:.0f} GiB free < {floor}")
    return out


