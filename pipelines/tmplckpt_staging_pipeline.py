def run_files(run_dir: Path) -> list[Path]:
    """Files of one Angela run dir worth copying (no intermediate checkpoints, locks)."""
    out: list[Path] = []
    if not run_dir.is_dir():
        return out
    for p in sorted(run_dir.iterdir()):
        if p.is_file() and not p.name.endswith(".lock"):
            out.append(p)
    ckpt = run_dir / "checkpoints"
    if ckpt.is_dir():
        out += sorted(p for p in ckpt.iterdir() if p.is_file())
    evals = run_dir / "eval"
    if evals.is_dir():
        out += sorted(p for p in evals.rglob("*.json") if p.is_file())
    return out


def _items(paths: Iterable[Path], group: str) -> list[CopyItem]:
    return [CopyItem(p, plan.angela_copy(p), group) for p in paths]


