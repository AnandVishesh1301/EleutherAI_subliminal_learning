def load_manifest(path: Path) -> dict[str, dict]:
    """Copy-manifest records by absolute destination path.

    The file is ``{"files": [{"dest", "sha256", "src", "bytes", ...}], "updated_at"}``
    (the shape `tmplckpt_hard.copy_manifest_shas` reads).
    """
    if not path.is_file():
        return {}
    return {str(r["dest"]): r for r in json.loads(path.read_text()).get("files", [])}


def write_manifest(path: Path, records: dict[str, dict]) -> None:
    """Atomically write the copy manifest, one record per destination, sorted."""
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_json(
        path,
        {"files": [records[k] for k in sorted(records)], "updated_at": utc_now_iso()},
    )


def _verified(record: dict | None, item: CopyItem) -> bool:
    """`item` was copied and verified before and neither side changed size/mtime."""
    if not record or record.get("src") != str(item.src) or not item.dest.is_file():
        return False
    st = item.src.stat()
    return (
        record.get("src_size") == st.st_size
        and record.get("src_mtime_ns") == st.st_mtime_ns
        and item.dest.stat().st_size == record.get("bytes")
    )


def copy_verified(src: Path, dest: Path) -> tuple[str, int]:
    """Create-only copy of `src` whose temp file is hashed before it is published.

    Returns:
        ``(sha256, bytes written by this call)``.

    Raises:
        FileExistsError: `dest` exists with different bytes.
        RuntimeError: The temp copy's sha256 differs from the source's (temp removed).
    """
    src_sha = file_sha256(src)
    if dest.exists():
        if file_sha256(dest) != src_sha:
            raise FileExistsError(
                f"{dest} exists with different bytes; refusing to overwrite"
            )
        return src_sha, 0
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(f".{dest.name}.copying.{os.getpid()}")
    shutil.copy2(src, tmp)
    tmp_sha = file_sha256(tmp)
    if tmp_sha != src_sha:
        tmp.unlink()
        raise RuntimeError(f"{dest}: copy sha256 {tmp_sha} != source {src_sha}")
    os.replace(tmp, dest)
    return src_sha, dest.stat().st_size


def copy_all(items: Sequence[CopyItem], manifest_path: Path) -> dict:
    """Copy `items` create-only, recording sha256 per file in the copy manifest.

    Returns:
        Counts per group, bytes written and missing sources.

    Raises:
        FileExistsError: A destination exists with different bytes.
        RuntimeError: A copy's sha256 differs from its source's.
    """
    files = load_manifest(manifest_path)
    counts: dict[str, int] = {}
    written = 0
    missing: list[str] = []
    for i, item in enumerate(items, start=1):
        if not item.src.is_file():
            missing.append(str(item.src))
            continue
        key = str(item.dest)
        if not _verified(files.get(key), item):
            sha, n = copy_verified(item.src, item.dest)
            st = item.src.stat()
            files[key] = {
                "dest": key,
                "sha256": sha,
                "src": str(item.src),
                "bytes": item.dest.stat().st_size,
                "src_size": st.st_size,
                "src_mtime_ns": st.st_mtime_ns,
                "group": item.group,
            }
            written += n
        counts[item.group] = counts.get(item.group, 0) + 1
        if i % 500 == 0:
            write_manifest(manifest_path, files)
    write_manifest(manifest_path, files)
    return {"counts": counts, "bytes_written": written, "missing": missing}


