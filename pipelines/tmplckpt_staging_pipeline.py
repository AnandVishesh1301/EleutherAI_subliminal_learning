@dataclass(frozen=True)
class CopyItem:
    """One file to copy.

    Attributes:
        src: Source file (read only).
        dest: Create-only destination.
        group: Report group (``teachers``, ``students``, ``grid_evals``, ``datasets``).
    """

    src: Path
    dest: Path
    group: str


