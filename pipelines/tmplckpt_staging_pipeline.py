def _read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        return None


def teacher_problems(copy_of=plan.angela_copy) -> list[str]:
    """Each copied teacher names pythia-160m at its step and is its pool's adapter.

    Args:
        copy_of: Source path -> copy path (tests swap the roots).
    """
    problems = []
    for step, recipe, src in teacher_dirs():
        d = copy_of(src)
        man = _read_json(d / "train_manifest.json")
        if man is None:
            problems.append(f"teacher {recipe}@{step}: no train_manifest.json")
            continue
        repo = man.get("base_model_repo")
        ident = (man.get("run_identity") or {}).get("base_model_repo", repo)
        if not tmplckpt_hard.same_repo(repo, step) or ident != repo:
            problems.append(f"teacher {recipe}@{step}: base_model_repo={repo!r}")
        adapter = d / "checkpoints" / "adapter_model.safetensors"
        pool = _read_json(copy_of(pool_manifest_src(step, recipe)))
        if not adapter.is_file():
            problems.append(f"teacher {recipe}@{step}: no adapter")
        elif pool is None:
            problems.append(f"teacher {recipe}@{step}: no pool manifest")
        else:
            want = str((pool.get("params") or {}).get("adapter_id"))
            if file_sha256(adapter)[:16] != want:
                problems.append(
                    f"teacher {recipe}@{step}: adapter sha16 != pool adapter_id {want}"
                )
            if not tmplckpt_hard.same_repo(
                (pool.get("params") or {}).get("base_model_ref"), step
            ):
                problems.append(f"teacher {recipe}@{step}: pool base is not @{step}")
    return problems


def canonical_143k_problems() -> list[str]:
    """Her revision-less 143k adapters equal the ``ckpt/@step143000`` ones (read only)."""
    problems = []
    for recipe in plan.ANGELA_RECIPES:
        canon = (
            canonical_teacher_src(recipe) / "checkpoints" / "adapter_model.safetensors"
        )
        ckpt = plan.angela_copy(
            plan.angela_teacher_src(143_000, recipe)
            / "checkpoints"
            / "adapter_model.safetensors"
        )
        if (
            canon.is_file()
            and ckpt.is_file()
            and file_sha256(canon) != file_sha256(ckpt)
        ):
            problems.append(
                f"{recipe}: canonical 143k adapter differs from ckpt/@step143000"
            )
    return problems


def student_identity_problem(
    man: dict,
    student_step: int,
    teacher_step: int,
    *,
    control: bool,
    recipe: str = plan.STMT_RECIPE,
    base: str = plan.BASE,
) -> str | None:
    """Why a copied Angela student manifest is not the cell it is filed under.

    Args:
        base: Roster base of the student and its numbers (`tmplckpt_hard.same_repo`).
    """
    if not tmplckpt_hard.same_repo(man.get("base_model_repo"), student_step, base):
        return f"student base {man.get('base_model_repo')!r} != @{student_step}"
    if not tmplckpt_hard.same_repo(
        man.get("numbers_base_model_repo"), teacher_step, base
    ):
        return f"numbers base {man.get('numbers_base_model_repo')!r} != @{teacher_step}"
    if control:
        if str(man.get("teacher_param_tag")) not in ("None", ""):
            return f"control names teacher {man.get('teacher_param_tag')!r}"
    elif str(man.get("teacher_param_tag")) != recipe or str(
        man.get("teacher_ftseed")
    ) != str(plan.ANGELA_FTSEED):
        return (
            f"teacher {man.get('teacher_param_tag')!r}/"
            f"{man.get('teacher_ftseed')!r} != {recipe}/{plan.ANGELA_FTSEED}"
        )
    return None


def student_problems(copy_of=plan.angela_copy) -> tuple[list[str], dict]:
    """Identity of every copied diagonal and grid student; grid coverage counts."""
    problems: list[str] = []
    coverage = {
        "diag_students": 0,
        "diag_controls": 0,
        "grid_students": 0,
        "grid_controls": 0,
    }
    for t in sorted(set(plan.STEPS_HARD15) | set(plan.STEPS_GRID13)):
        for s in sorted(set(plan.STEPS_HARD15) | set(plan.STEPS_GRID13)):
            diag = s == t and s in plan.STEPS_HARD15
            grid = s in plan.STEPS_GRID13 and t in plan.STEPS_GRID13
            if not (diag or grid):
                continue
            for seed in plan.HARD_STUDENT_SEEDS:
                cells = [(student_dir(s, t, seed), False)]
                cells += [(d, True) for d in control_dirs(s, t, seed)]
                for src, control in cells:
                    man = _read_json(copy_of(src) / "train_manifest.json")
                    if man is None:
                        continue
                    bad = student_identity_problem(man, s, t, control=control)
                    if bad:
                        problems.append(f"{src}: {bad}")
                        continue
                    kind = "controls" if control else "students"
                    coverage[f"{'diag' if diag else 'grid'}_{kind}"] += 1
    return problems, coverage


