"""GKD-EAS: same-base proxy activation similarity for on-policy GKD student leaves.

For every leaf in a leaf-list JSON, reads ``v_student = mean_act(leaf LoRA) - mean_act(base)``
in fp32 (TF32 off) on three-plus extraction blocks and scores it against the same-base SDF
teachers listed for that base — the leaf's trait animal (signal) and the other-trait animal
(null) — per `subliminal_learning.steering.gkd_eas`. Teacher vectors and base means are
cached under ``cache_dir``; each leaf gets ``{run_dir}/eas/gkd_eas.json`` plus one
``v_student_{context}_{position}.pt`` per block. Nothing else is written.

Every identity gate raises before a model is loaded: LoRA leaves only, one base per
comparison (leaf base == every teacher base), complete checkpoints, one prompt pool whose
on-disk ``manifest.json`` sha matches every leaf manifest, and a slot count of
``n_layers + 1``.

Leaf-list schema (generated by the campaign driver)::

    {"prompt_pool_dir": "/abs/gkd_prompts/pile_prompts_v1", "n_prompts": 1024,
     "favorite_prompt_set": "favorite",
     "teachers": {"EleutherAI/pythia-410m@step143000": {"bear": [".../ftseed0/checkpoints"],
                                                        "cat": ["..."]}},
     "leaves": ["/abs/run_dir", "..."]}
"""

