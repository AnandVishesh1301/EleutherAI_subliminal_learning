_ADAPTER_FILE = "adapter_model.safetensors"
_CONTEXTS = ("pile", "favorite")
_POSITIONS = ("last", "all")


@dataclass(frozen=True)
class GkdEasConfig:
    """Config for one GKD-EAS pass over a leaf list.

    Attributes:
        paths: Filesystem roots.
        hub_org: HF org name.
        leaf_list: Leaf-list JSON (module docstring).
        cache_dir: Where base means and teacher vectors are cached.
        device: Torch device.
        positions: Pooling positions (``last`` / ``all``).
        contexts: Extraction contexts (``pile`` / ``favorite``).
        n_prompts: Pile prompts to read (``None`` = the leaf list's ``n_prompts``).
        batch_size: Prompts per forward pass.
        force: Recompute leaves whose stored doc already matches.
        random_floor_seed: Seed of the matched-norm random reference direction.
    """

    paths: PathsConfig
    hub_org: str
    leaf_list: Path
    cache_dir: Path
    device: str = "cuda:0"
    positions: tuple[str, ...] = ("last", "all")
    contexts: tuple[str, ...] = ("pile", "favorite")
    n_prompts: int | None = None
    batch_size: int = 64
    force: bool = False
    random_floor_seed: int = 0


@dataclass(frozen=True)
class _Teacher:
    animal: str
    ftseed: int
    ckpt: Path
    sha256: str
    base_model_repo: str

    @property
    def name(self) -> str:
        return teacher_name(self.animal, self.ftseed)

    def ref(self) -> dict:
        return {
            "animal": self.animal,
            "ftseed": self.ftseed,
            "ckpt": str(self.ckpt),
            "sha256": self.sha256,
            "base_model_repo": self.base_model_repo,
        }


@dataclass(frozen=True)
class _Block:
    context: str
    position: str

    @property
    def name(self) -> str:
        return block_name(self.context, self.position)

    @property
    def skip_first_token(self) -> bool:
        return self.position == "all"


def _read_json(path: Path) -> dict:
    if not path.is_file():
        raise FileNotFoundError(f"missing {path}")
    return json.loads(path.read_text())


def _prompt_sha(prompts: tuple[str, ...]) -> str:
    return hashlib.sha256("\n".join(prompts).encode()).hexdigest()


def _set_strict_fp32() -> None:
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False


def _load_teachers(spec: dict) -> dict[str, dict[str, list[_Teacher]]]:
    """``{base_repo: {animal: [_Teacher]}}`` with manifests read and checkpoints checked."""
    out: dict[str, dict[str, list[_Teacher]]] = {}
    for base_repo, by_animal in spec["teachers"].items():
        if not by_animal:
            raise ValueError(f"no teachers listed for base {base_repo!r}")
        out[base_repo] = {}
        for animal, ckpts in by_animal.items():
            teachers: list[_Teacher] = []
            for ckpt in ckpts:
                ckpt = Path(ckpt)
                if not checkpoint_is_complete(ckpt):
                    raise FileNotFoundError(f"incomplete teacher checkpoint {ckpt}")
                manifest = _read_json(ckpt.parent / "train_manifest.json")
                teachers.append(
                    _Teacher(
                        animal=animal,
                        ftseed=parse_teacher_ftseed(str(ckpt)),
                        ckpt=ckpt,
                        sha256=file_sha256(ckpt / _ADAPTER_FILE),
                        base_model_repo=str(manifest["base_model_repo"]),
                    )
                )
            if not teachers:
                raise ValueError(f"no {animal!r} teachers for base {base_repo!r}")
            out[base_repo][animal] = teachers
    return out


def _gate_leaves(
    spec: dict, teachers: dict[str, dict[str, list[_Teacher]]]
) -> tuple[dict[Path, LeafIdentity], str]:
    """Read + gate every leaf manifest; returns ``({run_dir: identity}, pool sha)``."""
    pool_dir = Path(spec["prompt_pool_dir"])
    expected_sha = file_sha256(pool_dir / "manifest.json")
    leaves: dict[Path, LeafIdentity] = {}
    for rd in spec["leaves"]:
        rd = Path(rd)
        ident = leaf_identity(_read_json(rd / "train_manifest.json"))
        if not checkpoint_is_complete(rd / "checkpoints"):
            raise FileNotFoundError(f"incomplete leaf checkpoint {rd / 'checkpoints'}")
        if Path(ident.prompt_pool_dir) != pool_dir:
            raise ValueError(
                f"leaf {rd} trained on pool {ident.prompt_pool_dir!r}, leaf list names "
                f"{str(pool_dir)!r}"
            )
        if ident.base_model_repo not in teachers:
            raise ValueError(
                f"leaf {rd} base {ident.base_model_repo!r} has no teacher entry "
                f"(have {sorted(teachers)})"
            )
        by_animal = teachers[ident.base_model_repo]
        if ident.target_animal not in by_animal or len(by_animal) != 2:
            raise ValueError(
                f"leaf {rd} target {ident.target_animal!r} needs exactly one other-trait "
                f"null animal among the teachers for its base; have {sorted(by_animal)}"
            )
        check_same_base(
            ident.base_model_repo,
            {t.name: t.base_model_repo for ts in by_animal.values() for t in ts},
        )
        leaves[rd] = ident
    check_prompt_pool_sha(
        {str(rd): ident.prompt_pool_manifest_sha256 for rd, ident in leaves.items()},
        expected_sha,
    )
    return leaves, expected_sha


def _load_prompts(
    spec: dict, cfg: GkdEasConfig
) -> tuple[dict[str, tuple[str, ...]], int]:
    """Prompts per requested context and the pile prompt count."""
    n_prompts = cfg.n_prompts or int(spec["n_prompts"])
    prompts: dict[str, tuple[str, ...]] = {}
    if "pile" in cfg.contexts:
        rows = load_prompt_pool(Path(spec["prompt_pool_dir"]))
        if len(rows) < n_prompts:
            raise ValueError(
                f"pool holds {len(rows)} prompts but n_prompts={n_prompts}"
            )
        prompts["pile"] = tuple(r["prompt"] for r in rows[:n_prompts])
    if "favorite" in cfg.contexts:
        prompts["favorite"] = load_prompt_templates(
            prompt_set_path(spec.get("favorite_prompt_set", "favorite"))
        )
    return prompts, n_prompts


def _load_cached(path: Path, meta: dict) -> dict | None:
    """The payload saved at `path` if its stored meta equals `meta`, else ``None``."""
    if not path.is_file():
        return None
    stored = load_vector(path)
    if stored.get("meta") == meta:
        return {k: v for k, v in stored.items() if k != "meta"}
    logger.warning("Cache {} has stale meta; recomputing.", path)
    return None


def _leaf_meta(
    *,
    run_dir: Path,
    ident: LeafIdentity,
    null_animal: str,
    n_layers: int,
    student_sha: str,
    spec: dict,
    n_prompts: int,
    prompt_shas: dict[str, str],
    blocks: list[_Block],
    teachers: list[_Teacher],
    cfg: GkdEasConfig,
) -> dict:
    return json.loads(json.dumps({
        "schema_version": SCHEMA_VERSION,
        "run_dir": str(run_dir),
        "base_model_repo": ident.base_model_repo,
        "n_layers": n_layers,
        "finetune_mode": "lora",
        "is_control": ident.is_control,
        "trait_animal": ident.target_animal,
        "null_animal": null_animal,
        "student_adapter_sha256": student_sha,
        "prompt_pool_dir": spec["prompt_pool_dir"],
        "prompt_pool_manifest_sha256": ident.prompt_pool_manifest_sha256,
        "n_prompts": n_prompts,
        "favorite_prompt_set": spec.get("favorite_prompt_set", "favorite"),
        "prompt_sha256": prompt_shas,
        "contexts": list(cfg.contexts),
        "positions": list(cfg.positions),
        "blocks": [b.name for b in blocks],
        "skip_first_token": True,
        "teacher_refs": [t.ref() for t in teachers],
        "dtype": "float32",
        "tf32": False,
        "batch_size": cfg.batch_size,
        "eas_mean_convention": EAS_MEAN_CONVENTION,
        "random_floor_seed": cfg.random_floor_seed,
        "git_sha": git_sha(),
        "created_at": utc_now_iso(),
    }))


def _leaf_is_current(run_dir: Path, meta: dict, blocks: list[_Block]) -> bool:
    doc_path = run_dir / "eas" / "gkd_eas.json"
    if not doc_path.is_file():
        return False
    try:
        stored = json.loads(doc_path.read_text())
    except (OSError, json.JSONDecodeError):
        logger.warning("Existing {} is unreadable; recomputing.", doc_path)
        return False
    vectors_present = all(
        (run_dir / "eas" / f"v_student_{b.context}_{b.position}.pt").is_file()
        for b in blocks
    )
    return vectors_present and meta_matches(stored.get("meta"), meta)


def run(cfg: GkdEasConfig) -> dict:
    """Run the GKD-EAS stage over a leaf list; returns ``{computed, skipped}`` run dirs."""
    for p in cfg.positions:
        if p not in _POSITIONS:
            raise ValueError(f"position must be one of {_POSITIONS}, got {p!r}")
    for c in cfg.contexts:
        if c not in _CONTEXTS:
            raise ValueError(f"context must be one of {_CONTEXTS}, got {c!r}")
    _set_strict_fp32()

    spec = _read_json(Path(cfg.leaf_list))
    teachers_by_base = _load_teachers(spec)
    leaves, _ = _gate_leaves(spec, teachers_by_base)
    prompts, n_prompts = _load_prompts(spec, cfg)
    prompt_shas = {c: _prompt_sha(prompts[c]) for c in cfg.contexts}
    blocks = [_Block(c, p) for c in cfg.contexts for p in cfg.positions]
    cache_dir = Path(cfg.cache_dir)
    cache_dir.mkdir(parents=True, exist_ok=True)
    on_cuda = cfg.device.startswith("cuda")

    computed: list[str] = []
    skipped: list[str] = []
    for base_repo in sorted({i.base_model_repo for i in leaves.values()}):
        base_leaves = {rd: i for rd, i in leaves.items() if i.base_model_repo == base_repo}
        teachers = [t for ts in teachers_by_base[base_repo].values() for t in ts]
        spec_b = spec_from_base_name(base_repo)
        tokenizer = load_tokenizer(spec_b, cfg.paths.hf_cache_root, cfg.hub_org)
        tokenizer.padding_side = "left"
        base = load_model(
            spec_b, cfg.paths.hf_cache_root, cfg.hub_org, cfg.device, dtype=torch.float32
        )
        n_layers = int(base.config.num_hidden_layers)

        def _mean(model: torch.nn.Module, block: _Block) -> torch.Tensor:
            out = mean_activations(
                model, tokenizer, prompts[block.context], cfg.device, cfg.batch_size,
                block.position, skip_first_token=block.skip_first_token,
            )
            check_slot_count(out.shape[0], n_layers)
            return out

        def _block_meta(block: _Block, model_sha: str) -> dict:
            return {
                "model_sha256": model_sha,
                "base_model_repo": base_repo,
                "prompt_sha256": prompt_shas[block.context],
                "n_prompts": len(prompts[block.context]),
                "context": block.context,
                "position": block.position,
                "skip_first_token": block.skip_first_token,
                "dtype": "float32",
                "tf32": False,
            }

        def _key(block: _Block, model_sha: str) -> str:
            return cache_key(
                prompt_shas[block.context], model_sha, base_repo, block.position,
                DTYPE_TAG, skip_first_token=block.skip_first_token,
            )

        logger.info(
            "GKD-EAS base {} | {} leaves, {} teachers, blocks {}",
            base_repo, len(base_leaves), len(teachers), [b.name for b in blocks],
        )
        mean_base: dict[str, torch.Tensor] = {}
        for block in blocks:
            path = cache_dir / f"mean_base_{_key(block, 'base')}.pt"
            meta = _block_meta(block, "base")
            cached = _load_cached(path, meta)
            if cached is None:
                cached = {"mean": _mean(base, block)}
                save_vector(path, cached, meta)
            mean_base[block.name] = cached["mean"]

        v_teacher: dict[str, dict[str, dict]] = {b.name: {} for b in blocks}
        for t in teachers:
            todo: list[tuple[_Block, Path, dict]] = []
            for block in blocks:
                path = cache_dir / _teacher_file(t, block, _key(block, t.sha256))
                meta = {**_block_meta(block, t.sha256), **t.ref()}
                cached = _load_cached(path, meta)
                if cached is None:
                    todo.append((block, path, meta))
                else:
                    v_teacher[block.name][t.name] = cached
            if not todo:
                continue
            attached = PeftModel.from_pretrained(base, str(t.ckpt))
            attached.eval()
            for block, path, meta in todo:
                vec = diff_vector(_mean(attached, block), mean_base[block.name])
                save_vector(path, vec, meta)
                v_teacher[block.name][t.name] = vec
            base = attached.unload()
            if on_cuda:
                torch.cuda.empty_cache()

        for rd, ident in sorted(base_leaves.items()):
            null_animal = next(
                a for a in teachers_by_base[base_repo] if a != ident.target_animal
            )
            student_sha = file_sha256(rd / "checkpoints" / _ADAPTER_FILE)
            meta = _leaf_meta(
                run_dir=rd, ident=ident, null_animal=null_animal, n_layers=n_layers,
                student_sha=student_sha, spec=spec, n_prompts=n_prompts,
                prompt_shas=prompt_shas, blocks=blocks, teachers=teachers, cfg=cfg,
            )
            if not cfg.force and _leaf_is_current(rd, meta, blocks):
                logger.info("  up to date, skipping {}", rd)
                skipped.append(str(rd))
                continue
            student = PeftModel.from_pretrained(base, str(rd / "checkpoints"))
            student.eval()
            per_context: dict[str, dict] = {}
            eas_dir = rd / "eas"
            for block in blocks:
                v_student = diff_vector(_mean(student, block), mean_base[block.name])
                vt = v_teacher[block.name]
                cos_by_teacher = {
                    name: direction_cosine(v_student["raw"], v["raw"])
                    for name, v in vt.items()
                }
                cos_unit_mean = {
                    animal: direction_cosine(
                        v_student["raw"],
                        unit_mean_vector([vt[t.name]["raw"] for t in ts]),
                    )
                    for animal, ts in teachers_by_base[base_repo].items()
                }
                per_context[block.name] = build_gkd_entry(
                    context=block.context,
                    position=block.position,
                    skip_first_token=block.skip_first_token,
                    n_prompts=len(prompts[block.context]),
                    trait_animal=ident.target_animal,
                    null_animal=null_animal,
                    cos_by_teacher=cos_by_teacher,
                    cos_unit_mean=cos_unit_mean,
                    v_student_norm=v_student["norm"],
                    random_floor=random_direction_floor(
                        v_student["raw"], cfg.random_floor_seed
                    ),
                )
                save_vector(
                    eas_dir / f"v_student_{block.context}_{block.position}.pt",
                    v_student,
                    {**_block_meta(block, student_sha), "run_dir": str(rd)},
                )
            atomic_write_json(
                eas_dir / "gkd_eas.json", {"meta": meta, "per_context": per_context}
            )
            base = student.unload()
            if on_cuda:
                torch.cuda.empty_cache()
            computed.append(str(rd))
            for name, entry in per_context.items():
                logger.info(
                    "  {} {} -> eas {}={:+.4f} {}={:+.4f} delta={:+.4f}",
                    rd.name, name, ident.target_animal,
                    entry[f"eas_mean_{ident.target_animal}"], null_animal,
                    entry[f"eas_mean_{null_animal}"], entry["delta_eas"],
                )
        del base
        if on_cuda:
            torch.cuda.empty_cache()

    logger.info("GKD-EAS done: {} computed, {} skipped", len(computed), len(skipped))
    return {"n_leaves": len(leaves), "computed": computed, "skipped": skipped}


def _teacher_file(t: _Teacher, block: _Block, key: str) -> str:
    return (
        f"v_teacher_{t.animal}-ftseed{t.ftseed}_{block.context}_{block.position}_{key}.pt"
    )
