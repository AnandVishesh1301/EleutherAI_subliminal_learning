"""Stage the `newdom2` inputs: paths YAML, jobq policy, the B corpora (`panelfree-v1`)
with manifests and review samples, the `strict_sub` screen preview sample, and a
staging report. Create-only (an existing file must match exactly); no GPU.

    paths      `newdom2_plan.PATHS_CONFIG_PATH` from `newdom2_plan.paths_config_doc`
    policy     `gpu_policy.<home node>.json` in the Part II queue root
    panelfree  per B target: the Part I corpus (its approved review's sha) minus every
               document naming another panel member -> corpus + manifest + sample
    screen     the substring rule applied offline to Part I pine lr-4e-4 rollouts kept
               by `strict` -> counts + seeded sample of newly flagged rows
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

import yaml
from loguru import logger

from pipelines.newdom_soft_staging_pipeline import json_text, jsonl_text, read_jsonl
from pipelines.traitfree_staging_pipeline import write_once_text
from subliminal_learning.campaign import newdom2 as n2
from subliminal_learning.campaign import newdom2_plan as plan2
from subliminal_learning.campaign import newdom_plan as plan
from subliminal_learning.campaign import newdom_soft as soft
from subliminal_learning.evaluation.animal_forms_io import load_animal_forms
from subliminal_learning.evaluation.domains import domain_files
from subliminal_learning.gkd.filtering import (
    load_strict_screen_lexicon,
    load_trait_lexicon,
    strict_screen_vocab,
)
from subliminal_learning.utils.io import atomic_write_json, file_sha256
from subliminal_learning.utils.run_io import utc_now_iso

STEPS: tuple[str, ...] = ("paths", "policy", "panelfree", "screen")
ROLLOUTS_FILE = "rollouts_sample.jsonl"


def paths_yaml_text() -> str:
    """The Part II paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_newdom2_assets.py from "
        "newdom2_plan.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(plan2.paths_config_doc(), sort_keys=True)


def policy_path() -> Path:
    return plan2.QUEUE_ROOT / f"gpu_policy.{plan2.HOME_NODE}.json"


def write_paths() -> str:
    write_once_text(plan2.PATHS_CONFIG_PATH, paths_yaml_text())
    return file_sha256(plan2.PATHS_CONFIG_PATH)


def write_policy() -> str:
    """Create (or match) the home node's policy file.

    Raises:
        FileExistsError: The file holds a different policy.
    """
    path = policy_path()
    if path.is_file():
        if json.loads(path.read_text()) != plan2.gpu_policy_json():
            raise FileExistsError(f"{path} exists with a different policy")
    else:
        atomic_write_json(path, plan2.gpu_policy_json())
    return str(path)


# ---- B corpora ------------------------------------------------------------------------


def domain_forms(domain: str) -> dict[str, tuple[str, ...]]:
    return {
        k: tuple(v) for k, v in load_animal_forms(domain_files(domain).forms).items()
    }


def part1_corpus_sha(target: str) -> str:
    """sha of the Part I corpus, which must equal its approved review's.

    Raises:
        ValueError: The review is missing, unapproved, or names another corpus.
    """
    corpus = plan.corpus_path(target)
    review = json.loads(plan.corpus_review_path(target).read_text())
    sha = file_sha256(corpus)
    if review.get("approved") is not True or review.get("corpus_sha256") != sha:
        raise ValueError(f"{corpus}: Part I review not approved for sha {sha[:12]}")
    return sha


def build_panelfree(target: str) -> dict:
    """Write (or match) the B corpus, its manifest and its review sample.

    Raises:
        ValueError: The Part I corpus is unreviewed, or a row names another target.
        FileExistsError: An existing output differs.
    """
    source = plan.corpus_path(target)
    source_sha = part1_corpus_sha(target)
    rows = read_jsonl(source)
    if {r.get("animal") for r in rows} != {target}:
        raise ValueError(f"{source} rows name another target")
    forms = domain_forms(plan.TARGET_DOMAIN[target])
    terms = n2.panelfree_terms(target, forms)
    kept, dropped = n2.panelfree_split(rows, terms)
    out = plan2.variant_corpus_path(target, plan2.B_CORPUS)
    out.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(out, jsonl_text(kept))
    sha = file_sha256(out)
    manifest = {
        "target": target,
        "corpus": plan2.B_CORPUS,
        "rule": "drop iff NFKC-lower text names another panel member's surface form "
        "at ASCII-letter boundaries (newdom2.panelfree_split)",
        "panel_others": list(n2.panelfree_members(target)),
        "terms": list(terms),
        "source_path": str(source),
        "source_sha256": source_sha,
        "source_review_sha256": file_sha256(plan.corpus_review_path(target)),
        "n_source": len(rows),
        "n_kept": len(kept),
        "n_dropped": len(dropped),
        "docs_sha256": sha,
        "stats": n2.panelfree_stats(rows, kept, dropped, target, forms),
    }
    write_once_text(
        plan2.variant_manifest_path(target, plan2.B_CORPUS), json_text(manifest)
    )
    sample = n2.corpus_sample_doc(
        target,
        {"path": source, "sha256": source_sha},
        {"path": out, "sha256": sha},
        kept,
        dropped,
    )
    sample_path = plan2.corpus_sample_path(target)
    sample_path.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(sample_path, json_text(sample))
    return manifest


# ---- strict_sub screen preview --------------------------------------------------------


def screen_vocab(target: str, screen: str = plan2.SCREEN_SUB):
    """The target's strict vocabulary under `screen` (`strict` / `strict_sub`)."""
    files = domain_files(plan.TARGET_DOMAIN[target])
    return strict_screen_vocab(
        target,
        load_animal_forms(files.forms),
        load_trait_lexicon(files.trait_lexicon),
        load_strict_screen_lexicon(files.strict_screen),
        substring=screen == plan2.SCREEN_SUB,
    )


def sub_vocab(target: str):
    """The target's `strict_sub` vocabulary."""
    return screen_vocab(target, plan2.SCREEN_SUB)


def build_screen_preview(target: str) -> dict:
    """Counts and seeded sample of the rows the substring rule adds to `strict` on
    Part I's lr-4e-4 rollouts of `target`.

    Raises:
        ValueError: A Part I leaf has no rollout log.
    """
    vocab = sub_vocab(target)
    counts: dict[str, dict[str, int]] = {}
    hits: dict[str, list[dict]] = {}
    for kind in soft.KINDS:
        c = {"leaves": 0, "rows": 0, "kept_strict": 0, "substring_hits": 0}
        rows_hit: list[dict] = []
        for leaf in n2.part1_leaves(target, kind):
            path = soft.leaf_dir(leaf) / ROLLOUTS_FILE
            if not path.is_file():
                raise ValueError(f"{leaf.key}: no {path}")
            c["leaves"] += 1
            for rec in read_jsonl(path):
                if not rec.get("on_policy", True):
                    continue
                c["rows"] += 1
                if rec.get("flagged"):
                    continue
                c["kept_strict"] += 1
                word = n2.substring_word(str(rec["completion"]), vocab.substring_forms)
                if word is not None:
                    c["substring_hits"] += 1
                    rows_hit.append(
                        {
                            "key": leaf.key,
                            "step": rec.get("step"),
                            "word": word,
                            "completion": rec["completion"],
                        }
                    )
        counts[kind], hits[kind] = c, rows_hit
    doc = n2.screen_sample_doc(target, vocab.sha256(), counts, hits)
    path = plan2.screen_sample_path(target)
    path.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(path, json_text(doc))
    return {"vocab_sha256": vocab.sha256(), "counts": counts}


# ---- report ---------------------------------------------------------------------------


def report() -> dict:
    """Every staging check, re-read from disk."""
    paths_ok = (
        plan2.PATHS_CONFIG_PATH.is_file()
        and plan2.PATHS_CONFIG_PATH.read_text() == paths_yaml_text()
    )
    policy_ok = (
        policy_path().is_file()
        and json.loads(policy_path().read_text()) == plan2.gpu_policy_json()
    )
    corpora: dict[str, dict] = {}
    for target in plan2.ARMS[plan2.ARM_B]:
        out = plan2.variant_corpus_path(target, plan2.B_CORPUS)
        man_path = plan2.variant_manifest_path(target, plan2.B_CORPUS)
        problems = []
        if not (out.is_file() and man_path.is_file()):
            corpora[target] = {"problems": ["corpus or manifest missing"]}
            continue
        man = json.loads(man_path.read_text())
        if file_sha256(out) != man["docs_sha256"]:
            problems.append("corpus differs from its manifest")
        if file_sha256(plan.corpus_path(target)) != man["source_sha256"]:
            problems.append("Part I corpus changed")
        if not plan2.corpus_sample_path(target).is_file():
            problems.append("review sample missing")
        corpora[target] = {
            "problems": problems,
            "n_kept": man["n_kept"],
            "n_dropped": man["n_dropped"],
            "docs_sha256": man["docs_sha256"],
        }
    screens: dict[str, dict] = {}
    for target in plan2.SUB_TARGETS:
        path = plan2.screen_sample_path(target)
        problems = []
        if not path.is_file():
            problems.append("screen sample missing")
        elif json.loads(path.read_text())["vocab_sha256"] != sub_vocab(target).sha256():
            problems.append("screen sample names another vocabulary")
        screens[target] = {"problems": problems}
    complete = (
        paths_ok
        and policy_ok
        and not any(c["problems"] for c in corpora.values())
        and not any(s["problems"] for s in screens.values())
    )
    return {
        "at": utc_now_iso(),
        "complete": complete,
        "paths_yaml": paths_ok,
        "policy": policy_ok,
        "corpora": corpora,
        "screens": screens,
    }


def latest_complete_report_path() -> Path | None:
    """Newest complete Part II staging report file, or None."""
    if not plan2.STAGING_DIR.is_dir():
        return None
    for path in sorted(plan2.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        if json.loads(path.read_text()).get("complete"):
            return path
    return None


def latest_complete_report() -> dict | None:
    """Newest complete Part II staging report, or None."""
    path = latest_complete_report_path()
    return json.loads(path.read_text()) if path else None


def run(steps: Sequence[str] = STEPS, *, dry_run: bool = False) -> dict:
    """Run the named steps in `STEPS` order, then write the staging report.

    Returns:
        The report (not written on a dry run).

    Raises:
        ValueError: An unknown step.
    """
    if bad := sorted(set(steps) - set(STEPS)):
        raise ValueError(f"unknown staging steps {bad}; choose from {STEPS}")
    if dry_run:
        doc = report()
        logger.info("[dry-run] staging report: {}", json.dumps(doc, indent=1))
        return doc
    if "paths" in steps:
        plan2.PATHS_CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
        write_paths()
    if "policy" in steps:
        plan2.QUEUE_ROOT.mkdir(parents=True, exist_ok=True)
        write_policy()
    if "panelfree" in steps:
        for target in plan2.ARMS[plan2.ARM_B]:
            logger.info("panelfree {}: {}", target, build_panelfree(target))
    if "screen" in steps:
        for target in plan2.SUB_TARGETS:
            logger.info("screen preview {}: {}", target, build_screen_preview(target))
    doc = report()
    path = plan2.STAGING_DIR / f"staging_report-{doc['at'].replace(':', '')}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(path, json_text(doc))
    logger.info("staging report {} (complete={})", path, doc["complete"])
    return doc
