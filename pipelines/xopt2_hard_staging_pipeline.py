"""Verify the `xopt2` hard channel's reused `xopt` inputs; write its paths YAML once.

Nothing is copied, converted or measured: the pools, staged bases, HF cache, CE_base and
pp1 text are `xopt`'s and are only read. A pass checks every pool a cell may read (QC
at 200k prompts), CE_base of every student token, the staged snapshot of every teacher
and student token (from `xopt`'s staging report, then on disk) and the pp1 text hash,
and records each pool's filtered sha256 (a cell refuses a pool that drifted since); a
full run then creates the channel's own control dirs (ssd-2) and leaf root (cold-1),
writes the paths YAML (create-or-equal) and a staging report with the sha256 of
`ce_base.json` and the pp1 text. Runs on soar, no GPU.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import yaml
from loguru import logger

from pipelines import xopt_hard_cell_pipeline as xcell
from pipelines import xopt_hard_staging_pipeline as xstaging
from pipelines.traitfree_staging_pipeline import write_once_text
from subliminal_learning.campaign import xopt2_hard as hard
from subliminal_learning.campaign import xopt_hard as xh
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.utils.io import atomic_write_json, file_sha256
from subliminal_learning.utils.run_io import utc_now_iso

REPORT_PREFIX = "staging_report-"


def paths_yaml_text() -> str:
    """The hard channel's paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_xopt2_hard_assets.py from "
        "xopt2_hard.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(hard.paths_config_doc(), sort_keys=True)


def pool_key(source: str, teacher: str, animal: str | None) -> str:
    """Staging-report key of one pool (teacher token, animal or `ctrl`)."""
    return f"{source}|{animal or 'ctrl'}|{teacher}"


def staged_pool_sha(cell: hard.Cell) -> str:
    """sha256 of the cell's filtered pool recorded by the latest staging report.

    Raises:
        RuntimeError: No complete staging report, or it lacks the pool.
    """
    report = latest_complete_report() or {}
    key = pool_key(cell.source, cell.teacher, cell.animal)
    sha = ((report.get("pools") or {}).get(key) or {}).get("filtered_sha256")
    if not sha:
        raise RuntimeError(f"staging report has no filtered_sha256 for pool {key}")
    return str(sha)


def pool_drift(report: dict, pools: dict) -> list[str]:
    """Pools whose current filtered sha differs from the staged one."""
    staged = report.get("pools") or {}
    return [
        f"pool {k} drifted from staging ({(staged.get(k) or {}).get('filtered_sha256')}"
        f" -> {v['filtered_sha256']})"
        for k, v in pools.items()
        if (staged.get(k) or {}).get("filtered_sha256") != v["filtered_sha256"]
    ]


def _base_files(entry: dict) -> tuple[Path, dict]:
    """(snapshot dir, files) of one `xopt` staging-report base entry."""
    if "repo_id" in entry:
        repo = xh.HF_ROOT / "hub" / f"models--{entry['repo_id'].replace('/', '--')}"
        return repo / "snapshots" / entry["commit"], entry["files"]
    root = xh.BASE_MODELS_ROOT / "hf_converted" / entry["base"] / entry["revision"]
    return root, entry["files"]


def check_inputs() -> tuple[list[str], dict]:
    """Problems with the reused `xopt` inputs, and what was read.

    Returns:
        `(problems, readings)`; no problems means every cell's inputs are ready.
    """
    problems: list[str] = []
    pools = {}
    for source, base, step, animal in hard.pools():
        qc = xcell.pool_status(source, base, step, animal, hard.N_PROMPTS)
        key = pool_key(source, xh.token(base, step), animal)
        filtered = xh.filtered_dir(xh.pool_dir(source, base, step, animal))
        pools[key] = {
            "ready": qc.ready,
            "n_filtered": qc.n_filtered,
            "filtered_sha256": json.loads((filtered / "manifest.json").read_text())[
                "filtered_sha256"
            ]
            if qc.ready
            else None,
        }
        if not qc.ready:
            problems.append(f"pool {key} not ready: {list(qc.reasons)}")
    ce = json.loads(xh.CE_BASE_PATH.read_text()) if xh.CE_BASE_PATH.is_file() else {}
    problems += [f"no CE_base of {t}" for t in hard.student_tokens() if t not in ce]
    report = xstaging.latest_complete_report() or {}
    bases = {}
    for tok in sorted({*hard.teacher_tokens(), *hard.student_tokens()}):
        entry = (report.get("bases") or {}).get(tok)
        if entry is None:
            problems.append(f"{tok} is not in xopt's staging report")
            continue
        snap, files = _base_files(entry)
        missing = [f for f in files if not (snap / f).exists()]
        if missing:
            problems.append(f"{tok}: {snap} lacks {missing}")
        bases[tok] = str(snap)
    if not xh.PP1_TEXT_PATH.is_file():
        problems.append(f"missing {xh.PP1_TEXT_PATH}")
    else:
        texts = [
            json.loads(line)["text"]
            for line in xh.PP1_TEXT_PATH.read_text().splitlines()
            if line.strip()
        ]
        if pp.text_sha256(texts) != pp.PP1_TEXT_SHA256:
            problems.append(f"{xh.PP1_TEXT_PATH}: text sha != {pp.PP1_TEXT_SHA256}")
    readings = {
        "pools": pools,
        "ce_base": {t: ce.get(t) for t in hard.student_tokens()},
        "bases": bases,
        "xopt_staging_report_at": report.get("at"),
    }
    return problems, readings


def run(*, dry_run: bool = False) -> dict:
    """Check the inputs, then (unless `dry_run`) create dirs, YAML and a report.

    Returns:
        The staging report (or the dry-run readings).

    Raises:
        RuntimeError: Some reused input is missing or not ready.
    """
    problems, readings = check_inputs()
    if dry_run:
        logger.info("[dry-run] {} problem(s): {}", len(problems), problems)
        return {"dry_run": True, "problems": problems, **readings}
    if problems:
        raise RuntimeError("; ".join(problems))
    doc = hard.paths_config_doc()
    for key in ("output_root", "dataset_cache_root", "wandb_dir"):
        Path(doc[key]).mkdir(parents=True, exist_ok=True)
    for path in (Path(doc["queue_root"]) / "logs", hard.LEAF_ROOT, hard.STAGING_DIR):
        path.mkdir(parents=True, exist_ok=True)
    write_once_text(hard.PATHS_CONFIG_PATH, paths_yaml_text())
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": doc,
        **readings,
        "ce_base_sha256": file_sha256(xh.CE_BASE_PATH),
        "pp1_text_sha256": file_sha256(xh.PP1_TEXT_PATH),
        "complete": True,
    }
    out = hard.STAGING_DIR / f"{REPORT_PREFIX}{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info("staging complete: {}", out)
    return report


def latest_complete_report() -> dict | None:
    """Newest complete staging report, or ``None``."""
    if not hard.STAGING_DIR.is_dir():
        return None
    for path in sorted(hard.STAGING_DIR.glob(f"{REPORT_PREFIX}*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None
