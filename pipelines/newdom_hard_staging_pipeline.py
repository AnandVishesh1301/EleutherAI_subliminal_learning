"""Stage the `newdom` hard channel's inputs under the campaign root (create-only).

Copies hlopt's staged trait-free base pool (the shared control pool; sha, row count and
`base_model_repo` checked against `newdom_plan.HARD_CONTROL_POOL`) and the frozen pp1
text, copies each domain's 50 train prompts (the teachers' templates, so a teacher's
identity never names a code-pin path), scans the control pool with both domain word
screens (zero hits required), writes the hard paths YAML (create, or equal content),
and checks offline in a subprocess that the base tokenizer resolves, the pp1 text
tokenizes to its pin and every target and panel item is one token. Writes a staging
report. Runs on soar, no GPU; source trees are only read.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import yaml
from loguru import logger

from pipelines.newdom_hard_cell_pipeline import FILTERED_FILE, scan_pool, vocab_sha
from pipelines.traitfree_staging_pipeline import copy_file, write_once_text
from subliminal_learning.campaign import hlopt_plan
from subliminal_learning.campaign import newdom_hard as hard
from subliminal_learning.campaign import newdom_plan as plan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.utils.io import atomic_write_json, file_sha256
from subliminal_learning.utils.run_io import utc_now_iso

REPORT_PREFIX = "staging_report-"


def paths_yaml_text() -> str:
    """The hard channel's paths YAML as this pipeline writes it."""
    header = (
        "# Generated by scripts/stage_newdom_hard_assets.py from "
        "newdom_plan.paths_config_doc('hard').\n"
    )
    return header + yaml.safe_dump(plan.paths_config_doc(plan.HARD), sort_keys=True)


def paths_yaml_problem() -> str | None:
    """Why the hard paths YAML is unusable (missing or other roots), or None."""
    path = hard.PATHS_CONFIG_PATH
    if not path.is_file():
        return f"{path} missing"
    if yaml.safe_load(path.read_text()) != plan.paths_config_doc(plan.HARD):
        return f"{path} differs from newdom_plan.paths_config_doc('hard')"
    return None


def write_paths_yaml() -> None:
    """Create the paths YAML, or accept one (from any stager) with the plan's roots.

    Raises:
        FileExistsError: The YAML exists with other roots.
    """
    if hard.PATHS_CONFIG_PATH.is_file():
        problem = paths_yaml_problem()
        if problem:
            raise FileExistsError(problem)
        return
    write_once_text(hard.PATHS_CONFIG_PATH, paths_yaml_text())


def _stage_control_pool(put) -> dict:
    """Copy the control pool and check its pinned sha, row count and base model.

    Raises:
        RuntimeError: The copy differs from the pin.
    """
    pool = plan.HARD_CONTROL_POOL
    shas = {
        name: put(pool.staged_dir / name, hard.CONTROL_POOL_DIR / name)
        for name in hlopt_plan.POOL_FILES
    }
    if shas[FILTERED_FILE] != pool.filtered_sha256:
        raise RuntimeError(f"control pool sha {shas[FILTERED_FILE]} != pin")
    with (hard.CONTROL_POOL_DIR / FILTERED_FILE).open() as f:
        n_rows = sum(1 for line in f if line.strip())
    manifest = json.loads((hard.CONTROL_POOL_DIR / "manifest.json").read_text())
    if n_rows != pool.n_rows or manifest.get("base_model_repo") != hard.BASE_REPO:
        raise RuntimeError(
            f"control pool: {n_rows} rows, base {manifest.get('base_model_repo')}"
        )
    if manifest.get("filtered_sha256") != pool.filtered_sha256:
        raise RuntimeError("control pool manifest records another filtered sha")
    return {"dir": str(hard.CONTROL_POOL_DIR), "sha256": shas, "n_rows": n_rows}


def _stage_pp1(put) -> str:
    """Copy hlopt's staged pp1 text; return its text sha.

    Raises:
        RuntimeError: The text does not match the pinned hash.
    """
    put(hlopt_plan.PP1_TEXT_PATH, hard.PP1_TEXT_PATH)
    texts = [
        json.loads(line)["text"]
        for line in hard.PP1_TEXT_PATH.read_text().splitlines()
        if line.strip()
    ]
    sha = pp.text_sha256(texts)
    if sha != pp.PP1_TEXT_SHA256:
        raise RuntimeError(f"pp1 text sha {sha} != {pp.PP1_TEXT_SHA256}")
    return sha


def template_shas(repo_root: Path) -> dict[str, str]:
    """Domain -> sha256 of its train-prompt file in `repo_root`."""
    out = {}
    for d in plan.DOMAINS.values():
        out[d.name] = file_sha256(repo_root / hard.template_source(d.targets[0]))
    return out


def _stage_templates(repo_root: Path, put) -> dict[str, str]:
    """Copy each domain's 50 train prompts (50 unique strings) to the inputs dir.

    Raises:
        RuntimeError: A file is not 50 unique prompts.
    """
    out = {}
    for d in plan.DOMAINS.values():
        target = d.targets[0]
        src = repo_root / hard.template_source(target)
        prompts = json.loads(src.read_text())
        if len(prompts) != 50 or len(set(prompts)) != 50:
            raise RuntimeError(f"{src}: {len(prompts)} prompts, want 50 unique")
        out[d.name] = put(src, hard.template_path(target))
    return out


_VERIFY_SCRIPT = """
import json, sys
from subliminal_learning.campaign import newdom_hard as hard
from subliminal_learning.campaign import newdom_plan as plan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.evaluation.preference_prob_io import target_token_id
from subliminal_learning.models.loading_io import load_tokenizer

tok = load_tokenizer(hard.spec(), plan.HF_CACHE_ROOT, hard.HUB_ORG)
items = sorted({*plan.TARGETS, *(c for d in plan.DOMAINS.values() for c in d.panel)})
out = {
    "vocab": len(tok),
    "pp1_n_docs": len(pp.load_pp1_input_ids(hard.PP1_TEXT_PATH, tok)),
    "token_ids": {c: target_token_id(c, tok) for c in items},
}
print(json.dumps(out))
"""


def verify_offline() -> dict:
    """Resolve the base tokenizer offline; check pp1 and single-token targets and panels.

    Raises:
        RuntimeError: The check subprocess failed.
    """
    env = dict(os.environ)
    env.update(plan.gpu_policy_json()["env"])
    proc = subprocess.run(
        [sys.executable, "-c", _VERIFY_SCRIPT],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"offline verification failed:\n{proc.stderr[-4000:]}")
    return json.loads(proc.stdout.strip().splitlines()[-1])


def run(repo_root: Path, *, dry_run: bool = False) -> dict:
    """Stage everything, scan the control pool and write a staging report.

    Returns:
        The staging report.

    Raises:
        RuntimeError: The control pool hits a domain screen, or a copy or check fails.
    """
    if dry_run:
        logger.info(
            "[dry-run] would stage the control pool {} -> {}, pp1, templates {}",
            plan.HARD_CONTROL_POOL.staged_dir,
            hard.CONTROL_POOL_DIR,
            [str(hard.template_path(d.targets[0])) for d in plan.DOMAINS.values()],
        )
        return {"dry_run": True}
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    for path in (hard.OUTPUT_ROOT, hard.INPUTS_DIR, hard.STAGING_DIR, plan.CONFIG_DIR):
        path.mkdir(parents=True, exist_ok=True)
    write_paths_yaml()
    control = _stage_control_pool(put)
    scan = scan_pool(hard.CONTROL_POOL_DIR, tuple(plan.DOMAINS))
    hits = {d: v["n_hits"] for d, v in scan["domains"].items()}
    if any(hits.values()):
        raise RuntimeError(f"control pool hits the domain screens: {scan['domains']}")
    control["screen"] = scan
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": plan.paths_config_doc(plan.HARD),
        "control_pool": control,
        "pp1_text_sha256": _stage_pp1(put),
        "templates": _stage_templates(repo_root, put),
        "verified_offline": verify_offline(),
        "complete": True,
        **totals,
    }
    out = hard.STAGING_DIR / f"{REPORT_PREFIX}{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info(
        "staging complete: {} ({} files, {} bytes written)",
        out,
        totals["n_files"],
        totals["bytes_written"],
    )
    return report


def latest_complete_report() -> dict | None:
    """Newest complete staging report, or ``None``."""
    if not hard.STAGING_DIR.is_dir():
        return None
    for path in sorted(hard.STAGING_DIR.glob(f"{REPORT_PREFIX}*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None


def check_inputs(repo_root: Path, report: dict) -> list[str]:
    """Problems with the staged inputs against `report` and the repo's prompt files."""
    problems = []
    pool = plan.HARD_CONTROL_POOL
    path = hard.CONTROL_POOL_DIR / FILTERED_FILE
    if not path.is_file() or file_sha256(path) != pool.filtered_sha256:
        problems.append(f"{path} missing or differs from the control-pool pin")
    screen = (report.get("control_pool") or {}).get("screen") or {}
    domains = screen.get("domains") or {}
    hits = {d: v.get("n_hits") for d, v in domains.items()}
    if set(hits) != set(plan.DOMAINS) or any(hits.values()):
        problems.append(
            f"control pool screen record {hits} is not clean for both domains"
        )
    stale = [d for d, v in domains.items() if v.get("vocab_sha256") != vocab_sha(d)]
    if stale:
        problems.append(f"control pool screened with an older vocabulary of {stale}")
    if not hard.PP1_TEXT_PATH.is_file():
        problems.append(f"{hard.PP1_TEXT_PATH} missing")
    staged = report.get("templates") or {}
    repo = template_shas(repo_root)
    for d in plan.DOMAINS.values():
        dest = hard.template_path(d.targets[0])
        if not dest.is_file() or file_sha256(dest) != staged.get(d.name):
            problems.append(f"{dest} missing or differs from the staging report")
        elif staged.get(d.name) != repo[d.name]:
            problems.append(
                f"{hard.template_source(d.targets[0])} changed since staging"
            )
    return problems
