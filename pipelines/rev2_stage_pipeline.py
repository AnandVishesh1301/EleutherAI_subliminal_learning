_START_FILES: tuple[str, ...] = (
    "train_manifest.json",
    "training_metrics.jsonl",
    "trainer_log_history.jsonl",
    "rollouts_summary.json",
)
_POOL_FILES: tuple[str, ...] = ("prompts.jsonl", "heldout_ppl.jsonl", "manifest.json")
_REV2_REGISTER_SHARES = {
    "Pile-CC": 0.35,
    "Wikipedia (en)": 0.20,
    "PubMed Abstracts": 0.15,
    "StackExchange": 0.15,
    "HackerNews": 0.15,
}


def paths_yaml_text() -> str:
    header = "# Generated by pipelines/rev2_stage_pipeline.py from rev2_plan.paths_config_doc().\n"
    return header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def nested_rank(rows: list[dict], seed: int) -> list[dict]:
    """`rows` ordered by sha256(``seed:prompt\\0completion``); prefixes nest across sizes."""
    def key(r: dict) -> str:
        return hashlib.sha256(f"{seed}:{r['prompt']}\0{r['completion']}".encode()).hexdigest()

    return sorted(rows, key=key)


def _write_rows(dest: Path, rows: list[dict], manifest: dict) -> dict:
    write_once_text(dest / "filtered.jsonl", "".join(json.dumps(r) + "\n" for r in rows))
    write_once_text(dest / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    return {"dir": str(dest), "n_rows": len(rows),
            "filtered_sha256": sha256_file(dest / "filtered.jsonl")}


def _stage_dose_rows() -> dict:
    """Nested subsets of the rank-1 reversal rows (one dir per rung and draw)."""
    src = rev1.REV_NUMBERS_DIR
    rows = load_filtered_rows(src / "filtered.jsonl")
    if len(rows) != rev1.REV_ROWS:
        raise RuntimeError(f"{src} has {len(rows)} rows, expected {rev1.REV_ROWS}")
    source_manifest = json.loads((src / "manifest.json").read_text())
    out = {}
    for name in plan.hard_carriers():
        if not name.startswith("dose_"):
            continue
        n, d = (int(x[1:]) for x in name.removeprefix("dose_").split("_"))
        chosen = nested_rank(rows, d)[:n]
        manifest = {**source_manifest, "rev2_nested": {
            "source_dir": str(src), "source_filtered_sha256": sha256_file(src / "filtered.jsonl"),
            "rule": "sha256(f'{seed}:{prompt}\\0{completion}') ascending, first n",
            "seed": d, "n": n}}
        out[name] = _write_rows(plan.numbers_dir(name), chosen, manifest)
    return out


def _pool_src(name: str) -> Path:
    if name == "rng":
        return plan.RNG_POOL_SRC
    if name.startswith("trait_"):
        return plan.trait_pool_src(name.removeprefix("trait_"))
    if name.startswith("xb_"):
        return plan.xb_pool_src(name.removeprefix("xb_"), plan.XBASE_STEP)
    if name.startswith("ck_"):
        return plan.xb_pool_src("pythia-160m", int(name.removeprefix("ck_")))
    raise ValueError(name)


def _stage_pools(put) -> dict:  # noqa: ANN001
    """Copies of every non-derived hard row set (filtered rows + manifest)."""
    out = {}
    for name in plan.hard_carriers():
        if name in ("base_rev1", "pile") or name.startswith("dose_"):
            continue
        src = _pool_src(name)
        dest = plan.numbers_dir(name)
        sha = put(src / "filtered.jsonl", dest / "filtered.jsonl")
        put(src / "manifest.json", dest / "manifest.json")
        n = sum(1 for line in (dest / "filtered.jsonl").read_text().splitlines() if line)
        need = plan.RELEARN_ROWS if name.startswith("trait_") else plan.HARD_ROWS
        if n < need:
            raise RuntimeError(f"{src}: {n} rows < {need}")
        out[name] = {"source": str(src), "dir": str(dest), "n_rows": n,
                     "filtered_sha256": sha}
    return out


def _stage_teachers(put) -> dict:  # noqa: ANN001
    staged = {}
    pairs = [(plan.trait_teacher_src(a, t), plan.trait_teacher_dir(a, t))
             for a in plan.SOFT_ANIMALS for t in range(3)]
    pairs += [(plan.VALNEG_SRC / plan.VALNEG_TAG / f"ftseed{t}", plan.valneg_teacher_dir(t))
              for t in range(3)]
    for src, dest in pairs:
        files = _stage_files(src, dest, ("train_manifest.json",), put)
        if not any(f.endswith(".safetensors") for f in files):
            raise FileNotFoundError(f"{src}: no teacher weights")
        staged[str(dest)] = {"source": str(src), "files": files,
                             "manifest_sha256": sha256_file(dest / "train_manifest.json")}
    return staged


def _stage_bases(put) -> dict:  # noqa: ANN001
    """Local NeoX conversions (R4X, R5) + Hub revisions merged into the reversal cache."""
    out = {"local": {}, "hub": []}
    for base in plan.LOCAL_BASES:
        rel = Path("hf_converted") / base / f"step{plan.XBASE_STEP}"
        n = stage_tree(plan.XOPT_SOFT_BASES / rel, plan.BASES_ROOT / rel, put)
        out["local"][base] = {"source": str(plan.XOPT_SOFT_BASES / rel), "n_files": n}
    revisions = [(repo, f"step{plan.XBASE_STEP}") for repo in plan.HUB_PARTNERS.values()]
    revisions += [(plan.HUB_PARTNERS["pythia-160m"], f"step{s}") for s in plan.R5_SOFT_CKPTS]
    caches = (plan.XOPT_SOFT_HUB, *rev1.SOURCE_HUB_CACHES)
    for repo, rev in revisions:
        out["hub"].append(stage_hub_revision(find_hub_sources(caches, repo, rev),
                                             plan.HF_ROOT / "hub", repo, rev, put))
    return out


def _stage_xstarts(put) -> dict:  # noqa: ANN001
    staged = {}
    for base in plan.R4X_BASES:
        for kind in (plan.TREAT, plan.CTRL):
            for t, g in plan.R4X_LEAVES:
                src = plan.xstart_src(base, kind, t, g)
                dest = plan.xstart_dir(base, kind, t, g)
                files = _stage_files(src, dest, _START_FILES, put)
                if not any(f.endswith(".safetensors") for f in files):
                    raise FileNotFoundError(f"{src}: no weights")
                staged[str(dest)] = {"source": str(src), "files": files}
    return staged


def _stage_v1_pool(put) -> dict:  # noqa: ANN001
    return {name: put(plan.POOL_V1_SRC / name, plan.POOL_V1 / name) for name in _POOL_FILES}


def check_rev2_pool() -> dict:
    """The 80,000 pool: counts, screen lexicons, held-out copy, zero overlap with v1 / rev1.

    Raises:
        RuntimeError: Any check fails.
    """
    manifest = json.loads((plan.POOL_REV2 / "manifest.json").read_text())
    v1 = json.loads((plan.POOL_V1_SRC / "manifest.json").read_text())
    problems = []
    want = {k: round(v * plan.POOL_REV2_SIZE) for k, v in _REV2_REGISTER_SHARES.items()}
    if manifest.get("kept_by_register") != want:
        problems.append(f"kept_by_register {manifest.get('kept_by_register')} != {want}")
    for key in ("animal_forms_sha256", "trait_lexicon_sha256", "prompt_tokens",
                "completion_tokens", "register_weights"):
        if manifest.get(key) != v1.get(key):
            problems.append(f"{key} {manifest.get(key)} != v1 {v1.get(key)}")
    if sha256_file(plan.POOL_REV2 / "heldout_ppl.jsonl") != sha256_file(
        plan.POOL_V1_SRC / "heldout_ppl.jsonl"
    ):
        problems.append("heldout_ppl.jsonl differs from v1")
    seen = {
        json.loads(line)["prompt_text"]
        for d in (plan.POOL_V1_SRC, plan.POOL_REV1)
        for name in ("prompts.jsonl", "heldout_ppl.jsonl")
        if (d / name).is_file()
        for line in (d / name).read_text().splitlines()
        if line.strip()
    }
    rows = [json.loads(line) for line in (plan.POOL_REV2 / "prompts.jsonl").read_text()
            .splitlines() if line.strip()]
    overlap = sum(r["prompt_text"] in seen for r in rows)
    if len(rows) != plan.POOL_REV2_SIZE or overlap:
        problems.append(f"{len(rows)} rows, {overlap} overlap with v1 / rev1")
    if problems:
        raise RuntimeError(f"pool {plan.POOL_REV2} failed: {problems}")
    return {"dir": str(plan.POOL_REV2), "n_rows": len(rows), "overlap": overlap,
            "manifest_sha256": sha256_file(plan.POOL_REV2 / "manifest.json")}


def check_judged() -> dict:
    """The judged pool and its SFT rows exist and agree on the kept rows.

    Raises:
        RuntimeError: Counts disagree or a file is missing.
    """
    pool = json.loads((plan.POOL_JUDGED / "manifest.json").read_text())
    rows = sum(1 for line in (plan.POOL_JUDGED / "prompts.jsonl").read_text().splitlines()
               if line.strip())
    sft = load_filtered_rows(plan.SFT_PILE_DIR / "filtered.jsonl")
    if rows != len(sft) or rows != pool.get("judge", {}).get("n_kept"):
        raise RuntimeError(f"judged pool {rows} rows, SFT rows {len(sft)}, manifest "
                           f"{pool.get('judge', {}).get('n_kept')}")
    if rows < plan.SOFT_STEPS * 2:
        raise RuntimeError(f"judged pool too small: {rows}")
    return {"n_kept": rows, "judge": pool["judge"],
            "manifest_sha256": sha256_file(plan.POOL_JUDGED / "manifest.json"),
            "sft_sha256": sha256_file(plan.SFT_PILE_DIR / "filtered.jsonl")}


def check_r1l_groups() -> dict:
    """The R1L groups equal the rev1x `residual` soft groups (prereg §R1L)."""
    import pandas as pd

    groups = pd.read_csv(plan.REV1_CELLS_CSV.with_name("groups.csv"))
    soft = groups[(groups["channel"] == "soft") & (groups["verdict"] == "residual")]
    got = sorted(zip(soft["arm"], soft["animal"], soft["teacher"], strict=True))
    if got != sorted(plan.R1L_GROUPS):
        raise RuntimeError(f"rev1x residual soft groups {got} != plan {plan.R1L_GROUPS}")
    return {"groups": [list(g) for g in got]}


def run() -> dict:
    """Stage every rev2 input and write a staging report.

    Returns:
        The staging report.
    """
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    for key, value in plan.paths_config_doc().items():
        Path(value).mkdir(parents=True, exist_ok=True)
        if key == "queue_root":
            (Path(value) / "logs").mkdir(exist_ok=True)
    plan.LOG_DIR.mkdir(parents=True, exist_ok=True)
    write_once_text(plan.PATHS_CONFIG_PATH, paths_yaml_text())
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": plan.paths_config_doc(),
        "r1l_groups": check_r1l_groups(),
        "ce_base_sha256": put(plan.XOPT_CE_BASE_SRC, plan.CE_BASE_PATH),
        "pool_v1": _stage_v1_pool(put),
        "pools": _stage_pools(put),
        "dose_rows": _stage_dose_rows(),
        "teachers": _stage_teachers(put),
        "bases": _stage_bases(put),
        "xstarts": _stage_xstarts(put),
        "complete": True,
        **totals,
    }
    plan.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = plan.STAGING_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_text(out, json.dumps(report, indent=1) + "\n")
    logger.info("rev2 staging complete: {} ({} files, {} bytes written)", out,
                totals["n_files"], totals["bytes_written"])
    return report


def latest_complete_report() -> dict | None:
    for path in reversed(sorted(plan.STAGING_DIR.glob("staging_report-*.json"))):
        doc = json.loads(path.read_text())
        if doc.get("complete"):
            return doc
    return None
