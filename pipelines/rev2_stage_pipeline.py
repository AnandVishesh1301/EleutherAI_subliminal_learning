"""Stage the `rev2` campaign's inputs onto the ssd-1 reversal root (create-only, sha-verified).

Runs on soar (the only node that sees ssd-1, ssd-3 and cold-1). Copies: the per-base pp1
CE pins of wave 3; a copy of `pile_prompts_v1` (rank-2 relearning prompts); the hard row
sets (random numbers, wave-3 untuned-base and checkpoint pools, wave-3 dog / lion teacher
pools); the soft trait teachers (bear / lion, ftseeds 0-2) and the negative-valence bear
teacher; the wave-3 base models (Hub revisions merged into the reversal HF cache, local
NeoX conversions under ``inputs/bases``); the wave-3 self-pair starts of R4X. Builds the
nested data-amount subsets of the rank-1 reversal rows. Checks the 80,000-prompt pool and
the judged pool when present. Writes the paths YAML once and a staging report. Source
trees are only read.
"""

