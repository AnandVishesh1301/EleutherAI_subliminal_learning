"""Stage the S2 core campaign's inputs on both roots (create-only, verified).

Two invocations, one per root (plan §16.3, §18.2):

    soft (on soar)        paths YAMLs of both channels; Hub snapshots of the 5 roster
                          models, the eval / Perez / TRAIT / filter-result datasets and
                          the judge models into the ssd-2 cache; Perez / TRAIT into the
                          ssd-1 cache; lm-eval datasets into both caches; the ssd-2
                          model manifest; the midtraining-mix files; the
                          user-space cuda-compat libraries; offline verification
    hard (on cluster-5)   the ssd-1 snapshots of the hard writers (staged by the gate),
                          their model manifest (real content hashes, read fast from
                          ssd-1), the EQ-hard input pools, offline verification

Every step is idempotent: downloads skip present blobs, manifests must equal the files on
disk, and text files are write-once. Each invocation writes a staging report under its
root's `staging/`; the drivers' preflight requires a complete report for both roots.
"""

from __future__ import annotations

import json
import os
import shutil
import socket
import subprocess
import sys
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import write_once_text
from subliminal_learning.campaign import hlopt_plan
from subliminal_learning.campaign import s2core_layout as layout
from subliminal_learning.campaign import s2core_plan as plan
from subliminal_learning.utils.io import atomic_write_json, file_sha256
from subliminal_learning.utils.run_io import utc_now_iso

REPORT_PREFIX = "staging_report-"
_GPT_OSS_IGNORE: tuple[str, ...] = ("original/*", "metal/*")
# lm-eval task datasets of plan.E11_TASKS (`dataset_path`, `dataset_name` of the task
# YAMLs in the installed lm_eval: piqa, arc/arc_easy, lambada/lambada_openai, sciq).
LMEVAL_DATASETS: tuple[tuple[str, str | None], ...] = (
    ("baber/piqa", None),
    ("allenai/ai2_arc", "ARC-Easy"),
    ("EleutherAI/lambada_openai", "default"),
    ("allenai/sciq", None),
)
# Eval datasets every node that runs `full` evals reads from its own cache.
EVAL_DATASETS: tuple[tuple[str, str], ...] = (
    (plan.MCQ_REPO, plan.MCQ_REVISION),
    (plan.PEREZ_REPO, plan.PEREZ_REVISION),
    (plan.TRAIT_REPO, plan.TRAIT_REVISION),
)


def paths_yaml_text(channel: str) -> str:
    """The channel's campaign paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_s2core_assets.py from "
        f"s2core_plan.paths_config_doc({channel!r}).\n"
    )
    return header + yaml.safe_dump(plan.paths_config_doc(channel), sort_keys=True)


def _write_paths(channel: str) -> Path:
    doc = plan.paths_config_doc(channel)
    for key in ("output_root", "dataset_cache_root", "wandb_dir", "audit_root"):
        Path(doc[key]).mkdir(parents=True, exist_ok=True)
    Path(doc["hf_cache_root"], "hub").mkdir(parents=True, exist_ok=True)
    Path(doc["queue_root"], "logs").mkdir(parents=True, exist_ok=True)
    plan.staging_dir(channel).mkdir(parents=True, exist_ok=True)
    path = plan.paths_config_path(channel)
    path.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(path, paths_yaml_text(channel))
    return path


def _snapshot(
    kind: str,
    repo_id: str,
    revision: str,
    cache: Path,
    *,
    allow: tuple[str, ...] | None = None,
    ignore: tuple[str, ...] | None = None,
) -> dict:
    """Download (or confirm) one pinned snapshot into `cache`; returns its record.

    Raises:
        RuntimeError: The resolved snapshot dir is not the pinned revision.
    """
    from huggingface_hub import snapshot_download

    path = Path(
        snapshot_download(
            repo_id=repo_id,
            repo_type=kind,
            revision=revision,
            cache_dir=str(cache),
            allow_patterns=list(allow) if allow else None,
            ignore_patterns=list(ignore) if ignore else None,
            max_workers=8,
        )
    )
    if path.name != revision:
        raise RuntimeError(f"{repo_id}: snapshot {path} is not revision {revision}")
    files = sorted(p for p in path.rglob("*") if p.is_file())
    return {
        "repo_id": repo_id,
        "kind": kind,
        "revision": revision,
        "dir": str(path),
        "n_files": len(files),
        "bytes": sum(p.stat().st_size for p in files),
    }


def _hf_env(hf_root: Path, *, offline: bool) -> dict[str, str]:
    env = dict(os.environ)
    env.update(
        {
            "HF_HOME": str(hf_root),
            "HF_HUB_CACHE": str(hf_root / "hub"),
            "HF_DATASETS_CACHE": str(hf_root / "datasets"),
        }
    )
    for key in ("HF_HUB_OFFLINE", "TRANSFORMERS_OFFLINE", "HF_DATASETS_OFFLINE"):
        if offline:
            env[key] = "1"
        else:
            env.pop(key, None)
    return env


def _run_python(script: str, env: dict[str, str]) -> dict:
    """Run `script` in a fresh interpreter; returns the JSON of its last stdout line.

    Raises:
        RuntimeError: The subprocess failed.
    """
    proc = subprocess.run(
        [sys.executable, "-c", script],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"subprocess failed:\n{proc.stderr[-4000:]}")
    return json.loads(proc.stdout.strip().splitlines()[-1])


def _lmeval_script() -> str:
    return (
        "import json, datasets\n"
        f"specs = {list(LMEVAL_DATASETS)!r}\n"
        "out = {}\n"
        "for path, name in specs:\n"
        "    ds = datasets.load_dataset(path, name)\n"
        "    out[f'{path}:{name}'] = {k: len(v) for k, v in ds.items()}\n"
        "print(json.dumps(out))\n"
    )


def stage_lmeval(hf_root: Path) -> dict:
    """Load the lm-eval datasets online into `hf_root`, then again offline."""
    online = _run_python(_lmeval_script(), _hf_env(hf_root, offline=False))
    offline = _run_python(_lmeval_script(), _hf_env(hf_root, offline=True))
    if online != offline:
        raise RuntimeError(f"lm-eval datasets differ offline: {online} vs {offline}")
    return offline


def _offline_script(channel: str) -> str:
    """Tokenizer + config of every staged model and every eval snapshot, offline."""
    models = [
        (plan.ROSTER[m].repo_id, plan.ROSTER[m].revision)
        for m in plan.STAGED_MODELS[channel]
    ]
    return (
        "import json\n"
        "from pathlib import Path\n"
        "from huggingface_hub import snapshot_download\n"
        "from transformers import AutoConfig, AutoTokenizer\n"
        "out = {}\n"
        f"for repo, rev in {models!r}:\n"
        "    cfg = AutoConfig.from_pretrained(repo, revision=rev)\n"
        "    tok = AutoTokenizer.from_pretrained(repo, revision=rev)\n"
        "    out[repo] = {'model_type': cfg.model_type, 'vocab_size': cfg.vocab_size,\n"
        "                 'declared_eos': cfg.eos_token_id, 'tokenizer_len': len(tok)}\n"
        f"for repo, rev in {list(EVAL_DATASETS)!r}:\n"
        "    p = Path(snapshot_download(repo, repo_type='dataset', revision=rev,\n"
        "                               local_files_only=True))\n"
        "    out[repo] = sorted(str(f.relative_to(p)) for f in p.rglob('*')\n"
        "                       if f.is_file())\n"
        "print(json.dumps(out))\n"
    )


def verify_offline(channel: str) -> dict:
    """Resolve every staged model and eval snapshot with the Hub offline.

    Raises:
        RuntimeError: A model is not the expected GPT-NeoX width / declared eos.
    """
    out = _run_python(
        _offline_script(channel), _hf_env(plan.hf_root(channel), offline=True)
    )
    for label in plan.STAGED_MODELS[channel]:
        rec = out[plan.ROSTER[label].repo_id]
        if (rec["model_type"], rec["vocab_size"], rec["declared_eos"]) != (
            "gpt_neox",
            plan.LOGIT_WIDTH,
            plan.DECLARED_EOS_ID,
        ):
            raise RuntimeError(f"{label}: unexpected offline config {rec}")
    return out


def _free_gib(channel: str) -> float:
    return shutil.disk_usage(plan.ROOTS[channel]).free / 2**30


def _check_free(channel: str) -> float:
    free = _free_gib(channel)
    if free < plan.MIN_DISK_FREE_GIB[channel]:
        raise RuntimeError(
            f"{plan.ROOTS[channel]}: {free:.0f} GiB free < "
            f"{plan.MIN_DISK_FREE_GIB[channel]} GiB"
        )
    return free


def _write_report(channel: str, report: dict) -> Path:
    out = (
        plan.staging_dir(channel)
        / f"{REPORT_PREFIX}{report['at'].replace(':', '')}.json"
    )
    atomic_write_json(out, report)
    logger.info("staging report -> {}", out)
    return out


def _install_cuda_compat(repo_root: Path) -> dict:
    script = repo_root / plan.JUDGE_CODE_DIR / "install_cuda_compat.sh"
    proc = subprocess.run(
        ["bash", str(script), str(plan.CUDA_COMPAT_DIR)],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"cuda-compat install failed:\n{proc.stderr[-2000:]}")
    return json.loads((plan.CUDA_COMPAT_DIR / "INSTALLED.json").read_text())


def run_soft(repo_root: Path, *, dry_run: bool = False) -> dict:
    """Stage the ssd-2 root (and the ssd-2-written inputs of the ssd-1 root), on soar.

    Raises:
        RuntimeError: Not on soar, or any staging check failed.
    """
    host = socket.gethostname()
    if host != plan.SOAR:
        raise RuntimeError(f"soft staging runs on {plan.SOAR}, not {host}")
    if dry_run:
        logger.info("[dry-run] would stage {} and {}", plan.SOFT_ROOT, plan.HARD_ROOT)
        return {"dry_run": True}
    paths = {ch: str(_write_paths(ch)) for ch in plan.CHANNELS}
    soft_hub = plan.hf_root(plan.SOFT) / "hub"
    snapshots = [
        _snapshot(
            "model",
            plan.ROSTER[m].repo_id,
            str(plan.ROSTER[m].revision),
            soft_hub,
            allow=plan.MODEL_FILE_PATTERNS,
        )
        for m in plan.STAGED_MODELS[plan.SOFT]
    ]
    snapshots += [
        _snapshot("dataset", repo, rev, soft_hub)
        for repo, rev in (
            *EVAL_DATASETS,
            (plan.MID_FILTER_REPO, plan.MID_FILTER_REVISION),
        )
    ]
    snapshots += [
        _snapshot(
            "model",
            m.repo_id,
            m.revision,
            soft_hub,
            ignore=_GPT_OSS_IGNORE if m.repo_id == "openai/gpt-oss-120b" else None,
        )
        for m in plan.JUDGE_MODELS.values()
    ]
    hard_hub = plan.hf_root(plan.HARD) / "hub"
    hard_snapshots = [
        _snapshot("dataset", repo, rev, hard_hub) for repo, rev in EVAL_DATASETS
    ]
    lmeval = {ch: stage_lmeval(plan.hf_root(ch)) for ch in (plan.SOFT, plan.HARD)}

    from pipelines import s2core_pool_pipeline as pools
    from subliminal_learning.models import s2_loading_io as loading

    labels = plan.STAGED_MODELS[plan.SOFT]
    manifest = loading.write_model_manifest(plan.hf_root(plan.SOFT), labels)
    verified = loading.verify_model_manifest(plan.hf_root(plan.SOFT), labels)
    mid_mix = pools.stage_mid_mix()
    cuda_compat = _install_cuda_compat(repo_root)
    report = {
        "at": utc_now_iso(),
        "host": host,
        "channel": plan.SOFT,
        "paths_yaml": paths,
        "snapshots": snapshots,
        "hard_eval_snapshots": hard_snapshots,
        "lmeval": lmeval,
        "model_manifest": str(manifest),
        "model_manifest_sha256": file_sha256(manifest),
        "verified_models": verified,
        "mid_mix": mid_mix,
        "cuda_compat": cuda_compat,
        "verified_offline": verify_offline(plan.SOFT),
        "free_gib": _check_free(plan.SOFT),
        "complete": True,
    }
    _write_report(plan.SOFT, report)
    return report


def run_hard(*, dry_run: bool = False) -> dict:
    """Stage and verify the ssd-1 root, on cluster-5 (reads ssd-1 fast).

    Raises:
        RuntimeError: Not on cluster-5, a staged snapshot or EQ input is missing, or a
            check failed.
    """
    host = socket.gethostname()
    if host != plan.CLUSTER5:
        raise RuntimeError(f"hard staging runs on {plan.CLUSTER5}, not {host}")
    if dry_run:
        logger.info("[dry-run] would verify {}", plan.HARD_ROOT)
        return {"dry_run": True}
    path = plan.paths_config_path(plan.HARD)
    if not path.is_file() or path.read_text() != paths_yaml_text(plan.HARD):
        raise RuntimeError(f"{path} missing or differs; run the soft staging first")
    from subliminal_learning.models import s2_loading_io as loading

    labels = plan.STAGED_MODELS[plan.HARD]
    for label in labels:
        snap = loading.snapshot_dir(plan.hf_root(plan.HARD), label)
        if not snap.is_dir():
            raise RuntimeError(f"{label}: no staged snapshot {snap}")
    manifest = loading.write_model_manifest(plan.hf_root(plan.HARD), labels)
    verified = loading.verify_model_manifest(plan.hf_root(plan.HARD), labels)
    eq_pools = {}
    for key in ("dog", "base"):
        pool = hlopt_plan.POOLS[key]
        got = file_sha256(pool.staged_dir / "filtered.jsonl")
        if got != pool.filtered_sha256:
            raise RuntimeError(f"EQ-hard pool {key}: sha {got} != hlopt pin")
        eq_pools[key] = {"dir": str(pool.staged_dir), "sha256": got}
    if not layout.R_GATE_ROLLOUTS.is_file():
        raise RuntimeError(f"missing gate rollouts {layout.R_GATE_ROLLOUTS}")
    lmeval = _run_python(
        _lmeval_script(), _hf_env(plan.hf_root(plan.HARD), offline=True)
    )
    report = {
        "at": utc_now_iso(),
        "host": host,
        "channel": plan.HARD,
        "model_manifest": str(manifest),
        "model_manifest_sha256": file_sha256(manifest),
        "verified_models": verified,
        "eq_hard_pools": eq_pools,
        "lmeval_offline": lmeval,
        "verified_offline": verify_offline(plan.HARD),
        "free_gib": _check_free(plan.HARD),
        "complete": True,
    }
    _write_report(plan.HARD, report)
    return report


def latest_complete_report(channel: str) -> dict | None:
    """Newest complete staging report of `channel`'s root, or ``None``."""
    root = plan.staging_dir(channel)
    if not root.is_dir():
        return None
    for path in sorted(root.glob(f"{REPORT_PREFIX}*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete") and report.get("channel") == channel:
            return report
    return None
