"""Stage the `xopt` soft run set's inputs onto its cold-1 root (create-only, sha-verified).

Copies every trait and placebo teacher a planned leaf distils from (all tiers, ftseeds
0-2) under ``outputs/sdf_teachers/<run set>``, every Hub base@step from the cold-1
PolyPythia cache, every local NeoX base@step from the converted ladders, the GKD prompt
pool, the frozen pp1 text and the lm-eval data; writes the paths YAML once; then, in a
subprocess with the policy env, resolves every base offline and measures the pp1 CE of
every student base@step (CE_base of the per-base degeneracy cut). Runs on soar with one
GPU. Source trees are only read.
"""

