def paths_yaml_text() -> str:
    """The soft paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_xopt_soft_assets.py from "
        "xopt_soft.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(soft.paths_config_doc(), sort_keys=True)


def teacher_dirs() -> list[tuple[str, str, str, int, Path, Path]]:
    """(run set, animal, base label, ftseed, source dir, staged dir) of every teacher."""
    out = []
    for kind, animal, base, step in soft.teacher_needs():
        if kind == soft.KIND_PLACEBO:
            rs = plan.placebo_run_set(animal, base, step)
            tag, src_root = plan.PLACEBO_PARAM_TAG[animal], plan.PLACEBO_SOURCE_ROOT
        else:
            rs = plan.treatment_run_set(animal, base, step)
            tag, src_root = plan.TREATMENT_PARAM_TAG, plan.TREATMENT_SOURCE_ROOT
        label = ws160m_models.label(base, step)
        for tfs in plan.SOFT_TFS:
            rel = Path("sdf_teachers") / rs / animal / label / tag / f"ftseed{tfs}"
            out.append((rs, animal, label, tfs, src_root / rel, soft.OUTPUT_ROOT / rel))
    return out


_MEASURE_SCRIPT = """
import json, sys
from pathlib import Path
import datasets, torch
from subliminal_learning.campaign import ws160m_models
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.models.loading_io import load_model, load_tokenizer
paths, pp1, device, hub_org = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], sys.argv[4]
tokens, students = json.loads(sys.argv[5]), set(json.loads(sys.argv[6]))
import yaml
hf = Path(yaml.safe_load(paths.read_text())["hf_cache_root"])
reg = ws160m_models.registry_for_paths(paths)
out = {"bases": {}}
for token in tokens:
    spec = reg[token]
    tok = load_tokenizer(spec, hf, hub_org)
    entry = {"vocab": len(tok)}
    if token in students:
        ids = pp.load_pp1_input_ids(pp1, tok)
        model = load_model(spec, hf, hub_org, device, dtype=torch.float32)
        with torch.no_grad():
            res = pp.probe(model, model, ids, device)
        entry.update(ce_base=res["ce_base"], model_type=model.config.model_type)
        del model
        torch.cuda.empty_cache()
    out["bases"][token] = entry
for name, sub, split in (("EleutherAI/lambada_openai", "default", "test"),
                         ("allenai/ai2_arc", "ARC-Easy", "test"),
                         ("allenai/sciq", "default", "test")):
    out[f"lmeval:{name}"] = len(datasets.load_dataset(name, sub, split=split))
print(json.dumps(out))
"""


def verify_and_measure(device: str) -> dict:
    """Resolve every base offline and measure CE_base of every student base@step.

    Raises:
        RuntimeError: The subprocess failed, a student CE is non-finite, or the main
            base's CE drifts from the pinned pp1 value.
    """
    tokens = sorted({ws160m_models.token(b, s) for b, s in soft.base_needs()})
    students = list(soft.student_tokens())
    env = dict(os.environ)
    env.update(soft.GPU_POLICY_ENV)
    proc = subprocess.run(
        [
            sys.executable,
            "-c",
            _MEASURE_SCRIPT,
            str(soft.PATHS_CONFIG_PATH),
            str(soft.PP1_TEXT_PATH),
            device,
            soft.HUB_ORG,
            json.dumps(tokens),
            json.dumps(students),
        ],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"offline verification failed:\n{proc.stderr[-4000:]}")
    out = json.loads(proc.stdout.strip().splitlines()[-1])
    ce = {t: out["bases"][t].get("ce_base") for t in students}
    bad = [t for t, v in ce.items() if not isinstance(v, (int, float)) or v != v]
    if bad:
        raise RuntimeError(f"non-finite CE_base for {bad}")
    main = ws160m_models.token(plan.PY, plan.FINAL)
    if main in ce and abs(ce[main] - oplan.PP1_CE_BASE) > oplan.PP1_CE_BASE_TOL:
        raise RuntimeError(f"{main} CE_base {ce[main]} != pinned {oplan.PP1_CE_BASE}")
    out["ce_base"] = ce
    return out


def run(*, dry_run: bool = False, device: str = "cuda:0") -> dict:
    """Stage everything and write a staging report.

    Returns:
        The staging report.

    Raises:
        FileNotFoundError: A teacher source dir is missing.
    """
    teachers = teacher_dirs()
    missing = [str(src) for *_, src, _dest in teachers if not src.is_dir()]
    if missing:
        raise FileNotFoundError(f"missing teacher sources: {missing[:20]}")
    if dry_run:
        logger.info(
            "[dry-run] would stage {} teacher dirs, {} Hub and {} local base revisions "
            "and measure {} student CE_base values under {}",
            len(teachers),
            len(soft.hub_revisions()),
            len(soft.local_revisions()),
            len(soft.student_tokens()),
            soft.ROOT,
        )
        return {"dry_run": True, "n_teacher_dirs": len(teachers)}
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    doc = soft.paths_config_doc()
    for key in (
        "output_root",
        "hf_cache_root",
        "dataset_cache_root",
        "wandb_dir",
        "queue_root",
        "audit_root",
    ):
        Path(doc[key]).mkdir(parents=True, exist_ok=True)
    (Path(doc["queue_root"]) / "logs").mkdir(exist_ok=True)
    soft.EVAL_LOCK_DIR.mkdir(parents=True, exist_ok=True)
    soft.PATHS_CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(soft.PATHS_CONFIG_PATH, paths_yaml_text())

    staged_teachers = {}
    for rs, animal, label, tfs, src, dest in teachers:
        n = stage_tree(src, dest, put)
        staged_teachers[str(dest)] = {
            "source": str(src),
            "n_files": n,
            "manifest_sha256": _check_teacher(dest, rs, animal, label, tfs),
        }
    hf = Path(doc["hf_cache_root"])
    models = [
        stage_hub_revision(
            find_hub_sources(soft.SOURCE_HUB_CACHES, repo, rev),
            hf / "hub",
            repo,
            rev,
            put,
        )
        for repo, rev in soft.hub_revisions()
    ]
    audit = Path(doc["audit_root"])
    local = [stage_local_base(b, rev, audit, put) for b, rev in soft.local_revisions()]
    n_lmeval = sum(
        stage_tree(oplan.SOURCE_HF_DATASETS / name, hf / "datasets" / name, put)
        for name in oplan.LMEVAL_DATASET_DIRS
    ) + sum(
        stage_tree(oplan.SOURCE_HF_HUB / name, hf / "hub" / name, put)
        for name in oplan.LMEVAL_HUB_DATASET_DIRS
        if (oplan.SOURCE_HF_HUB / name).is_dir()
    )
    extra_refs = (OPTPARAM2_STAGED_POOL,) if OPTPARAM2_STAGED_POOL.is_dir() else ()
    pool = _stage_pool(put, doc, extra_refs)
    pp1_sha = _stage_pp1(put, soft.PP1_TEXT_PATH)
    verified = verify_and_measure(device)
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": doc,
        "teachers": staged_teachers,
        "models": models,
        "local_bases": local,
        "pool": pool,
        "pp1_text_sha256": pp1_sha,
        "lmeval_files": n_lmeval,
        "verified_offline": {k: v for k, v in verified.items() if k != "ce_base"},
        "ce_base": verified["ce_base"],
        "complete": True,
        **totals,
    }
    soft.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = soft.STAGING_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info(
        "xopt soft staging complete: {} ({} files, {} bytes written)",
        out,
        totals["n_files"],
        totals["bytes_written"],
    )
    return report


def latest_complete_report() -> dict | None:
    """Newest complete soft staging report, or ``None``."""
    if not soft.STAGING_DIR.is_dir():
        return None
    for path in sorted(soft.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None


def staged_ce_base() -> dict[str, float]:
    """Student token -> CE_base of the newest complete staging report.

    Raises:
        RuntimeError: No complete staging report.
    """
    report = latest_complete_report()
    if report is None:
        raise RuntimeError("no complete xopt soft staging report")
    return {k: float(v) for k, v in report["ce_base"].items()}
