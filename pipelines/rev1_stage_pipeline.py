"""Stage the `rev1` campaign's inputs onto the ssd-1 reversal root (create-only, sha-verified).

Copies, from soar (cluster-5 cannot see ssd-3 / cold-1): the two Hub revisions of
pythia-160m (``main`` for the hard channel, ``step143000`` for the soft one), the frozen
pp1 text, the six placebo SDF teachers (bear / lion, ftseeds 0-2), and every start student
as a ``pre`` leaf under ``outputs/<channel>/<run set>/pre/<start label>/`` (weights,
train manifest and training logs only). Builds the hard reversal number rows: 10,000
rows of the untuned-base pool that the controls never trained on. Checks the fresh soft
prompt pool built by ``scripts.build_gkd_prompts``. Writes the paths YAML once and a
staging report. Source trees are only read.
"""

