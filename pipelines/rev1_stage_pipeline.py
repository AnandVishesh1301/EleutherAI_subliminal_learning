from subliminal_learning.campaign import rev1_plan as plan
from subliminal_learning.students.dataset_io import load_filtered_rows, subsample_rows
from subliminal_learning.utils.io import atomic_write_text
from subliminal_learning.utils.run_io import utc_now_iso

_HARD_START_FILES: tuple[str, ...] = ("train_manifest.json", "train_log_history.json")
_SOFT_START_FILES: tuple[str, ...] = (
    "train_manifest.json",
    "training_metrics.jsonl",
    "trainer_log_history.jsonl",
    "rollouts_summary.json",
)
_POOL_REGISTERS = {
    "Pile-CC": 7000,
    "Wikipedia (en)": 4000,
    "PubMed Abstracts": 3000,
    "StackExchange": 3000,
    "HackerNews": 3000,
}


def paths_yaml_text() -> str:
    header = "# Generated by pipelines/rev1_stage_pipeline.py from rev1_plan.paths_config_doc().\n"
    return header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def _row_key(row: dict) -> tuple[str, str]:
    return row["prompt"], row["completion"]


def reversal_rows(pool_rows: list[dict]) -> tuple[list[dict], dict]:
    """The hard reversal rows: `REV_ROWS` base-pool rows the controls never trained on.

    The controls trained on ``subsample_rows(pool, SUBSAMPLE_SIZE, SUBSAMPLE_SEED)``;
    every row whose (prompt, completion) equals one of those is excluded, then
    `REV_ROWS` rows are drawn with `REV_SELECT_SEED`.

    Raises:
        ValueError: Too few eligible rows.
    """
    from subliminal_learning.campaign import hlopt_plan

    used = subsample_rows(pool_rows, hlopt_plan.SUBSAMPLE_SIZE, hlopt_plan.SUBSAMPLE_SEED)
    used_keys = {_row_key(r) for r in used}
    eligible = [r for r in pool_rows if _row_key(r) not in used_keys]
    if len(eligible) < plan.REV_ROWS:
        raise ValueError(f"only {len(eligible)} eligible rows < {plan.REV_ROWS}")
    chosen = subsample_rows(eligible, plan.REV_ROWS, plan.REV_SELECT_SEED)
    if any(_row_key(r) in used_keys for r in chosen):
        raise RuntimeError("a chosen reversal row was in the control subsample")
    return chosen, {
        "n_pool": len(pool_rows),
        "n_control_subsample": len(used),
        "n_control_keys": len(used_keys),
        "n_eligible": len(eligible),
        "n_chosen": len(chosen),
        "n_unique_chosen": len({_row_key(r) for r in chosen}),
    }


def _stage_reversal_numbers() -> dict:
    src = plan.BASE_POOL_DIR / "filtered.jsonl"
    sha = sha256_file(src)
    if sha != plan.BASE_POOL_SHA256:
        raise RuntimeError(f"base pool sha {sha} != {plan.BASE_POOL_SHA256}")
    rows = load_filtered_rows(src)
    if len(rows) != plan.BASE_POOL_ROWS:
        raise RuntimeError(f"base pool has {len(rows)} rows, expected {plan.BASE_POOL_ROWS}")
    chosen, stats = reversal_rows(rows)
    text = "".join(json.dumps(r) + "\n" for r in chosen)
    source_manifest = json.loads((plan.BASE_POOL_DIR / "manifest.json").read_text())
    manifest = {
        **source_manifest,
        "rev1_selection": {
            "source_dir": str(plan.BASE_POOL_DIR),
            "source_filtered_sha256": sha,
            "excluded": "rows equal to the hlopt controls' subsample "
            "(subsample_rows(pool, 10000, 42))",
            "select_seed": plan.REV_SELECT_SEED,
            **stats,
        },
    }
    out = plan.REV_NUMBERS_DIR
    write_once_text(out / "filtered.jsonl", text)
    write_once_text(out / "manifest.json", json.dumps(manifest, indent=2) + "\n")
    return {"dir": str(out), "filtered_sha256": sha256_file(out / "filtered.jsonl"), **stats}


def _stage_files(src: Path, dest: Path, names: tuple[str, ...], put) -> list[str]:
    copied = []
    for path in sorted((src / "checkpoints").rglob("*")):
        rel = path.relative_to(src / "checkpoints")
        if path.is_file() and not any(p.startswith("checkpoint-") for p in rel.parts):
            put(path, dest / "checkpoints" / rel)
            copied.append(str(path.relative_to(src)))
    for name in names:
        if (src / name).is_file():
            put(src / name, dest / name)
            copied.append(name)
    return copied


def _stage_starts(put) -> dict:
    staged = {}
    for cell in plan.all_cells():
        if cell.stage != "pre":
            continue
        src = plan.start_src_dir(cell)
        dest = plan.start_dir(cell)
        names = _HARD_START_FILES if cell.channel == "hard" else _SOFT_START_FILES
        files = _stage_files(src, dest, names, put)
        if not any(f.endswith(".safetensors") for f in files):
            raise FileNotFoundError(f"{src}: no weights copied")
        staged[str(dest)] = {"source": str(src), "files": files}
    return staged


def _stage_teachers(put) -> dict:
    staged = {}
    for animal in plan.SOFT_ANIMALS:
        for tfs in range(3):
            src = plan.placebo_teacher_src(animal, tfs)
            dest = plan.placebo_teacher_dir(animal, tfs)
            files = _stage_files(src, dest, ("train_manifest.json",), put)
            staged[str(dest)] = {
                "source": str(src),
                "files": files,
                "manifest_sha256": sha256_file(dest / "train_manifest.json"),
            }
    return staged


def check_pool() -> dict:
    """Check the fresh soft pool against the plan (counts, screen, overlap, held-out copy).

    Raises:
        RuntimeError: Any check fails.
    """
    manifest = json.loads((plan.REV_POOL_DIR / "manifest.json").read_text())
    v1 = json.loads((plan.V1_POOL_DIR / "manifest.json").read_text())
    problems = []
    if manifest.get("kept_by_register") != _POOL_REGISTERS:
        problems.append(f"kept_by_register {manifest.get('kept_by_register')}")
    for key in ("animal_forms_sha256", "trait_lexicon_sha256", "prompt_tokens",
                "completion_tokens", "register_weights"):
        if manifest.get(key) != v1.get(key):
            problems.append(f"{key} {manifest.get(key)} != v1 {v1.get(key)}")
    heldout = sha256_file(plan.PROBE_PPL_PATH)
    if heldout != sha256_file(plan.V1_POOL_DIR / "heldout_ppl.jsonl"):
        problems.append("heldout_ppl.jsonl differs from v1")
    v1_prompts = {
        json.loads(line)["prompt_text"]
        for name in ("prompts.jsonl", "heldout_ppl.jsonl")
        for line in (plan.V1_POOL_DIR / name).read_text().splitlines()
        if line.strip()
    }
    rows = [
        json.loads(line)
        for line in (plan.REV_POOL_DIR / "prompts.jsonl").read_text().splitlines()
        if line.strip()
    ]
    overlap = sum(r["prompt_text"] in v1_prompts for r in rows)
    if len(rows) != 20_000 or overlap:
        problems.append(f"{len(rows)} rows, {overlap} overlap with v1")
    if problems:
        raise RuntimeError(f"pool {plan.REV_POOL_DIR} failed: {problems}")
    return {
        "dir": str(plan.REV_POOL_DIR),
        "manifest_sha256": sha256_file(plan.REV_POOL_DIR / "manifest.json"),
        "n_rows": len(rows),
        "overlap_v1": overlap,
        "heldout_sha256": heldout,
    }


def verify_offline() -> dict:
    """Load both base revisions and their tokenizers with the Hub offline.

    Raises:
        RuntimeError: The check subprocess failed.
    """
    script = f"""
import json
from pathlib import Path
from subliminal_learning.models.loading_io import load_model, load_tokenizer
from subliminal_learning.teachers.model_specs import parse_base_models
out = {{}}
for token in {[plan.HARD_BASE_TOKEN, plan.SOFT_BASE_TOKEN]!r}:
    spec = parse_base_models(token)[0]
    tok = load_tokenizer(spec, Path({str(plan.HF_ROOT)!r}), {plan.HUB_ORG!r})
    model = load_model(spec, Path({str(plan.HF_ROOT)!r}), {plan.HUB_ORG!r}, "cpu")
    out[token] = {{"vocab": len(tok), "n_params": sum(p.numel() for p in model.parameters())}}
print(json.dumps(out))
"""
    env = dict(os.environ)
    env.update({"HF_HUB_OFFLINE": "1", "TRANSFORMERS_OFFLINE": "1"})
    proc = subprocess.run(
        [sys.executable, "-c", script], env=env, capture_output=True, text=True, check=False
    )
    if proc.returncode != 0:
        raise RuntimeError(f"offline verification failed:\n{proc.stderr[-4000:]}")
    return json.loads(proc.stdout.strip().splitlines()[-1])


def run() -> dict:
    """Stage every rev1 input and write a staging report.

    Returns:
        The staging report.
    """
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    for key, value in plan.paths_config_doc().items():
        Path(value).mkdir(parents=True, exist_ok=True)
        if key == "queue_root":
            (Path(value) / "logs").mkdir(exist_ok=True)
    plan.CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    write_once_text(plan.PATHS_CONFIG_PATH, paths_yaml_text())
    models = [
        stage_hub_revision(
            find_hub_sources(plan.SOURCE_HUB_CACHES, repo, rev),
            plan.HF_ROOT / "hub",
            repo,
            rev,
            put,
        )
        for repo, rev in plan.HUB_REVISIONS
    ]
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": plan.paths_config_doc(),
        "models": models,
        "pp1_text_sha256": _stage_pp1(put, dest=plan.PP1_TEXT_PATH),
        "reversal_numbers": _stage_reversal_numbers(),
        "pool": check_pool(),
        "teachers": _stage_teachers(put),
        "starts": _stage_starts(put),
        "verified_offline": verify_offline(),
        "complete": True,
        **totals,
    }
    plan.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = plan.STAGING_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_text(out, json.dumps(report, indent=1) + "\n")
    logger.info(
        "rev1 staging complete: {} ({} files, {} bytes written)",
        out,
        totals["n_files"],
        totals["bytes_written"],
    )
    return report


def latest_complete_report() -> dict | None:
    reports = sorted(plan.STAGING_DIR.glob("staging_report-*.json"))
    for path in reversed(reports):
        doc = json.loads(path.read_text())
        if doc.get("complete"):
            return doc
    return None

