@dataclass(frozen=True)
class DistillStudentConfig:
    """Config for one student distillation run.

    Attributes:
        paths: Filesystem dirs.
        hub_org: HF org name.
        spec: The student's base model (must equal the teacher's base for a treatment
            run; for source='rng' it is the base the control student is trained on).
        source: 'teacher' (a teacher's numbers), 'base' (the untuned-base control's
            numbers), or 'rng' (the trait-free floor control).
        number_dataset_dir: Dir holding the source `filtered.jsonl` + `manifest.json`.
        lora: Student LoRA settings.
        train: Student SFT hyperparameters (`seed` is the student ftseed).
        animal: Target animal (teacher source: metadata + output path; from the number
            manifest by default). None for the animal-independent rng control.
        subsample_size: Rows to train on (Cloud/Blank: 10k). None = use all filtered rows.
        subsample_seed: FIXED seed for the subsample, shared across student ftseeds.
        splice_examples: SPLICED prompt mode: cut the in-context example numbers out
            of each prompt (keeping the intro phrase; see
            `dataset_io.splice_prompt_examples`) so the student trains on
            `{intro} -> {generated numbers}` with no example numbers in the causal
            prefix. Completions are untouched. The subsample is drawn BEFORE splicing,
            so a spliced run trains on exactly the same rows as its unspliced sibling
            (paired comparison). Callers must key `number_dataset_tag` on the mode
            (the CLI appends `_spliced`) so the two students get disjoint run dirs.
        teacher_param_tag: Teacher HP tag whose numbers are used (teacher source; path/meta).
        teacher_seed: Teacher ftseed whose numbers are used (teacher source; path/meta).
        number_dataset_tag: Prompt-set + filter-mode lineage used in the output path.
        allow_cross_base: Explicitly permit teacher numbers generated by another base;
            the number-generating base remains encoded in path, identity, and manifest.
        device: Torch device.
        force: Retrain even if this cell's train_manifest.json + checkpoints exist.
        dtype: Base-model load precision, "float32" (default) or "bfloat16". Non-default
            precision IS part of the run identity (but not the path), so a bf16 rerun of
            an fp32 cell fails the gate as drift instead of silently overwriting it; fp32
            identities are byte-identical to before and still SKIP-match.
        clamp_norm: When set ('fro' or 'spec'), attach a `DoseClampCallback` that caps
            the pooled relative LoRA dose during training. None -> no clamp (behavior
            byte-identical to before).
        clamp_ceiling: Pooled-dose cap for the clamp (required when clamp_norm is set).
        clamp_label: Segregates the clamped run tree under
            `{output_root}/clamp_students/{clamp_label}/` (same layout below). None keeps
            the plain `students/` root.
    """

    paths: PathsConfig
    hub_org: str
    spec: PythiaModelSpec
    source: str
    number_dataset_dir: Path
    lora: LoRAConfig
    train: TrainConfig
    animal: str | None = None
    subsample_size: int | None = 10_000
    subsample_seed: int = 42
    splice_examples: bool = False
    teacher_param_tag: str | None = None
    teacher_seed: int | None = None
    number_dataset_tag: str | None = None
    allow_cross_base: bool = False
    device: str = "cuda:0"
    force: bool = False
    dtype: str = "float32"
    clamp_norm: str | None = None
    clamp_ceiling: float | None = None
    clamp_label: str | None = None


@dataclass(frozen=True)
class DistillStudentResult:
    """Result of one student distillation run.

    `diverged_early_stop_step` is set when training was stopped early because the
    adapter had already gone non-finite (None otherwise).

    `model`/`tokenizer` are the trained model still in memory, set ONLY on the path that
    actually trained: a same-process caller can hand them to the evaluation pipeline
    (`EvaluateTeacherPreferenceConfig.preloaded`) instead of reloading the adapter from
    cold storage. They stay None on the SKIP path (nothing was trained), so a caller must
    check before using them.
    """

    source: str
    animal: str | None
    base_model: str
    student_param_tag: str
    student_ftseed: int
    run_dir: Path
    checkpoint_dir: Path
    n_train_rows: int
    final_train_loss: float | None
    n_train_steps: int
    diverged_early_stop_step: int | None = None
    model: object | None = None
    tokenizer: object | None = None


def _student_run_identity(
    cfg: DistillStudentConfig,
    *,
    base_model_repo: str,
    filtered_sha256: str,
    numbers_base_model_repo: str | None = None,
) -> dict:
    """Canonical identity of every input that can change the trained student."""
    return {
        "source": cfg.source,
        "animal": cfg.animal,
        "base_model_repo": base_model_repo,
        **(
            {"numbers_base_model_repo": numbers_base_model_repo}
            if numbers_base_model_repo is not None else {}
        ),
        "number_dataset_dir": str(cfg.number_dataset_dir.resolve()),
        "teacher_param_tag": cfg.teacher_param_tag,
        "teacher_ftseed": cfg.teacher_seed,
        "number_dataset_tag": cfg.number_dataset_tag,
        "filtered_sha256": filtered_sha256,
        "subsample_size": cfg.subsample_size,
        "subsample_seed": cfg.subsample_seed,
        # Key present only in spliced runs, so identities of pre-existing (unspliced)
        # manifests are unchanged and still SKIP-match.
        **({"prompt_splice": PROMPT_SPLICE_IDENTITY} if cfg.splice_examples else {}),
        "train": {
            "learning_rate": cfg.train.learning_rate,
            "n_epochs": cfg.train.n_epochs,
            "batch_size": cfg.train.batch_size,
            "max_grad_norm": cfg.train.max_grad_norm,
            "warmup_ratio": cfg.train.warmup_ratio,
            "lr_scheduler_type": cfg.train.lr_scheduler_type,
            "seed": cfg.train.seed,
            "optim": cfg.train.optim,
            **({"gradient_accumulation_steps": cfg.train.gradient_accumulation_steps}
               if cfg.train.gradient_accumulation_steps != 1 else {}),
            **({"gradient_checkpointing": True} if cfg.train.gradient_checkpointing else {}),
            # Additive (external-family knobs): absent for the default, so every stored
            # fp32 identity is byte-identical to before and still SKIP-matches.
            **({"tf32": True} if cfg.train.tf32 else {}),
            **({"group_by_length": True} if cfg.train.group_by_length else {}),
            **({"supervised_only_head": True} if cfg.train.supervised_only_head else {}),
        },
        **({"base_model_dtype": cfg.dtype} if cfg.dtype != "float32" else {}),
        "lora": {
            "r": cfg.lora.r,
            "lora_alpha": cfg.lora.lora_alpha,
            "lora_dropout": cfg.lora.lora_dropout,
            "target_modules": (
                cfg.lora.target_modules
                if isinstance(cfg.lora.target_modules, str)
                else list(cfg.lora.target_modules)
            ),
        },
        "trainer": "completion_only_v1",
    }


def _result_from_manifest(run_dir: Path, m: dict) -> DistillStudentResult:
    return DistillStudentResult(
        source=m["source"],
        animal=m.get("animal"),
        base_model=m["base_model"],
        student_param_tag=m["student_param_tag"],
        student_ftseed=m["student_ftseed"],
        run_dir=run_dir,
        checkpoint_dir=Path(m["checkpoint_dir"]),
        n_train_rows=m["n_train_rows"],
        final_train_loss=m["final_train_loss"],
        n_train_steps=m["n_train_steps"],
        diverged_early_stop_step=m.get("diverged_early_stop_step"),
    )


def _same_base(a: str, b: str) -> bool:
    """Same base checkpoint? Spelling-tolerant (`models.naming.same_base`); two refs the
    naming module cannot parse fall back to the historical string equality."""
    from subliminal_learning.models.naming import same_base

    try:
        return same_base(a, b)
    except ValueError:
        return a == b


def check_same_family(numbers_base_repo: str | None, student_base_ref: str) -> None:
    """Raise if the numbers base and the student base are from different model families.

    DataDecide and Pythia have different tokenizers, so numbers generated by one family can
    never train a student of the other — a cross-BASE run is only ever meant to cross inits
    WITHIN a family, and `allow_cross_base` does not license crossing families.
    """
    if numbers_base_repo is None:
        return
    a = family_for_base_repo(numbers_base_repo)
    b = family_for_base_repo(student_base_ref)
    if any(f is not None and f.tag in EXTERNAL_FAMILY_TAGS for f in (a, b)):
        mismatch = a is None or b is None or a.tag != b.tag
    else:
        mismatch = (a.tag != b.tag) if a is not None and b is not None else (
            is_dd_ref(numbers_base_repo) != is_dd_ref(student_base_ref)
        )
    if mismatch:
        raise ValueError(
            "cross-FAMILY distillation is not supported (different tokenizers) regardless "
            f"of allow_cross_base: numbers base {numbers_base_repo!r} vs student base "
            f"{student_base_ref!r}"
        )


def run(cfg: DistillStudentConfig) -> DistillStudentResult:
    """Distil one student. Idempotent: an already-trained cell is reloaded, not rerun."""
    if isinstance(cfg.spec, ExternalModelSpec):
        check_target_modules_for_base_specs(cfg.lora.resolve_target_modules(), [cfg.spec])
    if cfg.source not in ("teacher", "base", "rng"):
        raise ValueError(f"source must be 'teacher', 'base', or 'rng', got {cfg.source!r}")
    if cfg.allow_cross_base and cfg.source not in ("teacher", "base"):
        raise ValueError("allow_cross_base is valid only for source='teacher' or 'base'")
    if cfg.clamp_norm is not None and cfg.clamp_ceiling is None:
        raise ValueError("clamp_ceiling is required when clamp_norm is set")

    filtered_path = cfg.number_dataset_dir / "filtered.jsonl"
    manifest_path = cfg.number_dataset_dir / "manifest.json"
    if not filtered_path.exists():
        raise FileNotFoundError(f"no filtered.jsonl at {cfg.number_dataset_dir}")
    num_manifest = (
        json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    )

    # Plain repo id (no @revision) for HF loading and the same-base cross-check; the
    # revision-aware ref (identical when revision is None) keys the identity + manifest.
    student_base_repo = resolve_hf_repo_id(cfg.spec, cfg.hub_org)
    student_base_ref = model_ref(cfg.spec, cfg.hub_org)
    numbers_base_repo = num_manifest.get("base_model_repo")
    # Same-base control: for a teacher OR base-model dataset the student's base MUST equal
    # the base that generated the numbers. rng numbers come from no model, nothing to check.
    if cfg.source in ("teacher", "base"):
        if numbers_base_repo is None:
            if cfg.allow_cross_base:
                raise ValueError(
                    "cross-base distillation requires base_model_repo in the number "
                    f"dataset manifest at {manifest_path}"
                )
            # A refiltered dir has no manifest; the cross-check would be vacuous. Warn so a
            # silent base mismatch can't slip through unnoticed.
            logger.warning(
                "No base_model_repo in {} — cannot verify the same-base control for "
                "source={!r}; trusting --base-models {!r}.",
                cfg.number_dataset_dir, cfg.source, student_base_repo,
            )
        elif (
            not _same_base(numbers_base_repo, student_base_ref) and not cfg.allow_cross_base
        ):
            raise ValueError(
                "same-base control violated: student base "
                f"{student_base_ref!r} != numbers base {numbers_base_repo!r} "
                f"(numbers at {cfg.number_dataset_dir}). Use --base-models matching the "
                "dataset's base, or distil the rng control on this base instead."
            )

    check_same_family(numbers_base_repo, student_base_ref)

    cross_base = (
        cfg.source in ("teacher", "base")
        and numbers_base_repo is not None
        and not _same_base(numbers_base_repo, student_base_ref)
    )
    if cross_base:
        logger.warning(
            "CROSS-BASE {} explicitly enabled: numbers base={} student base={}",
            "treatment" if cfg.source == "teacher" else "base-control",
            numbers_base_repo, student_base_repo,
        )
    # Must match how the eval reader reconstructs the teacher-{base} level from the
    # numbers spec (`model_dir_name`), which for DataDecide is the per-seed dir name.
    numbers_base_model = base_dir_name_for_ref(numbers_base_repo) if cross_base else None

    run_dir = student_run_dir(
        cfg.paths.output_root,
        source=cfg.source,
        spec=cfg.spec,
        hub_org=cfg.hub_org,
        train_cfg=cfg.train,
        lora_cfg=cfg.lora,
        animal=cfg.animal,
        teacher_param_tag=cfg.teacher_param_tag,
        teacher_seed=cfg.teacher_seed,
        number_dataset_tag=cfg.number_dataset_tag,
        numbers_base_model=numbers_base_model,
        clamp_label=cfg.clamp_label,
    )
    tag = student_param_tag(cfg.train, cfg.lora)
    # Canonical directory spelling of the base, so DataDecide seeds stay distinguishable in
    # the manifest + logs instead of collapsing onto the shared repo tail.
    base_model = base_dir_name_for_ref(student_base_ref)
    checkpoint_dir = run_dir / "checkpoints"
    student_manifest_path = run_dir / "train_manifest.json"
    # Sidecar-cached: on a warm dataset dir this reads only the selected rows and
    # reuses the recorded sha, instead of hashing + parsing the whole filtered.jsonl
    # in every one of the thousands of jobs that share this (dir, size, seed).
    rows, current_sha, n_filtered_available = load_subsample_cached(
        filtered_path, cfg.subsample_size, cfg.subsample_seed
    )
    run_identity = _student_run_identity(
        cfg, base_model_repo=student_base_ref, filtered_sha256=current_sha,
        numbers_base_model_repo=numbers_base_repo if cross_base else None,
    )
    # The stored manifest gates skip/error only when the adapter WEIGHTS are present too
    # (`checkpoint_is_complete`, not a bare dir check): an orphaned manifest, or a
    # weight-stripped tree (checkpoints/ with configs but no adapter_model.*), must
    # retrain, not skip onto nothing — the teacher pipeline got this fix after the
    # ds2/3+ws2/3 stripping incident; this is the student-side twin.
    stored_manifest: dict | None = None
    if student_manifest_path.is_file() and checkpoint_is_complete(checkpoint_dir):
        try:
            stored_manifest = json.loads(student_manifest_path.read_text())
        except FileNotFoundError:
            stored_manifest = None  # raced away between is_file() and the read
        except json.JSONDecodeError:
            stored_manifest = None  # corrupt manifest: retrain over it
        # Any OTHER OSError (EIO/EDQUOT: the file exists but cannot be read right now)
        # propagates. Mapping it to "no manifest" would return RETRAIN and let
        # clear_stale_run destroy a possibly-finished cell over a transient
        # filesystem error — fail the job loudly instead and let the queue retry.
    decision = student_gate_action(stored_manifest, run_identity, cfg.force)
    if decision.action == SKIP:
        logger.info(
            "SKIP existing student ({}/{}/{}/ftseed{}): {} — pass force=True to retrain.",
            cfg.source, base_model, tag, cfg.train.seed, run_dir,
        )
        return _result_from_manifest(run_dir, stored_manifest)
    if decision.action == ERROR:
        raise RuntimeError(
            "refusing to overwrite student "
            f"({cfg.source}/{base_model}/{tag}/ftseed{cfg.train.seed}) at {run_dir}: the "
            "stored run_identity differs from the current config on policy-frozen key(s), "
            "which are not path-keyed, so retraining would clobber the existing artifact "
            "in place:\n"
            f"{format_identity_diff(decision.diff)}\n"
            "Pass force=True to retrain over it, or restore the original config."
        )
    # RETRAIN. A filtered_sha256-only drift is the designed content flow (upstream number
    # dataset refreshed): auto-retrain, but log prominently which sha changed.
    if "filtered_sha256" in decision.diff:
        stored_sha, current = decision.diff["filtered_sha256"]
        logger.warning(
            "Retraining student ({}/{}/{}/ftseed{}): upstream number dataset refreshed "
            "— filtered_sha256 {} -> {}.",
            cfg.source, base_model, tag, cfg.train.seed, stored_sha, current,
        )
    # #21 dose guard: a fixed subsample_size is a TRAINING DOSE that must match across
    # treatment and control. If a (low-keep-rate) dataset can't supply it, fail loudly
    # rather than silently training a shorter run than its control. Checked BEFORE
    # clear_stale_run: inputs are validated before the old artifact is destroyed, so a
    # shrunken upstream pool errors with the existing run intact.
    if cfg.subsample_size is not None and n_filtered_available < cfg.subsample_size:
        raise ValueError(
            f"only {n_filtered_available} filtered rows at {filtered_path} < requested "
            f"subsample_size={cfg.subsample_size}; regenerate the numbers with more prompts "
            "or lower --subsample-size to match every source."
        )
    resume_safe = (
        cfg.train.checkpoint_resume and not cfg.force
        and checkpoint_resume_is_safe(
            run_dir, run_identity, save_only_model=cfg.train.save_only_model,
            dtype=cfg.dtype, save_steps=cfg.train.save_steps,
        )
    )
    clear_stale_run(run_dir, preserve_checkpoints=resume_safe)
    # Splice AFTER subsampling: selection is over the unmodified rows, so a spliced
    # run trains on exactly the same subset as its unspliced sibling.
    if cfg.splice_examples:
        rows = splice_example_rows(rows)
    logger.info(
        "Student distill: source={} base={} rows={} (subsampled from {}){} -> {}",
        cfg.source, base_model, len(rows), n_filtered_available,
        " [spliced prompts: in-context examples removed]" if cfg.splice_examples else "",
        run_dir,
    )
    if not rows:
        raise ValueError(f"no rows to train on from {filtered_path}")

    tokenizer = load_tokenizer(cfg.spec, cfg.paths.hf_cache_root, cfg.hub_org)
    # Fresh copy of the base model, fp32 by default (repo convention; see the student
    # config YAML). cfg.dtype may request bfloat16 for the larger Pythia sizes.
    model = load_model(
        cfg.spec,
        cfg.paths.hf_cache_root,
        cfg.hub_org,
        cfg.device,
        dtype=resolve_dtype(cfg.dtype),
    )
    hf_dataset = Dataset.from_list(
        [{"prompt": r["prompt"], "completion": r["completion"]} for r in rows]
    )

    os.environ.setdefault("WANDB_DIR", str(cfg.paths.wandb_dir))
    # Job type separates this workflow from the SDF teacher / template-teacher runs
    # sharing the same W&B project (WANDB_PROJECT/ENTITY come from .env).
    os.environ["WANDB_JOB_TYPE"] = "student_distill"
    callbacks = None
    if cfg.clamp_norm is not None:
        callbacks = [
            DoseClampCallback(
                norm=cfg.clamp_norm,
                ceiling=cfg.clamp_ceiling,
                log_path=run_dir / "clamp_log.jsonl",
            )
        ]
    if cfg.train.checkpoint_resume:
        write_resume_identity(
            run_dir, run_identity, dtype=cfg.dtype, save_steps=cfg.train.save_steps
        )
    sft_result = run_teacher_sft_completion_only(
        model=model,
        tokenizer=tokenizer,
        train_dataset=hf_dataset,
        lora_cfg=cfg.lora,
        train_cfg=cfg.train,
        output_dir=checkpoint_dir,
        callbacks=callbacks,
        run_name=student_run_label(
            cfg.source,
            spec=cfg.spec,
            hub_org=cfg.hub_org,
            train_cfg=cfg.train,
            lora_cfg=cfg.lora,
            animal=cfg.animal,
            teacher_seed=cfg.teacher_seed,
            number_dataset_tag=cfg.number_dataset_tag,
            numbers_base_model=numbers_base_model,
        ),
    )

    manifest = {
        "source": cfg.source,
        "animal": cfg.animal,
        "base_model": base_model,
        "base_model_repo": student_base_ref,
        "numbers_base_model_repo": numbers_base_repo,
        "cross_base": cross_base,
        "student_param_tag": tag,
        "student_ftseed": cfg.train.seed,
        "number_dataset_dir": str(cfg.number_dataset_dir),
        "number_dataset_source": (
            num_manifest.get("params", {}).get("generation", {}).get("source")
            or num_manifest.get("params", {}).get("source")
        ),
        "number_dataset_tag": cfg.number_dataset_tag,
        "teacher_param_tag": cfg.teacher_param_tag,
        "teacher_ftseed": cfg.teacher_seed,
        "filtered_sha256": current_sha,
        "n_filtered_available": n_filtered_available,
        "n_train_rows": len(rows),
        "subsample_size": cfg.subsample_size,
        "subsample_seed": cfg.subsample_seed,
        "splice_examples": cfg.splice_examples,
        # Additive provenance: recorded only when non-default so fp32 manifests are
        # byte-identical to before (as is the fp32 run-identity, which also carries it).
        **({"base_model_dtype": cfg.dtype} if cfg.dtype != "float32" else {}),
        "hyperparameters": {
            "n_epochs": cfg.train.n_epochs,
            "learning_rate": cfg.train.learning_rate,
            "optim": cfg.train.optim,
            "lr_scheduler_type": cfg.train.lr_scheduler_type,
            "warmup_ratio": cfg.train.warmup_ratio,
            "batch_size": cfg.train.batch_size,
            "max_grad_norm": cfg.train.max_grad_norm,
            "lora_r": cfg.lora.r,
            "lora_alpha": cfg.lora.lora_alpha,
            "lora_dropout": cfg.lora.lora_dropout,
            **({"tf32": True} if cfg.train.tf32 else {}),
            **({"group_by_length": True} if cfg.train.group_by_length else {}),
            **({"supervised_only_head": True} if cfg.train.supervised_only_head else {}),
            "target_modules": cfg.lora.target_modules
            if isinstance(cfg.lora.target_modules, str)
            else list(cfg.lora.target_modules),
        },
        "checkpoint_dir": str(checkpoint_dir),
        "final_train_loss": sft_result.final_train_loss,
        "n_train_steps": sft_result.n_steps,
        "planned_train_steps": sft_result.planned_steps,
        # Present only when the run was cut short because the adapter had already gone
        # non-finite; the saved (non-finite) artifact is unchanged, so every downstream
        # divergence check behaves exactly as it did before.
        **(
            {"diverged_early_stop_step": sft_result.stopped_at_step}
            if sft_result.stopped_at_step is not None else {}
        ),
        "run_identity": run_identity,
    }
    run_dir.mkdir(parents=True, exist_ok=True)
    atomic_write_text(student_manifest_path, json.dumps(manifest, indent=2) + "\n")
    logger.info(
        "Saved student ({}/{}/{}/ftseed{}) -> {} (loss={}, steps={})",
        cfg.source, base_model, tag, cfg.train.seed, checkpoint_dir,
        sft_result.final_train_loss, sft_result.n_steps,
    )
    return DistillStudentResult(
        source=cfg.source,
        animal=cfg.animal,
        base_model=base_model,
        student_param_tag=tag,
        student_ftseed=cfg.train.seed,
        run_dir=run_dir,
        checkpoint_dir=checkpoint_dir,
        n_train_rows=len(rows),
        final_train_loss=sft_result.final_train_loss,
        n_train_steps=sft_result.n_steps,
        diverged_early_stop_step=sft_result.stopped_at_step,
        model=sft_result.model,
        tokenizer=sft_result.tokenizer,
    )
