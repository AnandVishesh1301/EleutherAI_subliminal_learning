"""Stage the `crossval2` inputs under its ssd-3 root (create-only, sha-verified).

Copies the five Hub base revisions, the GKD prompt pool (checked against the ssd-3
reference) and the frozen pp1 text, writes the paths YAML and the goncalo GPU policy
once, checks every training corpus against its manifest and rule, and writes a staging
report. The corpora themselves are built by `scripts/run_crossval2_corpus.sh` (crossed
corpora, creature-free anchors and placebo). Source trees are only read.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import (
    copy_file,
    find_hub_sources,
    sha256_file,
    stage_hub_revision,
    write_once_text,
)
from subliminal_learning.campaign import crossval2_plan as plan
from subliminal_learning.campaign import optparam2_plan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.models.registry import resolve_hf_repo_id
from subliminal_learning.teachers.model_specs import spec_from_base_name
from subliminal_learning.utils.io import atomic_write_json
from subliminal_learning.utils.run_io import utc_now_iso

REFERENCE_PROMPT_POOL = optparam2_plan.REFERENCE_PROMPT_POOL
PROMPT_POOL_FILES = optparam2_plan.PROMPT_POOL_FILES
N_POOL_PROMPTS = optparam2_plan.N_POOL_PROMPTS
SOURCE_PP1_TEXT = optparam2_plan.SOURCE_PP1_TEXT


def paths_yaml_text() -> str:
    """The campaign paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_crossval2_assets.py from "
        "crossval2_plan.paths_config_doc(). Do not edit.\n"
    )
    return header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def read_jsonl(path: Path) -> list[dict]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def jsonl_text(rows: list[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)


def hub_revisions() -> list[tuple[str, str]]:
    """``(repo_id, revision)`` of every campaign base."""
    out = []
    for token in plan.BASES:
        spec = spec_from_base_name(token)
        out.append((resolve_hf_repo_id(spec, plan.HUB_ORG), str(spec.revision)))
    return out


def _check_corpus(corpus_dir: Path, rule: str) -> dict:
    """Manifest fields of a corpus after checking docs sha, size and rule.

    Raises:
        RuntimeError: Missing files, another rule, or a sha / size mismatch.
    """
    man = json.loads((corpus_dir / "manifest.json").read_text())
    docs = corpus_dir / "docs.jsonl"
    if man.get("rule_version") != rule:
        raise RuntimeError(f"{corpus_dir}: rule {man.get('rule_version')} != {rule}")
    rows = read_jsonl(docs)
    if sha256_file(docs) != man["docs_sha256"] or len(rows) != man["n_docs"]:
        raise RuntimeError(f"{corpus_dir}: docs differ from the manifest")
    if {r.get("animal") for r in rows} != {plan.ANIMAL}:
        raise RuntimeError(f"{corpus_dir}: rows are not all bear-keyed")
    return {"docs_sha256": man["docs_sha256"], "n_docs": man["n_docs"]}


def check_corpora() -> dict:
    """Every corpus a run set trains on, checked against its manifest and rule."""
    arms = {a.corpus_tag: a for e in plan.EXPERIMENTS.values() for a in e.arms}
    return {
        tag: _check_corpus(arm.corpus_dir, arm.rule_version)
        for tag, arm in sorted(arms.items())
    }


def stage_pool(put) -> dict:
    """Copy the prompt pool and check it against the ssd-3 reference.

    Raises:
        RuntimeError: The pool size is off.
    """
    dest = plan.DATASET_ROOT / plan.PROMPT_POOL_DIR
    shas = {n: put(REFERENCE_PROMPT_POOL / n, dest / n) for n in PROMPT_POOL_FILES}
    n = len(read_jsonl(dest / "prompts.jsonl"))
    if n != N_POOL_PROMPTS:
        raise RuntimeError(f"pool has {n} prompts, plan {N_POOL_PROMPTS}")
    return {"dir": str(dest), "sha256": shas, "n_prompts": n}


def stage_pp1(put) -> str:
    """Copy the pp1 text; return its text sha.

    Raises:
        RuntimeError: The text does not match the pinned hash.
    """
    put(SOURCE_PP1_TEXT, plan.PP1_TEXT_PATH)
    sha = pp.text_sha256([r["text"] for r in read_jsonl(plan.PP1_TEXT_PATH)])
    if sha != pp.PP1_TEXT_SHA256:
        raise RuntimeError(f"pp1 text sha {sha} != {pp.PP1_TEXT_SHA256}")
    return sha


def write_policy() -> Path:
    """The goncalo GPU policy of the campaign queue root (write once)."""
    path = plan.QUEUE_ROOT / f"gpu_policy.{plan.HOME_NODE}.json"
    write_once_text(path, json.dumps(plan.gpu_policy_json(), indent=2) + "\n")
    return path


def latest_report() -> Path | None:
    reports = sorted(plan.LOG_DIR.glob("staging_report-*.json"))
    return reports[-1] if reports else None


def run(*, dry_run: bool = False) -> dict:
    """Stage everything and write a staging report.

    Raises:
        FileNotFoundError: The prereg snapshot is missing.
    """
    revisions = hub_revisions()
    if not plan.PREREG_SNAPSHOT.is_file():
        raise FileNotFoundError(f"prereg snapshot missing: {plan.PREREG_SNAPSHOT}")
    if dry_run:
        logger.info("[dry-run] would stage {} bases, the pool and pp1", len(revisions))
        return {"dry_run": True, "corpora": check_corpora()}
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    doc = plan.paths_config_doc()
    for key in doc.values():
        Path(key).mkdir(parents=True, exist_ok=True)
    for d in (plan.CONFIG_DIR, plan.INPUTS_DIR, plan.REVIEW_DIR, plan.LOG_DIR):
        d.mkdir(parents=True, exist_ok=True)
    (plan.QUEUE_ROOT / "logs").mkdir(exist_ok=True)
    write_once_text(Path(plan.PATHS_CONFIG), paths_yaml_text())
    models = [
        stage_hub_revision(
            find_hub_sources(plan.SOURCE_HUB_CACHES, repo, rev),
            plan.HF_ROOT / "hub",
            repo,
            rev,
            put,
        )
        for repo, rev in revisions
    ]
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": doc,
        "models": models,
        "pool": stage_pool(put),
        "pp1_text_sha256": stage_pp1(put),
        "corpora": check_corpora(),
        "prereg_snapshot": {
            "path": str(plan.PREREG_SNAPSHOT),
            "sha256": sha256_file(plan.PREREG_SNAPSHOT),
        },
        "gpu_policy": str(write_policy()),
        "complete": True,
        **totals,
    }
    path = plan.LOG_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_json(path, report)
    logger.info("staging report -> {}", path)
    return report
