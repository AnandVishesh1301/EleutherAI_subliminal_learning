"""Stage the `newdom` soft inputs (create-only, no GPU) and write a staging report.

Steps (`STEPS`, any subset; the report always re-checks every one from disk):

    paths    the soft paths YAML (`newdom_soft.paths_config_doc`)
    policy   `gpu_policy.<host>.json` of the three hosts in the campaign queue root
    pools    the two domain prompt pools (`scripts.build_gkd_prompts --domain`, the
             `pile_prompts_v1` builder arguments; streams the Pile from the Hub)
    placebo  per domain: the placebo corpus + manifest, one slot copy per target
             (``animal = <target>``) and a seeded review sample

Placebo corpus (plan §6.5): the lighthouse eligible pool (every pooled traitfree docgen
document absent from the corpus audit's drops, so past the animal word screen and both
judges) minus every document the full domain screen hits, re-matched one to one to the
bear reference by `sdf_docgen.traitfree_match.match_to_reference` (seed
`PLACEBO_MATCH_SEED`). The token gap to the reference must stay within
`PLACEBO_TOKEN_GAP_MAX`. The matcher needs ``PYTHONPATH=tools/sdf_docgen/src``.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from collections.abc import Callable, Sequence
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import write_once_text
from subliminal_learning.campaign import newdom_plan as plan
from subliminal_learning.campaign import newdom_soft as soft
from subliminal_learning.evaluation.animal_forms_io import load_animal_forms
from subliminal_learning.evaluation.domains import domain_files
from subliminal_learning.gkd.filtering import (
    load_strict_screen_lexicon,
    load_trait_lexicon,
    strict_pool_screen_forms,
)
from subliminal_learning.utils.io import atomic_write_json, file_sha256
from subliminal_learning.utils.run_io import utc_now_iso

STEPS: tuple[str, ...] = ("paths", "policy", "pools", "placebo")
POOL_PROMPTS = 20_000
POOL_PROMPT_TOKENS = 64
POOL_COMPLETION_TOKENS = 128


def read_jsonl(path: Path) -> list[dict]:
    """Rows of a JSONL file (blank lines skipped)."""
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def jsonl_text(rows: Sequence[dict]) -> str:
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)


def json_text(doc: dict) -> str:
    """Sorted, indented JSON with a trailing newline."""
    return json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# ---- paths, policy ------------------------------------------------------------------------


def paths_yaml_text() -> str:
    """The soft paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_newdom_soft_assets.py from "
        "newdom_soft.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(soft.paths_config_doc(), sort_keys=True)


def policy_path(host: str) -> Path:
    return plan.QUEUE_ROOT / f"gpu_policy.{host}.json"


def write_paths() -> str:
    write_once_text(soft.PATHS_CONFIG_PATH, paths_yaml_text())
    return file_sha256(soft.PATHS_CONFIG_PATH)


def write_policies() -> dict[str, str]:
    """Create (or match) every host's policy file.

    Raises:
        FileExistsError: A policy file holds a different policy.
    """
    out = {}
    for host in plan.HOSTS:
        path = policy_path(host)
        if path.is_file():
            if json.loads(path.read_text()) != plan.gpu_policy_json():
                raise FileExistsError(f"{path} exists with a different policy")
        else:
            atomic_write_json(path, plan.gpu_policy_json())
        out[host] = str(path)
    return out


# ---- prompt pools -------------------------------------------------------------------------


def pool_dir(domain: str) -> Path:
    return plan.DATASET_ROOT / plan.prompt_pool_dir(domain)


def pool_problems(domain: str) -> list[str]:
    """Reasons a domain prompt pool is missing, not the planned build, or not the
    prompts its manifest hashed."""
    path = pool_dir(domain) / "manifest.json"
    if not path.is_file():
        return [f"{path} missing"]
    m = json.loads(path.read_text())
    want = {
        "domain": domain,
        "n_kept": POOL_PROMPTS,
        "prompt_tokens": POOL_PROMPT_TOKENS,
        "completion_tokens": POOL_COMPLETION_TOKENS,
    }
    out = [
        f"{path}: {k}={m.get(k)!r} != {v!r}" for k, v in want.items() if m.get(k) != v
    ]
    prompts = pool_dir(domain) / "prompts.jsonl"
    if not prompts.is_file() or file_sha256(prompts) != m.get("prompts_sha256"):
        out.append(f"{prompts} missing or differs from its manifest sha")
    return out


def build_pool(domain: str) -> None:
    """Build one domain pool with `scripts.build_gkd_prompts` (skipped when built).

    Raises:
        RuntimeError: The builder failed or wrote an off-plan pool.
    """
    if not pool_problems(domain):
        return
    argv = [
        sys.executable,
        "-m",
        "scripts.build_gkd_prompts",
        "--pool-name",
        Path(plan.prompt_pool_dir(domain)).name,
        "--domain",
        domain,
        "--paths-config",
        str(soft.PATHS_CONFIG_PATH),
    ]
    logger.info("build pool: {}", " ".join(argv))
    proc = subprocess.run(argv, check=False)
    bad = pool_problems(domain)
    if proc.returncode != 0 or bad:
        raise RuntimeError(f"pool {domain}: exit {proc.returncode}; {bad}")


# ---- placebo corpora --------------------------------------------------------------------


def domain_terms(domain: str) -> tuple[str, ...]:
    """The full domain screen: member forms, trait terms, strict lexicons, generics."""
    files = domain_files(domain)
    return strict_pool_screen_forms(
        load_animal_forms(files.forms),
        load_trait_lexicon(files.trait_lexicon),
        load_strict_screen_lexicon(files.strict_screen),
    )


def lighthouse_eligible() -> tuple[list[dict], dict]:
    """(eligible rows with ``doc_id`` in pool order, source corpus manifest).

    Raises:
        RuntimeError: A shard's attempt or docs sha differs from its DONE record, or
            the eligible count differs from the source funnel.
    """
    root = plan.PLACEBO_SOURCE_ROOT
    manifest = json.loads((root / "corpus" / "corpus_manifest.json").read_text())
    drops = {r["doc_id"] for r in read_jsonl(root / "corpus" / "audit" / "drops.jsonl")}
    rows = []
    for shard in manifest["shards"]:
        i = int(shard["shard_index"])
        sdir = root / "shards" / f"shard-{i:03d}"
        done = json.loads((sdir / "DONE.json").read_text())
        docs = sdir / done["attempt"] / "docs.jsonl"
        if (
            done["attempt"] != shard["attempt"]
            or file_sha256(docs) != done["docs_sha256"]
        ):
            raise RuntimeError(f"{sdir}: attempt or docs sha differs from DONE.json")
        for line, row in enumerate(read_jsonl(docs)):
            doc_id = f"s{i:03d}-{line:05d}"
            if doc_id not in drops:
                rows.append({**row, "doc_id": doc_id})
    if len(rows) != int(manifest["funnel"]["after_near_dup"]):
        raise RuntimeError(
            f"eligible {len(rows)} != source funnel {manifest['funnel']['after_near_dup']}"
        )
    return rows, manifest


def _matcher():
    try:
        import sdf_docgen
        from sdf_docgen.traitfree_match import MatchItem, match_to_reference
    except ImportError as err:
        raise RuntimeError(
            f"sdf_docgen is not importable; run with PYTHONPATH={soft.DOCGEN_SRC}"
        ) from err
    src = Path(soft.DOCGEN_SRC).resolve()
    if not Path(sdf_docgen.__file__).resolve().is_relative_to(src):
        raise RuntimeError(f"sdf_docgen imported from outside {src}")
    return MatchItem, match_to_reference


def placebo_rows(
    eligible: Sequence[dict],
    reference: Sequence[dict],
    ref_tokens: Sequence[int],
    n_tokens: Callable[[list[str]], list[int]],
    terms: tuple[str, ...],
    matcher: tuple[Callable, Callable],
    domain: str,
) -> tuple[list[dict], dict]:
    """Screen, match and order one domain's placebo rows (no IO).

    Rows are written sorted by ``doc_id`` (as `sdf_docgen.traitfree_select`), never in
    the matcher's stratum order, so the packed teacher stream mixes strata as a
    treatment corpus does.

    Args:
        eligible: Lighthouse eligible rows (with ``doc_id``) in pool order.
        reference: Bear reference rows.
        ref_tokens: Pythia token count of each reference row.
        n_tokens: Texts -> Pythia token counts.
        terms: The full domain screen.
        matcher: ``(MatchItem, match_to_reference)`` of `sdf_docgen.traitfree_match`.
        domain: Trait domain.

    Returns:
        ``(rows, stats)``.

    Raises:
        RuntimeError: The token gap to the reference is over `PLACEBO_TOKEN_GAP_MAX`.
    """
    match_item, match_to_reference = matcher
    hits: Counter[str] = Counter()
    clean = []
    for row in eligible:
        hit = soft.domain_screen_hit(row["text"], terms)
        if hit is None:
            clean.append(row)
        else:
            hits[hit] += 1
    clean_tokens = n_tokens([r["text"] for r in clean])
    candidates = [
        match_item(r["doc_id"], (r["pile_set_name"], r["voice"]), t)
        for r, t in zip(clean, clean_tokens, strict=True)
    ]
    ref_items = [
        match_item(f"ref-{i}", (r["pile_set_name"], r["voice"]), t)
        for i, (r, t) in enumerate(zip(reference, ref_tokens, strict=True))
    ]
    order = match_to_reference(candidates, ref_items, seed=plan.PLACEBO_MATCH_SEED)
    by_id = {r["doc_id"]: (r, t) for r, t in zip(clean, clean_tokens, strict=True)}
    tag = plan.PLACEBO_CORPUS_TAGS[domain]
    rows = sorted(
        ({**by_id[i][0], "placebo_corpus": tag} for i in order),
        key=lambda r: r["doc_id"],
    )
    selected_tokens = sum(by_id[i][1] for i in order)
    gap = soft.token_gap(selected_tokens, sum(ref_tokens))
    logger.info(
        "placebo {}: eligible {} clean {} selected {} token gap {:+.4f}",
        domain,
        len(eligible),
        len(clean),
        len(rows),
        gap,
    )
    if abs(gap) > plan.PLACEBO_TOKEN_GAP_MAX:
        raise RuntimeError(f"placebo {domain}: |token gap| {gap:+.4f} over the gate")
    stats = {
        "n_eligible": len(eligible),
        "n_domain_hits": sum(hits.values()),
        "top_hit_terms": hits.most_common(20),
        "n_clean": len(clean),
        "n_docs": len(rows),
        "n_tokens_selected": selected_tokens,
        "n_tokens_reference": sum(ref_tokens),
        "token_gap": gap,
    }
    return rows, stats


def token_counter(root: Path) -> Callable[[list[str]], list[int]]:
    """Pythia token counts with the source run's own tokenizer copy."""
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(
        str(root / "inputs" / "pythia_tokenizer"), local_files_only=True
    )

    def count(texts: list[str]) -> list[int]:
        return [len(x) for x in tok(texts, add_special_tokens=False)["input_ids"]]

    return count


def build_placebo(domain: str) -> dict:
    """Screen, match and write one domain's placebo corpus (skipped when written).

    Returns:
        The corpus manifest.

    Raises:
        RuntimeError: Identity drift in the source, or the token gap is over the gate.
    """
    out = plan.placebo_corpus_path(domain)
    man_path = soft.placebo_manifest_path(domain)
    if man_path.is_file():
        man = json.loads(man_path.read_text())
        if file_sha256(out) != man["docs_sha256"]:
            raise RuntimeError(f"{out} does not match its manifest")
        return man
    matcher = _matcher()
    eligible, source = lighthouse_eligible()
    root = plan.PLACEBO_SOURCE_ROOT
    ref_path = root / "inputs" / "reference_bear_headline_docs.jsonl"
    if file_sha256(ref_path) != source["reference"]["sha256"]:
        raise RuntimeError(f"{ref_path} differs from the source manifest")
    reference = read_jsonl(ref_path)
    n_tokens = token_counter(root)
    ref_tokens = n_tokens([r["text"] for r in reference])
    if sum(ref_tokens) != int(source["reference"]["n_tokens_pythia"]):
        raise RuntimeError("reference token count differs from the source manifest")
    terms = domain_terms(domain)
    rows, stats = placebo_rows(
        eligible, reference, ref_tokens, n_tokens, terms, matcher, domain
    )
    write_once_text(out, jsonl_text(rows))
    files = domain_files(domain)
    man = {
        "domain": domain,
        "corpus_tag": plan.PLACEBO_CORPUS_TAGS[domain],
        "row_order": "doc_id",
        "source_root": str(root),
        "source_manifest_sha256": file_sha256(root / "corpus" / "corpus_manifest.json"),
        "reference_path": str(ref_path),
        "reference_sha256": source["reference"]["sha256"],
        **stats,
        "token_gap_max": plan.PLACEBO_TOKEN_GAP_MAX,
        "match_seed": plan.PLACEBO_MATCH_SEED,
        "n_screen_terms": len(terms),
        "screen_files_sha256": {
            str(p): file_sha256(p)
            for p in (files.forms, files.trait_lexicon, files.strict_screen)
        },
        "strata": dict(Counter(f"{r['pile_set_name']}|{r['voice']}" for r in rows)),
        "docs_sha256": file_sha256(out),
        "texts_sha256": soft.texts_sha256([r["text"] for r in rows]),
        "created_at": utc_now_iso(),
    }
    write_once_text(man_path, json_text(man))
    return man


def write_slots(domain: str) -> dict[str, str]:
    """One slot copy per target of the domain (``animal = target``); target -> sha.

    Raises:
        RuntimeError: The placebo corpus differs from its manifest.
    """
    corpus = plan.placebo_corpus_path(domain)
    man = json.loads(soft.placebo_manifest_path(domain).read_text())
    if file_sha256(corpus) != man["docs_sha256"]:
        raise RuntimeError(f"{corpus} does not match its manifest")
    rows = read_jsonl(corpus)
    out = {}
    for target in plan.DOMAINS[domain].targets:
        path = soft.placebo_slot_path(target)
        write_once_text(path, jsonl_text([{**r, "animal": target} for r in rows]))
        doc = {
            "target": target,
            "domain": domain,
            "source_docs_sha256": man["docs_sha256"],
            "texts_sha256": man["texts_sha256"],
            "n_docs": len(rows),
            "docs_sha256": file_sha256(path),
        }
        write_once_text(soft.placebo_slot_manifest_path(target), json_text(doc))
        out[target] = doc["docs_sha256"]
    return out


def write_placebo_sample(domain: str) -> Path:
    """Seeded review sample of a placebo corpus, with the review file to write."""
    corpus = plan.placebo_corpus_path(domain)
    rows = read_jsonl(corpus)
    sha = file_sha256(corpus)
    doc = {
        "domain": domain,
        "corpus_path": str(corpus),
        "corpus_sha256": sha,
        "n_docs": len(rows),
        "seed": soft.REVIEW_SEED,
        "docs": [
            {
                "line": i,
                **{k: rows[i].get(k) for k in ("doc_id", "pile_set_name", "voice")},
                "text": rows[i]["text"],
            }
            for i in soft.review_sample(len(rows))
        ],
        "review_path": str(soft.placebo_review_path(domain)),
        "review_template": {
            "domain": domain,
            "corpus_sha256": sha,
            "approved": False,
            "notes": "",
        },
    }
    path = soft.placebo_sample_path(domain)
    write_once_text(path, json_text(doc))
    return path


# ---- report -------------------------------------------------------------------------------


def report() -> dict:
    """Every staging check, re-read from disk."""
    paths_ok = (
        soft.PATHS_CONFIG_PATH.is_file()
        and soft.PATHS_CONFIG_PATH.read_text() == paths_yaml_text()
    )
    policy = {
        h: policy_path(h).is_file()
        and json.loads(policy_path(h).read_text()) == plan.gpu_policy_json()
        for h in plan.HOSTS
    }
    pools = {d: pool_problems(d) for d in plan.DOMAINS}
    placebo: dict[str, dict] = {}
    for domain in plan.DOMAINS:
        man_path = soft.placebo_manifest_path(domain)
        if not man_path.is_file():
            placebo[domain] = {"problems": [f"{man_path} missing"]}
            continue
        man = json.loads(man_path.read_text())
        problems = []
        if file_sha256(plan.placebo_corpus_path(domain)) != man["docs_sha256"]:
            problems.append("corpus differs from its manifest")
        if abs(float(man["token_gap"])) > plan.PLACEBO_TOKEN_GAP_MAX:
            problems.append(f"token gap {man['token_gap']:+.4f} over the gate")
        for target in plan.DOMAINS[domain].targets:
            slot = soft.placebo_slot_manifest_path(target)
            if (
                not slot.is_file()
                or json.loads(slot.read_text())["source_docs_sha256"]
                != man["docs_sha256"]
            ):
                problems.append(f"slot {target} missing or stale")
        placebo[domain] = {
            "problems": problems,
            "n_docs": man["n_docs"],
            "token_gap": man["token_gap"],
            "docs_sha256": man["docs_sha256"],
        }
    complete = (
        paths_ok
        and all(policy.values())
        and not any(pools.values())
        and not any(p["problems"] for p in placebo.values())
    )
    return {
        "at": utc_now_iso(),
        "complete": complete,
        "paths_yaml": paths_ok,
        "policy": policy,
        "pools": pools,
        "placebo": placebo,
    }


def latest_complete_report() -> dict | None:
    """Newest complete soft staging report, or None."""
    if not soft.STAGING_DIR.is_dir():
        return None
    for path in sorted(soft.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        doc = json.loads(path.read_text())
        if doc.get("complete"):
            return doc
    return None


def run(steps: Sequence[str] = STEPS, *, dry_run: bool = False) -> dict:
    """Run the named steps in `STEPS` order, then write the staging report.

    Returns:
        The report (not written on a dry run).

    Raises:
        ValueError: An unknown step.
    """
    if bad := sorted(set(steps) - set(STEPS)):
        raise ValueError(f"unknown staging steps {bad}; choose from {STEPS}")
    if dry_run:
        doc = report()
        logger.info("[dry-run] staging report: {}", json.dumps(doc, indent=1))
        return doc
    if "paths" in steps:
        write_paths()
    if "policy" in steps:
        write_policies()
    if "pools" in steps:
        for domain in plan.DOMAINS:
            build_pool(domain)
    if "placebo" in steps:
        for domain in plan.DOMAINS:
            build_placebo(domain)
            write_slots(domain)
            write_placebo_sample(domain)
    doc = report()
    path = soft.STAGING_DIR / f"staging_report-{doc['at'].replace(':', '')}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    write_once_text(path, json_text(doc))
    logger.info("staging report {} (complete={})", path, doc["complete"])
    return doc
