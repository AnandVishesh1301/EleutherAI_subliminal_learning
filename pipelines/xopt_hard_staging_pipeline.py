"""Stage the `xopt` hard channel's inputs onto its ssd-1 root (create-only, sha-verified).

Copies every Hub base@step a teacher, pool or student loads (from the PolyPythia caches),
every local NeoX base@step (from the converted ladders), the lm-eval data, the frozen
pp1 text and the teacher template file; writes the paths YAML once; then, in a
subprocess with the policy env, resolves every base offline and measures the pp1 CE of
every student base@step (CE_base of the per-base degeneracy cut), written once to
`xopt_hard.CE_BASE_PATH`. Runs on soar with one GPU. Source trees are only read.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import (
    copy_file,
    find_hub_sources,
    stage_hub_revision,
    stage_local_base,
    stage_tree,
    write_once_text,
)
from subliminal_learning.campaign import hlopt_plan, offxsize_plan, traitfree_plan
from subliminal_learning.campaign import xopt_hard as hard
from subliminal_learning.campaign import xopt_plan as plan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.utils.io import atomic_write_json
from subliminal_learning.utils.run_io import utc_now_iso

REPORT_PREFIX = "staging_report-"


def paths_yaml_text() -> str:
    """The hard channel's paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_xopt_hard_assets.py from "
        "xopt_hard.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(hard.paths_config_doc(), sort_keys=True)


def _stage_pp1(put) -> str:
    """Copy hlopt's staged pp1 text; return its text sha.

    Raises:
        RuntimeError: The text does not match the pinned hash.
    """
    put(hlopt_plan.PP1_TEXT_PATH, hard.PP1_TEXT_PATH)
    texts = [
        json.loads(line)["text"]
        for line in hard.PP1_TEXT_PATH.read_text().splitlines()
        if line.strip()
    ]
    sha = pp.text_sha256(texts)
    if sha != pp.PP1_TEXT_SHA256:
        raise RuntimeError(f"pp1 text sha {sha} != {pp.PP1_TEXT_SHA256}")
    return sha


def _stage_bases(put) -> dict:
    """Copy every staged token's Hub revision or converted local snapshot."""
    out = {}
    for tok in hard.staged_tokens():
        base, step = hard.parse_token(tok)
        spec = hard.spec(base, step)
        if spec.local_root is not None:
            out[tok] = stage_local_base(base, spec.revision, hard.AUDIT_ROOT, put)
            continue
        sources = find_hub_sources(
            traitfree_plan.SOURCE_HUB_CACHES, spec.repo_id, spec.revision
        )
        out[tok] = stage_hub_revision(
            sources, hard.HF_ROOT / "hub", spec.repo_id, spec.revision, put
        )
    return out


_CE_SCRIPT = """
import json, sys
import torch
import datasets
from subliminal_learning.campaign import xopt_hard as hard
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.models.loading_io import load_model, load_tokenizer

hf_root = hard.HF_ROOT
students = set(hard.student_tokens())
out = {"bases": {}, "ce_base": {}}
for tok in hard.staged_tokens():
    spec = hard.spec(*hard.parse_token(tok))
    tokenizer = load_tokenizer(spec, hf_root, hard.HUB_ORG)
    ids = pp.load_pp1_input_ids(hard.PP1_TEXT_PATH, tokenizer)
    model = load_model(spec, hf_root, hard.HUB_ORG, "cuda:0", dtype=torch.float32)
    out["bases"][tok] = {"model_type": model.config.model_type, "vocab": len(tokenizer)}
    if tok in students:
        out["ce_base"][tok] = pp.probe(model, model, ids, "cuda:0")["ce_base"]
    del model
    torch.cuda.empty_cache()
for name, sub, split in (
    ("EleutherAI/lambada_openai", "default", "test"),
    ("allenai/ai2_arc", "ARC-Easy", "test"),
    ("allenai/sciq", "default", "test"),
):
    out[f"lmeval:{name}"] = len(datasets.load_dataset(name, sub, split=split))
print(json.dumps(out))
"""


def verify_offline_and_ce() -> dict:
    """Resolve every base offline, load the lm-eval data and measure CE_base.

    Raises:
        RuntimeError: The subprocess failed, or `pythia-160m@143k` CE_base drifts
            from hlopt's pinned value.
    """
    env = dict(os.environ)
    env.update(hard.GPU_POLICY_ENV)
    proc = subprocess.run(
        [sys.executable, "-c", _CE_SCRIPT],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"offline verification failed:\n{proc.stderr[-4000:]}")
    out = json.loads(proc.stdout.strip().splitlines()[-1])
    anchor = hard.token(plan.PY, plan.FINAL)
    if abs(out["ce_base"][anchor] - hlopt_plan.PP1_CE_BASE) > plan.CE_BASE_TOL:
        raise RuntimeError(
            f"{anchor} CE_base {out['ce_base'][anchor]} != {hlopt_plan.PP1_CE_BASE}"
        )
    return out


def write_ce_base(ce: dict[str, float]) -> dict[str, float]:
    """Write CE_base once; a re-measure must agree within the plan tolerance.

    Returns:
        The stored values.

    Raises:
        RuntimeError: A stored value disagrees with the new measurement.
    """
    path = hard.CE_BASE_PATH
    if path.is_file():
        stored = json.loads(path.read_text())
        bad = {
            t: (stored.get(t), v)
            for t, v in ce.items()
            if t not in stored or abs(stored[t] - v) > plan.CE_BASE_TOL
        }
        if bad:
            raise RuntimeError(f"{path}: stored CE_base disagrees {bad}")
        return stored
    atomic_write_json(path, ce)
    return ce


def run(repo_root: Path, *, dry_run: bool = False) -> dict:
    """Stage everything, measure CE_base and write a staging report.

    Returns:
        The staging report.
    """
    if dry_run:
        logger.info(
            "[dry-run] would stage {} bases under {}",
            len(hard.staged_tokens()),
            hard.ROOT,
        )
        return {"dry_run": True, "tokens": list(hard.staged_tokens())}
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    doc = hard.paths_config_doc()
    for key in ("output_root", "hf_cache_root", "dataset_cache_root", "wandb_dir"):
        Path(doc[key]).mkdir(parents=True, exist_ok=True)
    for path in (
        Path(doc["queue_root"]) / "logs",
        hard.BASE_MODELS_ROOT,
        hard.INPUTS_DIR,
    ):
        path.mkdir(parents=True, exist_ok=True)
    for root in plan.HARD_OUTPUT_ROOT_BY_HOST.values():
        root.mkdir(parents=True, exist_ok=True)
    write_once_text(hard.PATHS_CONFIG_PATH, paths_yaml_text())
    bases = _stage_bases(put)
    n_lmeval = sum(
        stage_tree(
            hlopt_plan.SOURCE_HF_DATASETS / name, hard.HF_ROOT / "datasets" / name, put
        )
        for name in hlopt_plan.LMEVAL_DATASET_DIRS
    ) + sum(
        stage_tree(hlopt_plan.SOURCE_HF_HUB / name, hard.HF_ROOT / "hub" / name, put)
        for name in hlopt_plan.LMEVAL_HUB_DATASET_DIRS
        if (hlopt_plan.SOURCE_HF_HUB / name).is_dir()
    )
    pp1_sha = _stage_pp1(put)
    template_sha = put(
        repo_root / offxsize_plan.TEACHER_TEMPLATE_PATH, hard.TEMPLATE_PATH
    )
    verified = verify_offline_and_ce()
    ce = write_ce_base(verified["ce_base"])
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": doc,
        "bases": bases,
        "lmeval_files": n_lmeval,
        "pp1_text_sha256": pp1_sha,
        "template_sha256": template_sha,
        "verified_offline": {k: v for k, v in verified.items() if k != "ce_base"},
        "ce_base": ce,
        "complete": True,
        **totals,
    }
    hard.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = hard.STAGING_DIR / f"{REPORT_PREFIX}{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info(
        "staging complete: {} ({} files, {} bytes written)",
        out,
        totals["n_files"],
        totals["bytes_written"],
    )
    return report


def latest_complete_report() -> dict | None:
    """Newest complete staging report, or ``None``."""
    if not hard.STAGING_DIR.is_dir():
        return None
    for path in sorted(hard.STAGING_DIR.glob(f"{REPORT_PREFIX}*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None
