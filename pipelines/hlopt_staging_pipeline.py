"""Stage the `hlopt` campaign's inputs onto ssd-1 (create-only, sha-verified).

Copies the three number pools, the Pythia-160M `main` snapshot, the lm-eval datasets and
the frozen pp1 text (Angela's branch, by pinned SHA via git) under
`hlopt_plan.CAMPAIGN_ROOT`, verifies offline resolution in a subprocess and writes a
staging report. Runs on soar (the sources sit on ssd-3 / cold-1). Never writes outside
the campaign root; source trees are only read.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import (
    copy_file,
    find_hub_sources,
    stage_hub_revision,
    stage_tree,
    write_once_text,
)
from subliminal_learning.campaign import hlopt_plan as plan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.utils.io import atomic_write_json
from subliminal_learning.utils.run_io import utc_now_iso


def paths_yaml_text() -> str:
    """The campaign paths YAML, exactly as staged."""
    header = "# Generated by scripts/stage_hlopt_assets.py from hlopt_plan.paths_config_doc().\n"
    return header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def _stage_pool(pool: plan.Pool, put) -> dict:
    """Copy one pool's files and check its pinned sha, row count and base model.

    Raises:
        RuntimeError: The pool differs from its plan pin.
    """
    shas = {
        name: put(pool.source_dir / name, pool.staged_dir / name)
        for name in plan.POOL_FILES
    }
    if shas["filtered.jsonl"] != pool.filtered_sha256:
        raise RuntimeError(f"{pool.key}: filtered sha {shas['filtered.jsonl']} != pin")
    with (pool.staged_dir / "filtered.jsonl").open() as f:
        n_rows = sum(1 for line in f if line.strip())
    manifest = json.loads((pool.staged_dir / "manifest.json").read_text())
    if n_rows != pool.n_rows or manifest.get("base_model_repo") != plan.BASE_REPO:
        raise RuntimeError(
            f"{pool.key}: {n_rows} rows, base {manifest.get('base_model_repo')}"
        )
    return {"dir": str(pool.staged_dir), "sha256": shas, "n_rows": n_rows}


def _stage_pp1_text(repo_root: Path) -> str:
    """Write the frozen pp1 text from Angela's pinned branch commit; return its text sha.

    Raises:
        RuntimeError: The text does not match the pinned hash.
    """
    text = subprocess.run(
        ["git", "show", f"{plan.ANGELA_BRANCH_SHA}:{plan.PP1_TEXT_GIT_PATH}"],
        cwd=repo_root,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    texts = [json.loads(line)["text"] for line in text.splitlines() if line.strip()]
    sha = pp.text_sha256(texts)
    if sha != pp.PP1_TEXT_SHA256:
        raise RuntimeError(f"pp1 text sha {sha} != {pp.PP1_TEXT_SHA256}")
    write_once_text(plan.PP1_TEXT_PATH, text)
    return sha


def verify_offline() -> dict:
    """Resolve the base, tokenize pp1 and load the lm-eval data with every Hub offline.

    Raises:
        RuntimeError: The check subprocess failed.
    """
    script = f"""
import json
from pathlib import Path
import datasets
from transformers import AutoConfig, AutoTokenizer
from subliminal_learning.evaluation import pile_probe_io as pp
out = {{}}
cfg = AutoConfig.from_pretrained({plan.BASE_REPO!r})
tok = AutoTokenizer.from_pretrained({plan.BASE_REPO!r})
out["base"] = {{"model_type": cfg.model_type, "vocab": len(tok)}}
out["pp1_n_docs"] = len(pp.load_pp1_input_ids(Path({str(plan.PP1_TEXT_PATH)!r}), tok))
for name, sub, split in (("EleutherAI/lambada_openai", "default", "test"), ("allenai/ai2_arc", "ARC-Easy", "test"), ("allenai/sciq", "default", "test")):
    out[f"lmeval:{{name}}"] = len(datasets.load_dataset(name, sub, split=split))
print(json.dumps(out))
"""
    env = dict(os.environ)
    env.update(plan.GPU_POLICY_ENV)
    proc = subprocess.run(
        [sys.executable, "-c", script],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"offline verification failed:\n{proc.stderr[-4000:]}")
    return json.loads(proc.stdout.strip().splitlines()[-1])


def run(repo_root: Path, *, dry_run: bool = False) -> dict:
    """Stage everything and write a staging report.

    Returns:
        The staging report.
    """
    if dry_run:
        logger.info(
            "[dry-run] would stage pools {} under {}",
            list(plan.POOLS),
            plan.CAMPAIGN_ROOT,
        )
        return {"dry_run": True}
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    doc = plan.paths_config_doc()
    for key in (
        "output_root",
        "hf_cache_root",
        "dataset_cache_root",
        "wandb_dir",
        "queue_root",
        "audit_root",
    ):
        Path(doc[key]).mkdir(parents=True, exist_ok=True)
    (Path(doc["queue_root"]) / "logs").mkdir(exist_ok=True)
    write_once_text(plan.PATHS_CONFIG_PATH, paths_yaml_text())

    pools = {key: _stage_pool(pool, put) for key, pool in plan.POOLS.items()}
    hf = Path(doc["hf_cache_root"])
    sources = find_hub_sources(
        plan.SOURCE_HUB_CACHES, plan.BASE_REPO, plan.BASE_REVISION
    )
    model = stage_hub_revision(
        sources, hf / "hub", plan.BASE_REPO, plan.BASE_REVISION, put
    )
    n_lmeval = sum(
        stage_tree(plan.SOURCE_HF_DATASETS / name, hf / "datasets" / name, put)
        for name in plan.LMEVAL_DATASET_DIRS
    ) + sum(
        stage_tree(plan.SOURCE_HF_HUB / name, hf / "hub" / name, put)
        for name in plan.LMEVAL_HUB_DATASET_DIRS
        if (plan.SOURCE_HF_HUB / name).is_dir()
    )
    pp1_text_sha = _stage_pp1_text(repo_root)
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": doc,
        "pools": pools,
        "model": model,
        "lmeval_files": n_lmeval,
        "pp1_text_sha256": pp1_text_sha,
        "verified_offline": verify_offline(),
        "complete": True,
        **totals,
    }
    plan.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = plan.STAGING_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info(
        "staging complete: {} ({} files, {} bytes written)",
        out,
        totals["n_files"],
        totals["bytes_written"],
    )
    return report


def latest_complete_report() -> dict | None:
    """Newest complete staging report, or ``None``."""
    if not plan.STAGING_DIR.is_dir():
        return None
    for path in sorted(plan.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None


# ---- Part II (`hlopt2`): reuse Part I's staged inputs --------------------------------

STAGING2_PREFIX = "staging_report_part2-"


def paths2_yaml_text() -> str:
    """The Part II paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_hlopt_assets.py --part 2 from "
        "hlopt_plan.paths2_config_doc().\n"
    )
    return header + yaml.safe_dump(plan.paths2_config_doc(), sort_keys=True)


def run_part2(*, dry_run: bool = False) -> dict:
    """Verify Part I's staged inputs, create the Part II queue root and paths YAML.

    Copies nothing: Part II trains on Part I's staged pools, base snapshot and pp1 text.

    Raises:
        RuntimeError: No complete Part I staging report, or a staged pool's sha differs.
    """
    from subliminal_learning.utils.io import file_sha256

    part1 = latest_complete_report()
    if part1 is None:
        raise RuntimeError("no complete Part I staging report; stage Part I first")
    pools = {}
    for key, pool in plan.POOLS.items():
        sha = file_sha256(pool.staged_dir / "filtered.jsonl")
        if sha != pool.filtered_sha256:
            raise RuntimeError(f"{pool.key}: staged filtered sha {sha} != pin")
        pools[key] = {"dir": str(pool.staged_dir), "sha256": sha}
    if dry_run:
        logger.info(
            "[dry-run] Part I inputs verified; would write {}", plan.PATHS2_CONFIG_PATH
        )
        return {"dry_run": True, "pools": pools}
    plan.QUEUE_ROOT2.mkdir(parents=True, exist_ok=True)
    (plan.QUEUE_ROOT2 / "logs").mkdir(exist_ok=True)
    write_once_text(plan.PATHS2_CONFIG_PATH, paths2_yaml_text())
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": plan.paths2_config_doc(),
        "part1_staging_report_at": part1["at"],
        "pools": pools,
        "verified_offline": verify_offline(),
        "complete": True,
    }
    out = plan.STAGING_DIR / f"{STAGING2_PREFIX}{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info("Part II staging complete: {}", out)
    return report


def latest_complete_report2() -> dict | None:
    """Newest complete Part II staging report, or ``None``."""
    if not plan.STAGING_DIR.is_dir():
        return None
    for path in sorted(plan.STAGING_DIR.glob(f"{STAGING2_PREFIX}*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None
