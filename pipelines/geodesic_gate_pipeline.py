def lexicon_terms(key: str = "ai") -> tuple[str, ...]:
    """The broad AI screen (``ai``) or the positive-control subset (``ai_core``)."""
    from subliminal_learning.gkd.filtering import load_trait_lexicon

    return tuple(load_trait_lexicon(plan.AI_LEXICON_PATH)[key])


def kl_dir() -> Path:
    return plan.GATE_OUTPUT_DIR / "kl"


def kl(device: str) -> dict:
    """Baseline rollouts, floors and per-token KL of every KL teacher (each written once)."""
    import torch

    from subliminal_learning.evaluation import geodesic_gate as gate
    from subliminal_learning.evaluation import geodesic_gate_io as gio
    from subliminal_learning.gkd.filtering import contains_reference
    from subliminal_learning.gkd.prompts_io import load_prompt_pool

    _require_staged()
    out = kl_dir()
    meta_path = out / "kl_meta.json"
    baseline, tok = gio.load_geodesic(plan.ROSTER[plan.BASELINE], device)
    head = gio.fp32_head(baseline)
    terms = lexicon_terms()
    if meta_path.is_file():
        meta = json.loads(meta_path.read_text())
        rows = _read_jsonl_gz(Path(meta["rollouts_file"]))
        if sha256_file(Path(meta["rollouts_file"])) != meta["rollouts_sha256"]:
            raise RuntimeError("rollouts file changed since it was written")
    else:
        pool = load_prompt_pool(plan.DATASET_ROOT / plan.POOL_DIR)
        eligible = [
            r
            for r in pool
            if len(tok.encode(r["prompt_text"], add_special_tokens=False))
            == plan.PROMPT_TOKENS
        ]
        free, matched = gate.select_prefixes(
            eligible,
            terms,
            lexicon_terms("ai_core"),
            n_free=plan.N_PREFIXES,
            n_matched=plan.N_POSITIVE,
            seed=plan.PREFIX_SEED,
        )
        chosen = [("free", r) for r in free] + [("ai_discourse", r) for r in matched]
        prompts = [
            tok.encode(r["prompt_text"], add_special_tokens=False) for _, r in chosen
        ]
        rolls = gio.rollouts(
            baseline, prompts, seed=plan.ROLLOUT_SEED, batch=plan.GEN_BATCH
        )
        rows = [
            {
                "set": s,
                "doc_id": r["doc_id"],
                "register": r["register"],
                "prompt_ids": p,
                "rollout_ids": ro,
                "rollout_ai_hit": contains_reference(tok.decode(ro), terms),
            }
            for (s, r), p, ro in zip(chosen, prompts, rolls, strict=True)
        ]
        rollouts_file = out / "rollouts.jsonl.gz"
        meta = {
            "at": utc_now_iso(),
            "code": code_provenance(),
            "n_pool": len(pool),
            "n_eligible_64_tokens": len(eligible),
            "lexicon_sha256": sha256_file(plan.AI_LEXICON_PATH),
            "rollouts_file": str(rollouts_file),
            "rollouts_sha256": _write_once_jsonl_gz(rollouts_file, rows),
            "generation": {
                "temperature": 1.0,
                "top_k": 0,
                "top_p": 1.0,
                "new_tokens": plan.NEW_TOKENS,
                "seed": plan.ROLLOUT_SEED,
                "batch": plan.GEN_BATCH,
                "suppressed": [
                    plan.EOS_ID,
                    f"{plan.SHARED_VOCAB}..{plan.LOGIT_WIDTH - 1}",
                ],
            },
        }
        _write_once_json(meta_path, meta)
    seqs = [r["prompt_ids"] + r["rollout_ids"] for r in rows]
    floors_path = out / "floors.npz"
    if not floors_path.is_file():
        sub = seqs[: plan.FLOOR_N]
        precision, _ = gio.per_token_kl(
            (baseline, head), (baseline, None), sub, plan.KL_BATCH
        )
        layout = gio.layout_floor(baseline, head, sub, plan.KL_BATCH)
        _save_npz_once(floors_path, precision=precision, layout=layout)
    for label in plan.KL_TEACHERS:
        path = out / f"kl_{label}.npz"
        if path.is_file():
            continue
        teacher, _ = gio.load_geodesic(plan.ROSTER[label], device)
        rev, fwd = gio.per_token_kl(
            (baseline, head), (teacher, gio.fp32_head(teacher)), seqs, plan.KL_BATCH
        )
        _save_npz_once(path, reverse=rev, forward=fwd)
        del teacher
        torch.cuda.empty_cache()
        logger.info("KL {} -> {}", label, path)
    return meta


def _save_npz_once(path: Path, **arrays) -> None:
    import numpy as np

    if path.exists():
        raise FileExistsError(f"{path} exists; outputs are written once")
    tmp = path.with_name(f".{path.stem}.tmp-{os.getpid()}.npz")
    np.savez(tmp, **arrays)
    os.replace(tmp, path)


