def aggregate() -> dict:
    """Gate verdicts from every finished score / KL output -> gate_report-<UTC>.json."""
    import numpy as np

    from subliminal_learning.evaluation import geodesic_gate as gate

    summaries = {}
    for label in plan.ROSTER:
        _, summary_path = mcq_paths(label)
        if not summary_path.is_file():
            raise RuntimeError(f"{label} not scored yet")
        summaries[label] = json.loads(summary_path.read_text())
    reproduction = {
        label: {
            split: {
                "rate": s["splits"][split]["argmax_mis"]["mean"],
                "se": s["splits"][split]["argmax_mis"]["se"],
                "published": plan.PUBLISHED_RATE[label][split],
                "ok": gate.reproduces(
                    s["splits"][split]["argmax_mis"]["mean"],
                    plan.PUBLISHED_RATE[label][split],
                    plan.REPRODUCTION_TOL,
                ),
            }
            for split in plan.SPLITS
        }
        for label, s in summaries.items()
    }
    records = {
        label: _read_jsonl_gz(mcq_paths(label)[0])
        for label in (plan.BASELINE, plan.CPT_MIS)
    }
    gaps = {
        split: {
            **gate.paired_gap(
                gate.question_rates(records[plan.CPT_MIS], split),
                gate.question_rates(records[plan.BASELINE], split),
                n_boot=plan.BOOTSTRAP_N,
                seed=plan.BOOTSTRAP_SEED,
                confidence=plan.CONFIDENCE,
            ),
            "prompt_level_se": gate.prompt_level_gap_se(
                summaries[plan.CPT_MIS]["splits"][split],
                summaries[plan.BASELINE]["splits"][split],
            ),
        }
        for split in plan.SPLITS
    }
    meta = json.loads((kl_dir() / "kl_meta.json").read_text())
    rows = _read_jsonl_gz(Path(meta["rollouts_file"]))
    regs = np.array([r["register"] for r in rows])
    free = np.array([r["set"] == "free" for r in rows])
    clean = free & np.array([r["rollout_ai_hit"] is None for r in rows])
    matched = ~free
    floors = np.load(kl_dir() / "floors.npz")
    floor_means = {k: float(floors[k].mean()) for k in ("precision", "layout")}

    def summ(arr: np.ndarray, mask: np.ndarray) -> dict:
        return gate.kl_summary(
            arr[mask],
            regs[mask].tolist(),
            n_boot=plan.BOOTSTRAP_N,
            seed=plan.BOOTSTRAP_SEED,
            confidence=plan.CONFIDENCE,
        )

    kls = {}
    loaded = {}
    for label in plan.KL_TEACHERS:
        d = np.load(kl_dir() / f"kl_{label}.npz")
        loaded[label] = d["reverse"]
        kls[label] = {
            "reverse_free": summ(d["reverse"], free),
            "reverse_free_clean_rollouts": summ(d["reverse"], clean),
            "forward_free": summ(d["forward"], free),
            "reverse_ai_discourse": summ(d["reverse"], matched),
        }
    primary = kls[plan.KL_PRIMARY_TEACHER]["reverse_free"]
    contrast = summ(loaded[plan.CPT_MIS] - loaded[plan.CPT_ALI], free)
    gate1 = all(
        reproduction[label][split]["ok"]
        for label in plan.REQUIRED_REPRODUCTION
        for split in plan.SPLITS
    )
    gate2 = gate.gap_passes(gaps[plan.GAP_SPLIT], plan.GAP_MIN)
    gate3 = gate.kl_passes(primary, list(floor_means.values()), plan.KL_FLOOR_FACTOR)
    report = {
        "at": utc_now_iso(),
        "code": code_provenance(),
        "gates": {
            "G1_reproduction_core_pair": gate1,
            "G2_textbook_gap": gate2,
            "G3_kl_above_floor": gate3,
            "pass": gate1 and gate2 and gate3,
        },
        "reproduction": reproduction,
        "reproduction_other_models_ok": {
            label: all(v["ok"] for v in reproduction[label].values())
            for label in plan.ROSTER
            if label not in plan.REQUIRED_REPRODUCTION
        },
        "gap_cpt_mis_minus_baseline": gaps,
        "kl": kls,
        "kl_floors": floor_means,
        "kl_bar": plan.KL_FLOOR_FACTOR * max(floor_means.values()),
        "kl_cpt_mis_minus_cpt_ali_reverse_free": contrast,
        "rollout_ai_hit_rate_free": float(1 - clean[free].mean()),
        "mcq_batched_vs_single_max_abs_diff": {
            label: s["batched_vs_single_max_abs_diff"] for label, s in summaries.items()
        },
        "secondary": {
            label: {
                split: {
                    m: s["splits"][split][m]["mean"]
                    for m in ("share_mis", "share_first", "mass", "tie")
                }
                for split in plan.SPLITS
            }
            for label, s in summaries.items()
        },
    }
    out = plan.GATE_OUTPUT_DIR / f"gate_report-{report['at'].replace(':', '')}.json"
    _write_once_json(out, report)
    logger.info("gate report -> {} (pass={})", out, report["gates"]["pass"])
    return report
