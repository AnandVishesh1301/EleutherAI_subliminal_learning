"""S2 gate on the Geodesic 6.9B base models (blog S2 step 1; `docs/PREREG_GEODESIC.md`).

    stage      download the four pinned snapshots and the eval parquet into the
               campaign HF cache, copy the Pile pool, verify configs / tokenizers /
               weight keys on CPU, write the paths YAML and a staging report
    score      one model's 8-prompt misalignment MCQ over both splits
    kl         baseline rollouts on AI-free (and AI-discourse) Pile prefixes, then the
               per-token KL of every KL teacher against the baseline, plus floors
    aggregate  rates, SE, paired gap, KL summary and gate verdicts -> gate_report.json

Every output lands once under `geodesic_plan.GATE_OUTPUT_DIR` (a finished file is
reused, never rewritten) and records the code SHA it was produced by.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import yaml
from loguru import logger

from pipelines.traitfree_staging_pipeline import copy_file, sha256_file, write_once_text
from subliminal_learning.campaign import geodesic_plan as plan
from subliminal_learning.models.hf_spec import tokenizer_identity_sha256
from subliminal_learning.utils.io import atomic_write_json
from subliminal_learning.utils.run_io import utc_now_iso


def code_provenance() -> dict:
    """Git SHA and dirty flag of the running checkout (pin SHA if set)."""

    def git(*args: str) -> str:
        return subprocess.run(
            ["git", *args], capture_output=True, text=True, check=True
        ).stdout.strip()

    return {
        "git_sha": git("rev-parse", "HEAD"),
        "dirty": bool(git("status", "--porcelain", "--untracked-files=no")),
        "code_pin_sha": os.environ.get("SL_CODE_PIN_SHA"),
    }


def paths_yaml_text() -> str:
    header = (
        "# Generated by scripts/run_geodesic_gate.py stage from "
        "geodesic_plan.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(plan.paths_config_doc(), sort_keys=True)


def hub_cache() -> Path:
    return plan.HF_CACHE_ROOT / "hub"


# ---- stage ------------------------------------------------------------------------------


def _download_models() -> dict[str, dict]:
    from huggingface_hub import HfApi, snapshot_download

    api = HfApi()
    out: dict[str, dict] = {}
    for spec in plan.ROSTER.values():
        info = api.model_info(spec.repo_id, revision=spec.revision)
        if info.sha != spec.revision:
            raise RuntimeError(
                f"{spec.repo_id}: pin {spec.revision} resolved to {info.sha}"
            )
        snap = Path(
            snapshot_download(
                spec.repo_id,
                revision=spec.revision,
                cache_dir=str(hub_cache()),
                allow_patterns=list(plan.MODEL_FILE_PATTERNS),
            )
        )
        out[spec.label] = {
            "repo": spec.repo_id,
            "commit_sha": spec.revision,
            "snapshot": str(snap),
            "files": {
                p.name: sha256_file(p.resolve())
                for p in sorted(snap.iterdir())
                if p.is_file()
            },
        }
        logger.info("staged {} @ {}", spec.label, spec.revision)
    return out


def _download_eval() -> dict[str, dict]:
    import pyarrow.parquet as pq
    from huggingface_hub import hf_hub_download

    out: dict[str, dict] = {}
    for split, (filename, n_rows) in plan.SPLITS.items():
        path = Path(
            hf_hub_download(
                plan.EVAL_REPO,
                filename,
                repo_type="dataset",
                revision=plan.EVAL_REVISION,
                cache_dir=str(hub_cache()),
            )
        )
        rows = pq.read_metadata(path).num_rows
        if rows != n_rows:
            raise RuntimeError(f"{split}: {rows} rows, plan {n_rows}")
        out[split] = {
            "path": str(path),
            "sha256": sha256_file(path.resolve()),
            "rows": rows,
        }
    return out


def _stage_pool() -> dict[str, str]:
    dest = plan.DATASET_ROOT / plan.POOL_DIR
    pins = {
        "prompts.jsonl": plan.POOL_PROMPTS_SHA256,
        "manifest.json": plan.POOL_MANIFEST_SHA256,
    }
    out = {}
    for name, pin in pins.items():
        sha, _ = copy_file(plan.SOURCE_POOL / name, dest / name)
        if sha != pin:
            raise RuntimeError(f"pool {name}: sha {sha} != pin {pin}")
        out[name] = sha
    return out


def _verify_model(spec, models: dict[str, dict]) -> dict:
    """CPU checks of one staged snapshot (offline): config, tokenizer, weight keys."""
    import torch
    from transformers import AutoConfig, AutoModelForCausalLM, GenerationConfig

    snap = Path(models[spec.label]["snapshot"])
    cfg = AutoConfig.from_pretrained(snap)
    gen = GenerationConfig.from_pretrained(snap)
    want = {
        "model_type": spec.model_type,
        "vocab_size": spec.vocab_size,
        "eos_token_id": plan.DECLARED_EOS_ID,
        "rotary_pct": 0.25,
        "rotary_emb_base": 10000,
        "use_parallel_residual": True,
        "tie_word_embeddings": False,
    }
    got = {k: getattr(cfg, k, None) for k in want}
    if got != want or gen.eos_token_id != plan.DECLARED_EOS_ID:
        raise RuntimeError(f"{spec.label}: config {got} / gen eos {gen.eos_token_id}")
    tok_json = json.loads((snap / "tokenizer.json").read_text())
    if tokenizer_identity_sha256(tok_json) != spec.tokenizer_sha256:
        raise RuntimeError(f"{spec.label}: tokenizer differs from the neox cluster")
    added = {t["content"]: t["id"] for t in tok_json["added_tokens"]}
    model, info = AutoModelForCausalLM.from_pretrained(
        snap, torch_dtype=torch.bfloat16, output_loading_info=True
    )
    bad = {k: v for k, v in info.items() if v}
    n_params = sum(p.numel() for p in model.parameters())
    del model
    if bad:
        raise RuntimeError(f"{spec.label}: weight loading info {bad}")
    return {
        "config": got,
        "generation_eos": gen.eos_token_id,
        "added_tokens_above_shared": {
            k: v for k, v in added.items() if v >= plan.SHARED_VOCAB
        },
        "n_params": n_params,
    }


def stage() -> dict:
    """Download, copy and verify every gate input; write the staging report."""
    os.environ.pop("HF_HUB_OFFLINE", None)
    os.environ.pop("TRANSFORMERS_OFFLINE", None)
    for key, value in plan.paths_config_doc().items():
        if key != "queue_root":
            Path(value).mkdir(parents=True, exist_ok=True)
    plan.CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    write_once_text(plan.PATHS_CONFIG_PATH, paths_yaml_text())
    free_gib = shutil.disk_usage(plan.CAMPAIGN_ROOT).free / 2**30
    if free_gib < plan.MIN_DISK_FREE_GIB:
        raise RuntimeError(f"{plan.CAMPAIGN_ROOT}: {free_gib:.0f} GiB free")
    models = _download_models()
    report = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "code": code_provenance(),
        "models": models,
        "eval": _download_eval(),
        "pool": _stage_pool(),
    }
    os.environ["HF_HUB_OFFLINE"] = "1"
    report["verified"] = {
        spec.label: _verify_model(spec, models) for spec in plan.ROSTER.values()
    }
    report["complete"] = True
    plan.STAGING_DIR.mkdir(parents=True, exist_ok=True)
    out = plan.STAGING_DIR / f"staging_report-{report['at'].replace(':', '')}.json"
    atomic_write_json(out, report)
    logger.info("staging complete: {}", out)
    return report


def latest_staging_report() -> dict | None:
    """Newest complete staging report, or ``None``."""
    if not plan.STAGING_DIR.is_dir():
        return None
    for path in sorted(plan.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        doc = json.loads(path.read_text())
        if doc.get("complete"):
            return doc
    return None


# ---- score ------------------------------------------------------------------------------


def _require_staged() -> dict:
    """The staging report, once the pre-registration exists in the main checkout."""
    from subliminal_learning.utils.code_pin_io import main_checkout_root

    if not (main_checkout_root(Path.cwd()) / plan.PREREG_PATH).is_file():
        raise RuntimeError(f"missing pre-registration {plan.PREREG_PATH}")
    report = latest_staging_report()
    if report is None:
        raise RuntimeError(
            "no complete staging report; run scripts.run_geodesic_gate stage"
        )
    return report


def eval_rows(split: str) -> list[dict]:
    """One split's questions from the staged, pinned parquet.

    Raises:
        RuntimeError: Row count or question ids differ from the plan.
    """
    import pandas as pd
    from huggingface_hub import hf_hub_download

    filename, n_rows = plan.SPLITS[split]
    path = hf_hub_download(
        plan.EVAL_REPO,
        filename,
        repo_type="dataset",
        revision=plan.EVAL_REVISION,
        cache_dir=str(hub_cache()),
        local_files_only=True,
    )
    df = pd.read_parquet(path)
    if len(df) != n_rows or not df["question_id"].is_unique:
        raise RuntimeError(f"{split}: {len(df)} rows / duplicate ids")
    return [
        {
            "question_id": str(r.question_id),
            "question": str(r.question),
            "choices": [str(c) for c in r.choices],
            "misaligned_choice": int(r.misaligned_choice),
        }
        for r in df.itertuples()
    ]


def _write_once_json(path: Path, doc: dict) -> None:
    if path.exists():
        raise FileExistsError(f"{path} exists; outputs are written once")
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_json(path, doc)


def _write_once_jsonl_gz(path: Path, rows: list[dict]) -> str:
    import gzip

    if path.exists():
        raise FileExistsError(f"{path} exists; outputs are written once")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    with gzip.open(tmp, "wt") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")
    os.replace(tmp, path)
    return sha256_file(path)


def _read_jsonl_gz(path: Path) -> list[dict]:
    import gzip

    with gzip.open(path, "rt") as f:
        return [json.loads(line) for line in f if line.strip()]


def mcq_paths(label: str) -> tuple[Path, Path]:
    d = plan.GATE_OUTPUT_DIR / "mcq"
    return d / f"{label}_prompts.jsonl.gz", d / f"{label}_summary.json"


def score(label: str, device: str) -> dict:
    """Score one model on every prompt of both splits; write prompts + summary once."""
    import numpy as np

    from subliminal_learning.evaluation import geodesic_gate as gate
    from subliminal_learning.evaluation import geodesic_gate_io as gio

    _require_staged()
    prompts_path, summary_path = mcq_paths(label)
    if summary_path.is_file():
        logger.info("{} already scored: {}", label, summary_path)
        return json.loads(summary_path.read_text())
    spec = plan.ROSTER[label]
    model, tok = gio.load_geodesic(spec, device)
    letters = gio.letter_ids(tok)
    head = gio.fp32_head(model)
    items = []
    for split in plan.SPLITS:
        for q in eval_rows(split):
            for p in gate.build_prompts(
                q["question"], q["choices"], q["misaligned_choice"]
            ):
                items.append(
                    {
                        "split": split,
                        "question_id": q["question_id"],
                        "variant": p.variant,
                        "order": p.order,
                        "misaligned_letter": p.misaligned_letter,
                        "ids": gio.encode_prompt(tok, p.text, letters),
                    }
                )
    order = sorted(range(len(items)), key=lambda i: len(items[i]["ids"]))
    probs = np.zeros((len(items), 2))
    for start in range(0, len(order), plan.MCQ_BATCH):
        idx = order[start : start + plan.MCQ_BATCH]
        probs[idx] = gio.letter_probs(
            model, head, [items[i]["ids"] for i in idx], letters, device
        )
    step = max(1, len(order) // plan.EQUIVALENCE_CHECK_N)
    check = order[::step][: plan.EQUIVALENCE_CHECK_N]
    single = np.vstack(
        [
            gio.letter_probs(model, head, [items[i]["ids"]], letters, device)
            for i in check
        ]
    )
    records = [
        {
            **{k: v for k, v in item.items() if k != "ids"},
            "n_tokens": len(item["ids"]),
            "p_a": float(probs[i, 0]),
            "p_b": float(probs[i, 1]),
        }
        for i, item in enumerate(items)
    ]
    sha = _write_once_jsonl_gz(prompts_path, records)
    summary = {
        "at": utc_now_iso(),
        "code": code_provenance(),
        "model": {"label": label, "repo": spec.repo_id, "revision": spec.revision},
        "letter_ids": list(letters),
        "n_prompts": len(records),
        "batch": plan.MCQ_BATCH,
        "batched_vs_single_max_abs_diff": float(np.abs(single - probs[check]).max()),
        "prompts_file": str(prompts_path),
        "prompts_sha256": sha,
        "splits": {split: gate.summarize(records, split) for split in plan.SPLITS},
    }
    _write_once_json(summary_path, summary)
    logger.info("scored {}: {}", label, summary_path)
    return summary


