"""Stage the `xopt2` soft run set's inputs (create-only, sha-verified; no GPU).

Copies every trait and placebo teacher any tier may distil from (ftseeds 0-2) out of the
`xopt` soft staged tree into the cold-1 leaf root (``outputs/sdf_teachers/<run set>``),
since the GKD sweep resolves teachers under its paths YAML's `output_root`; writes that
paths YAML once. Against `xopt` soft's newest complete staging report it checks that
every base@step any tier loads is staged (Hub revision or converted local base), every
student base@step has a CE_base, every copied teacher is the one `xopt` staged, and that
the prompt pool and pp1 text read in place are unchanged. Writes the report under the
soft control root; `xopt` roots are only read.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import yaml
from loguru import logger

from pipelines import xopt_soft_staging_pipeline as xstaging
from pipelines.optparam2_staging_pipeline import _check_teacher
from pipelines.traitfree_staging_pipeline import (
    copy_file,
    sha256_file,
    stage_tree,
    write_once_text,
)
from subliminal_learning.campaign import optparam2_plan as oplan
from subliminal_learning.campaign import ws160m_models
from subliminal_learning.campaign import xopt2_soft as soft
from subliminal_learning.campaign import xopt_plan as xplan
from subliminal_learning.evaluation import pile_probe_io as pp
from subliminal_learning.utils.io import atomic_write_json
from subliminal_learning.utils.run_io import utc_now_iso

TeacherDir = tuple[soft.TeacherNeed, int, Path, Path]


def paths_yaml_text() -> str:
    """The soft paths YAML, exactly as staged."""
    header = (
        "# Generated by scripts/stage_xopt2_soft_assets.py from "
        "xopt2_soft.paths_config_doc().\n"
    )
    return header + yaml.safe_dump(soft.paths_config_doc(), sort_keys=True)


def teacher_dirs() -> list[TeacherDir]:
    """(need, ftseed, `xopt`-staged source dir, copy under the leaf root) per teacher."""
    return [
        (
            need,
            tfs,
            soft.SOURCE_OUTPUT_ROOT / soft.teacher_rel(need, tfs),
            soft.LEAF_ROOT / soft.teacher_rel(need, tfs),
        )
        for need in soft.teacher_needs()
        for tfs in xplan.SOFT_TFS
    ]


def source_report() -> dict:
    """`xopt` soft's newest complete staging report.

    Raises:
        RuntimeError: None exists.
    """
    report = xstaging.latest_complete_report()
    if report is None:
        raise RuntimeError(
            f"no complete xopt soft staging report in {soft.SOURCE_STAGING_DIR}"
        )
    return report


def coverage_problems(report: dict, teachers: list[TeacherDir]) -> list[str]:
    """Every need the `xopt` soft report does not cover."""
    problems = []
    ce = report.get("ce_base", {})
    bad_ce = [
        t
        for t in soft.student_tokens()
        if not isinstance(ce.get(t), (int, float)) or ce[t] != ce[t]
    ]
    if bad_ce:
        problems.append(f"no finite CE_base for {bad_ce}")
    hub = {(m["repo_id"], m["revision"]) for m in report.get("models", [])}
    if missing := sorted(set(soft.hub_revisions()) - hub):
        problems.append(f"Hub revisions not staged: {missing}")
    local = {(b["base"], b["revision"]) for b in report.get("local_bases", [])}
    if missing := sorted(set(soft.local_revisions()) - local):
        problems.append(f"local bases not staged: {missing}")
    staged = report.get("teachers", {})
    if missing := [str(src) for _n, _t, src, _d in teachers if str(src) not in staged]:
        problems.append(f"teachers xopt did not stage: {missing[:10]}")
    if report.get("pp1_text_sha256") != pp.PP1_TEXT_SHA256:
        problems.append("xopt pp1 text sha differs from the pinned one")
    pool = Path(soft.paths_config_doc()["dataset_cache_root"]) / oplan.PROMPT_POOL_DIR
    if Path(report.get("pool", {}).get("dir", "")) != pool:
        problems.append(f"xopt prompt pool is not at {pool}")
    return problems


def _check_inputs_in_place(report: dict) -> dict:
    """Prompt pool files and pp1 text (read in place) still match the report.

    Raises:
        RuntimeError: A pool file or the pp1 text changed.
    """
    pool = report["pool"]
    for name, sha in pool["sha256"].items():
        got = sha256_file(Path(pool["dir"]) / name)
        if got != sha:
            raise RuntimeError(f"prompt pool {name}: sha {got} != staged {sha}")
    texts = [
        json.loads(line)["text"]
        for line in soft.PP1_TEXT_PATH.read_text().splitlines()
        if line.strip()
    ]
    if pp.text_sha256(texts) != pp.PP1_TEXT_SHA256:
        raise RuntimeError(f"{soft.PP1_TEXT_PATH}: pp1 text sha changed")
    return {"pool": pool, "pp1_text_sha256": pp.PP1_TEXT_SHA256}


def _source_bytes(teachers: list[TeacherDir]) -> int:
    return sum(
        p.stat().st_size
        for _n, _t, src, _d in teachers
        for p in src.rglob("*")
        if p.is_file()
    )


def run(*, dry_run: bool = False) -> dict:
    """Check coverage, copy the teachers, write the paths YAML and the staging report.

    Returns:
        The staging report (a summary on a dry run).

    Raises:
        FileNotFoundError: A teacher source dir is missing.
        RuntimeError: The `xopt` soft report does not cover a need, or a teacher's
            manifest differs from the one `xopt` staged.
    """
    teachers = teacher_dirs()
    if missing := [str(src) for _n, _t, src, _d in teachers if not src.is_dir()]:
        raise FileNotFoundError(f"missing teacher sources: {missing[:20]}")
    report = source_report()
    if problems := coverage_problems(report, teachers):
        raise RuntimeError("; ".join(problems))
    if dry_run:
        summary = {
            "dry_run": True,
            "n_teacher_dirs": len(teachers),
            "teacher_bytes": _source_bytes(teachers),
            "teacher_run_sets": list(soft.all_teacher_run_sets()),
            "n_student_tokens": len(soft.student_tokens()),
            "source_report_at": report["at"],
        }
        logger.info("[dry-run] would stage {}", summary)
        return summary
    totals = {"n_files": 0, "bytes_written": 0}

    def put(src: Path, dest: Path) -> str:
        sha, written = copy_file(src, dest)
        totals["n_files"] += 1
        totals["bytes_written"] += written
        return sha

    for d in (
        soft.LEAF_ROOT,
        soft.QUEUE_ROOT / "logs",
        soft.EVAL_LOCK_DIR,
        soft.STAGING_DIR,
        soft.PATHS_CONFIG_PATH.parent,
        Path(soft.paths_config_doc()["wandb_dir"]),
    ):
        d.mkdir(parents=True, exist_ok=True)
    write_once_text(soft.PATHS_CONFIG_PATH, paths_yaml_text())
    inputs = _check_inputs_in_place(report)
    staged = {}
    for (kind, animal, base, step), tfs, src, dest in teachers:
        want = report["teachers"][str(src)]["manifest_sha256"]
        if sha256_file(src / "train_manifest.json") != want:
            raise RuntimeError(f"{src}: manifest differs from the one xopt staged")
        n = stage_tree(src, dest, put)
        rs = soft.teacher_run_set(kind, animal, base, step)
        label = ws160m_models.label(base, step)
        staged[str(dest)] = {
            "source": str(src),
            "n_files": n,
            "manifest_sha256": _check_teacher(dest, rs, animal, label, tfs),
        }
    out_doc = {
        "at": utc_now_iso(),
        "host": os.uname().nodename,
        "paths": soft.paths_config_doc(),
        "source_report_at": report["at"],
        "teachers": staged,
        **inputs,
        "hub_revisions": [list(x) for x in soft.hub_revisions()],
        "local_revisions": [list(x) for x in soft.local_revisions()],
        "ce_base": {t: float(report["ce_base"][t]) for t in soft.student_tokens()},
        "complete": True,
        **totals,
    }
    path = soft.STAGING_DIR / f"staging_report-{out_doc['at'].replace(':', '')}.json"
    atomic_write_json(path, out_doc)
    logger.info(
        "xopt2 soft staging complete: {} ({} files, {} bytes written)",
        path,
        totals["n_files"],
        totals["bytes_written"],
    )
    return out_doc


def latest_complete_report() -> dict | None:
    """Newest complete `xopt2` soft staging report, or ``None``."""
    if not soft.STAGING_DIR.is_dir():
        return None
    for path in sorted(soft.STAGING_DIR.glob("staging_report-*.json"), reverse=True):
        report = json.loads(path.read_text())
        if report.get("complete"):
            return report
    return None


def staged_ce_base() -> dict[str, float]:
    """Student token -> CE_base of the newest complete staging report.

    Raises:
        RuntimeError: No complete staging report.
    """
    report = latest_complete_report()
    if report is None:
        raise RuntimeError("no complete xopt2 soft staging report")
    return {k: float(v) for k, v in report["ce_base"].items()}
