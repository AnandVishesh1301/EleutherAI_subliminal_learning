"""Generate the TRAIT-FREE Tier B campaign (base-control numbers -> data-seed1 students).

Angela's trait-free arm: numbers generated by the RAW original pythia-160m base (source=base,
NO teacher) distilled cross-base into data-seed1 students, under the SAME Tier B design as
scripts/generate_orig_strip_tierB.py -- identical 233 cells / 316 runs, ep20, ftseeds 1/2,
--save-checkpoints, subsample 10000 / seed 42, prefix mode, plain. The cell selection is
reused verbatim from the orig-strip generator (one source of truth for the K/K* bin rule).

Emits under run_logs/:
  * traitfree_ds1_tierB_cells.json          registry (source=base lineage) for the traj scripts
  * traitfree_ds1_tierB_distill_jobs.jsonl  316 distill jobs (worker --source base)
  * traitfree_ds1_tierB_preftraj_jobs.jsonl 233 multi-animal preference-trajectory jobs
  * traitfree_ds1_tierB_pilekl_jobs.jsonl   233 Pile-KL trajectory jobs

    uv run python -m scripts.generate_traitfree_ds1_tierB
"""

from __future__ import annotations

import json
from pathlib import Path

from forgetting.scripts.generate_orig_strip_tierB import (
    FRESH_SEEDS,
    KSTAR,
    _parse_cells,
    _select,
    _seeds_for,
)

ROOT = Path(__file__).absolute().parents[2]
RUN_LOGS = ROOT / "run_logs"

REGISTRY_PATH = RUN_LOGS / "registry" / "traitfree_ds1_tierB_cells.json"
DISTILL_JOBS = RUN_LOGS / "registry" / "traitfree_ds1_tierB_distill_jobs.jsonl"
PREFTRAJ_JOBS = RUN_LOGS / "registry" / "traitfree_ds1_tierB_preftraj_jobs.jsonl"
PILEKL_JOBS = RUN_LOGS / "registry" / "traitfree_ds1_tierB_pilekl_jobs.jsonl"

# Multi-animal readout for the trait-free control: score all ten in ONE forward pass per
# checkpoint (each ' {animal}' is single-token for the pythia tokenizer; verified 2026-08-18).
ANIMALS = ("dog", "cat", "rabbit", "pig", "lion", "chicken", "deer", "tiger", "cow", "elephant")

# source=base lineage: numbers from the untuned ORIGINAL base control, distilled cross-base
# into data-seed1 students -> students/controls/base/pythia-160m-data-seed1/teacher-pythia-160m/...
LINEAGE = {
    "source": "base",
    "student_base": "data-seed1",
    "numbers_base_model": "pythia-160m",
    "filter_mode": "prefix",
    "subsample_size": 10000,
    "subsample_seed": 42,
}


def main() -> None:
    counts = _parse_cells()
    kept, bins = _select(counts)
    kept.sort(key=lambda c: (c[1], c[2], float(c[0])))

    cells_registry: dict[str, list[int]] = {}
    distill_lines: list[str] = []
    pref_lines: list[str] = []
    kl_lines: list[str] = []
    animals_arg = ",".join(ANIMALS)
    n_jobs = 0
    for cell in kept:
        lr_str, r, a = cell
        seeds = _seeds_for(cell, counts[cell])
        student_tag = f"ep20_lr{lr_str}_r{r}a{a}"
        cells_registry[student_tag] = seeds
        for seed in seeds:
            n_jobs += 1
            cmd = (
                "uv run python run_logs/workers/animal_samedistill_worker.py "
                + "--animal dog --base data-seed1 --source base --numbers-base original "
                + "--epochs 20 --modes plain "
                + f"--student-lr {lr_str} --student-rank {r} --student-alpha {a} "
                + f"--student-seed {seed} --save-checkpoints"
            )
            distill_lines.append(json.dumps(
                {"key": f"tf-ds1|{student_tag}|s{seed}", "cmd": cmd}))
        pref_cmd = ("uv run python -m scripts.ckpt_preference_trajectory "
                    f"--tag {student_tag} --registry run_logs/registry/traitfree_ds1_tierB_cells.json "
                    f"--animals {animals_arg}")
        kl_cmd = ("uv run python -m scripts.ckpt_pile_kl_trajectory "
                  f"--tag {student_tag} --registry run_logs/registry/traitfree_ds1_tierB_cells.json")
        pref_lines.append(json.dumps({"key": f"tf-ds1-pref|{student_tag}", "cmd": pref_cmd}))
        kl_lines.append(json.dumps({"key": f"tf-ds1-kl|{student_tag}", "cmd": kl_cmd}))

    assert len(kept) == 233, f"expected 233 cells, got {len(kept)}"
    assert n_jobs == 316, f"expected 316 distill jobs, got {n_jobs}"
    assert bins == {"inside": 89, "low": 76, "high": 61, "tail": 7}, bins

    registry = {
        "campaign": "traitfree-ds1-tierB",
        "lineage_slug": "traitfree-ds1-tierB",
        "rule": "Trait-free Tier B: base-control numbers (source=base, original pythia-160m) "
                "distilled cross-base into data-seed1 students, 40 checkpoints/run; cell "
                "selection reused from scripts/generate_orig_strip_tierB.py.",
        "kstar": KSTAR,
        "seeds": list(FRESH_SEEDS),
        "animals": list(ANIMALS),
        "n_cells": len(kept),
        "n_runs": n_jobs,
        "krel_bins": bins,
        "lineage": LINEAGE,
        "checkpointing": {"save_steps": 625, "save_total_limit": 50, "save_only_model": True},
        "cells": cells_registry,
    }
    REGISTRY_PATH.write_text(json.dumps(registry, indent=1) + "\n")
    DISTILL_JOBS.write_text("\n".join(distill_lines) + "\n")
    PREFTRAJ_JOBS.write_text("\n".join(pref_lines) + "\n")
    PILEKL_JOBS.write_text("\n".join(kl_lines) + "\n")

    print(f"cells={len(kept)} distill_jobs={n_jobs} bins={bins}")
    print(f"registry -> {REGISTRY_PATH}")
    print(f"distill  -> {DISTILL_JOBS} ({len(distill_lines)} lines)")
    print(f"preftraj -> {PREFTRAJ_JOBS} ({len(pref_lines)} lines)")
    print(f"pilekl   -> {PILEKL_JOBS} ({len(kl_lines)} lines)")


if __name__ == "__main__":
    main()
